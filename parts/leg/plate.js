// 増加装甲（すね、骨 shin）：厚い塊のすね（parts/leg/mass.js の SHINB）の前と左右を包む脚甲。ひざ当ての下（y −0.275）から足首の上
// （y −0.71：足首の受けと足が回る所の上）まで。後ろ（ふくらはぎ）は開いていて、もとのすねが出る。中心を外へ寄せてあり、内（股の側）へは
// 1 cm しか太らない。原点はひざの中心 K、+x 側の 1 個（反対側は鏡像で置く）。すねと一緒に伸び縮みする（bodyparts.js fitItem）。
// 作りの決まりは parts/upper/plate.js と同じ（貼った板にしない・面は垂直にしない・留め具は付けない）。寸法は [独自]。
import { MAIN, DARK } from '../../xsasm-lib.js';
import { hull, grille } from '../upper/kit.js';

const SH = { bone: 'shin', pivot: 'none' };
const EX = '#93a0ae';   // 追加の色 1（xs-editor/paint.js ROLE_COLOR.ex1）：増加装甲の色。機体の文書の paint.pal.ex1 で決まり、ゲームの機体ごとの塗り替えを受けない
const shell = (name, secs, o = {}) => ({ name, kind: 'loft', secs, color: EX, pos: [0, 0, 0], ...SH, ...o });
const sec = (y, x, pts) => ({ y, x, pts });
// 断面の角：前の中央・前の端・前の角・横・（奥：すねの殻の中）
const GREAVE = [
  sec(-0.275, 0.07, [[0, 0.135], [0.07, 0.13], [0.142, 0.085], [0.158, -0.02], [0.13, -0.06], [0, -0.06]]),     // 上の縁（すねの殻の上の端のすぐ下）
  sec(-0.33, 0.094, [[0, 0.165], [0.092, 0.158], [0.176, 0.1], [0.192, -0.03], [0.16, -0.085], [0, -0.085]]),
  sec(-0.46, 0.096, [[0, 0.172], [0.095, 0.165], [0.18, 0.105], [0.196, -0.04], [0.165, -0.1], [0, -0.1]]),    // いちばん太い（ふくらはぎの高さ）
  sec(-0.64, 0.09, [[0, 0.16], [0.082, 0.153], [0.16, 0.095], [0.174, -0.035], [0.145, -0.085], [0, -0.085]]),
  sec(-0.71, 0.086, [[0, 0.135], [0.07, 0.13], [0.142, 0.08], [0.152, -0.03], [0.125, -0.07], [0, -0.07]]),    // 下の縁（足首の上）
];
/** 前の稜：脚甲の前の面より 1.2 cm 前、上から下へ細る */
const ridge = () => hull('脚甲の前の稜', [1, -1].flatMap(s => [[0.094 + s * 0.04, -0.3, 0.166], [0.094 + s * 0.04, -0.46, 0.186], [0.094 + s * 0.052, -0.3, 0.14], [0.094 + s * 0.052, -0.46, 0.16],
  [0.09 + s * 0.03, -0.68, 0.158], [0.09 + s * 0.04, -0.68, 0.135]]), { color: MAIN, ...SH });
/** 外の面の通気口：ふくらはぎの推進器の吸気。面は脚甲の外の面（下へ内へ寄る）に沿う */
const vent = () => grille('脚甲の通気口', [0.288, -0.43, 0.025], [0, 0, -1], [0.1, 1, 0], 0.085, 0.11, { dep: 0.016, slats: 4 }).map(pc => ({ ...pc, ...SH }));

export default [
  { id: 'shinplate', name: '増加装甲（すねの脚甲・前の稜と通気口）', cat: 'すねの増加装甲', size: [0.4, 0.44, 0.28], pieces: [shell('脚甲の殻', GREAVE), ridge(), ...vent()] },
];
