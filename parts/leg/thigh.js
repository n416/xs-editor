// 太もも（脚の骨 leg）。原点はひざの中心 K、股関節の軸は y +0.46。中身は y 0.1 より上（その下はひざの関節が入る）。
// ひざの横は、内の層の角ばった板（parts/leg/kit.js の thighTabs）で、その外をすねの横の装甲が上がって覆う。どの太ももも同じ。
// 約束（骨格図 xsbody.js と、腰の部品を測った値。下の寸法は置くときに横 1.25 倍・外へ 0.0525。parts/leg/kit.js）：
//   ・幅は ±0.11（置いて 内 −0.085 〜 外 0.19）。上の端（y 0.25 より上）は 外が T（0.026）まで（置いて股関節の軸の ±0.085 の中。その外に脚の台がある）。
//     外へ太くなるのは y 0.2 より下
//   ・前の面：y 0.2 より上は股関節の軸から 0.105 まで、y 0.17 より下は 0.13 まで。片膝で太ももを 92° 上げると、前の面が前スカートの蝶番の
//     すぐ下へ来る（蝶番は股関節の 0.145 上・0.195〜0.22 前。これより出ると、スカートが開ききっても当たる）。後ろは −0.11 まで
//   ・ひざ裏の逃げ：下（y YR より下）の後ろ半分は、細いフレーム（|x| 0.068）だけにする。ひざを深く曲げると、すねの横の装甲（|x| 0.074 より外）が
//     このフレームの左右に入る（body がそう分ける）
// 広い面は垂直にも水平にもしない（上下で太さを変える・丸める）。
import { hull, piston } from '../limb/kit.js';
import { LEG, KX, thighTabs, wide, oc, sq, stack, half, TOP_XO as T } from './kit.js';
import { DARK, BLACK, MAIN, ACCENT } from '../../xsasm-lib.js';

const X = 0.11, YR = 0.2, FW = 0.068;
const TH = (id, name, size, pieces) => ({ id, name, cat: '太もも', size: [size[0] * KX, size[1], size[2]], pieces: [...pieces, ...thighTabs()].map(pc => ({ ...LEG, ...wide(pc) })) });
/** 切り口の前後の位置（下で後ろ寄り、上で前寄り：切り口の面も傾ける） */
const cut = y => -0.025 + (y - 0.1) * 0.14;
/** 太ももの中身：輪の並び（下から上）を、下（YR より下）は前半分の塊と後ろの細いフレームに、上はそのままの塊にする */
function body(name, rings, o = {}, frame = { color: DARK }) {
  const yOf = r => r[0][1], low = rings.filter(r => yOf(r) <= YR + 1e-6), up = rings.filter(r => yOf(r) >= YR - 1e-6);
  const front = low.map(r => r.map(([x, y, z]) => [x, y, Math.max(z, cut(y))]));
  const rear = low.map(r => r.map(([x, y, z]) => [Math.max(-FW, Math.min(FW, x)), y, Math.min(z, cut(y) + 0.004)]));
  return [...stack(name, front, o), ...stack(`${name}のひざ裏のフレーム`, rear, frame), ...(up.length > 1 ? stack(`${name}の上`, up, o) : [])];
}
/** 前の面の横の溝（黒）：高さ y、前の面 z、半幅 w */
const frontSlit = (name, y, z, w, dz = 0.0) => hull(name, [[-w, y - 0.009, z - 0.006], [w, y - 0.009, z - 0.006], [-w, y + 0.009, z - 0.006 + dz], [w, y + 0.009, z - 0.006 + dz],
  [-w + 0.004, y - 0.007, z + 0.004], [w - 0.004, y - 0.007, z + 0.004], [-w + 0.004, y + 0.007, z + 0.004 + dz], [w - 0.004, y + 0.007, z + 0.004 + dz]], { color: BLACK });
/** 輪の並び（下から上）：y 0.1〜0.2 が太い所、y 0.25 より上は細い（スカートの中） */
// 前の外の角は大きく落とす（c 0.05）：外で後ろへ曲がる前スカート（左右が合わさる形）は、開くと外の端が 2.8 cm 沈むので、角が高いと当たる
const RINGS = (f, c = [0.035, 0.05, 0.05, 0.03, 0.022]) => [f(0.1, -X + 0.01, X - 0.01, -0.07, 0.112, c[0]), f(0.15, -X + 0.002, X - 0.002, -0.098, 0.11, c[1]), f(0.2, -X, X, -0.106, 0.103, c[2]),
  f(0.25, -X, T, -0.102, 0.1, c[3]), f(0.45, -X + 0.004, T - 0.003, -0.085, 0.094, c[4])];
const round = (y, xi, xo, zb, zf) => sq(y, xi, xo, zb, zf, 2.4);
/** 前の装甲の輪の並び（暗いフレームの前にかぶせる）。zs は切り口 */
const ARMOR = zs => [half(0.105, -X + 0.01, X - 0.01, 0.112, zs + 0.026, 0.035), half(0.15, -X + 0.002, X - 0.002, 0.111, zs + 0.018, 0.05), half(0.2, -X, X, 0.104, zs + 0.01, 0.05), half(0.255, -X, T, 0.101, zs, 0.03), half(0.43, -X + 0.004, T - 0.002, 0.095, zs - 0.006, 0.02)];

