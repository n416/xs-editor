// 厚い塊の脚（太ももは骨 leg、すねは骨 shin）：輪を重ねた小さな塊と貼った板をやめ、1 つの多面体にする。上半身の厚い殻（parts/upper/mass.js）と組む。
// 原点はひざの中心 K。殻は「角のある断面をつなぐ形」（partgeo.js の loft の pts）。殻の数字は置いた後の寸法で書く（今までの部品は ±0.11 で書いて
// 置くときに横 1.25 倍・外へ 0.0525 ずらす。殻はその道具 wide を通さない）：ひざの中心から 内 −0.085 〜 外 0.19。
// 前に決まった約束は変えない（parts/leg/kit.js・thigh.js・shin.js の先頭）：
//   太もも：中身は y 0.1 より上。y 0.25 より上は股関節の軸の ±0.085 の中（その外は脚の台）。前の面は y 0.2 より上で 0.105 まで・y 0.17 より下で 0.13 まで、後ろは −0.11 まで。
//           y 0.2 より下の後ろ半分は細いフレームだけ（ひざを深く曲げると、すねの横の装甲がその左右に入る）。ひざの横は太ももの下の板（thighTabs）
//   すね：中身（全幅）は y −0.24 より下。その上の真ん中は節とひざ当ての場所。横は、すねの壁がひざの横まで上がった横の装甲で関節を覆う。
//         前の面は y −0.43 より上で 0.118 まで。足首の装甲は y −0.8 より上。節・後ろの立ち上がり・足首は今までと同じ物
// 役目：すねは太ももより太く、ふくらはぎがいちばん太い（推進器と脚を動かす機械が入る）。横の装甲は貼った板ではなく、すねの壁がそのまま上がった形
//（外の面の出と前後の縁を、すねの殻の上の端に合わせる）。寸法は [独自]
import { LEG, SHIN, FOOT, ANKLE_Y, thighTabs, shinPlates, link, wide, shells, curve, kneecap, KX, DX } from './kit.js';
import { cylX } from '../limb/kit.js';
import { ellipsoid, piece, planesFromPoints, DARK, MAIN } from '../../xsasm-lib.js';
import { ANKLE_RANGE } from '../../doublejoint.js';

const shell = (name, secs, o = {}) => ({ name, kind: 'loft', secs, color: MAIN, pos: [0, 0, 0], ...o });
const cut = y => -0.025 + (y - 0.1) * 0.14;   // 太ももの下の、前の塊と後ろのフレームの境（thigh.js と同じ）
const FW = 0.085;                             // ひざ裏のフレームの半分の幅（置いた後。今までの 0.068 × 1.25）
/** 太ももの下（y 0.2 より下）：前は全幅、後ろは細いフレーム。上から見て T 字 */
const low = (y, w, zf, zb) => ({ y, x: DX, pts: [[0, zf], [w - 0.04, zf], [w, zf - 0.04], [w, cut(y)], [FW, cut(y) - 0.004], [FW, zb], [0, zb]] });
/** 太ももの上：全幅の塊。cx は中心（y 0.25 より上は股関節の軸の真下 = 0） */
const up = (y, cx, w, zf, zb) => ({ y, x: cx, pts: [[0, zf], [w - 0.035, zf], [w, zf - 0.035], [w, cut(0.2)], [w, cut(0.2) - 0.004], [w - 0.035, zb], [0, zb]] });
const THIGH = [
  low(0.1, 0.13, 0.125, -0.1), low(0.17, 0.1375, 0.13, -0.105), low(0.2, 0.1375, 0.105, -0.108),
  up(0.205, DX, 0.1375, 0.105, -0.11), up(0.25, 0, 0.085, 0.105, -0.11), up(0.4, 0, 0.085, 0.1, -0.105), up(0.47, 0, 0.075, 0.08, -0.085),
];
// すねの殻：角は 前の中央・前の端・前の角・横の後ろ・後ろの角・後ろの中央
const sh = (y, cx, pts) => ({ y, x: cx, pts });
// ひざの下で外へ張り出す（内の面は股関節の軸から 0.085 のまま、外はふくらはぎで 0.245）：上半身の太さに脚の太さを合わせる
/** すねの殻の下の端（y −0.8）の断面。足首の受けの二股の板は、この横の面（前の角 [0.118, 0.058]〜後ろの角 [0.13, −0.055]）がそのまま下りた物。
 *  y −0.74 からこの端までは、横の面を板と同じ傾き（YOKE_LEAN）で下ろす（前は 0.105、後ろは −0.13） */
const ANKLE_TOP = [[0, 0.105], [0.06, 0.1], [0.118, 0.058], [0.13, -0.055], [0.085, -0.12], [0, -0.13]];
const YOKE_LEAN = 0.05;   // 板の面の傾き：下へ 1 進むと内へ 0.05（垂直にしない）
export const SHINB = [
  sh(-0.8, DX, ANKLE_TOP),                                                                                          // 足首の上（足首の受けがここから下りる）
  sh(-0.74, DX, ANKLE_TOP.map(([x, z]) => [x && x + YOKE_LEAN * 0.06, z + Math.sign(z) * 0.002])),
  sh(-0.62, 0.075, [[0, 0.12], [0.075, 0.115], [0.133, 0.068], [0.14, -0.075], [0.092, -0.16], [0, -0.17]]),
  sh(-0.36, 0.08, [[0, 0.125], [0.088, 0.12], [0.156, 0.075], [0.165, -0.09], [0.11, -0.215], [0, -0.225]]),      // ふくらはぎ（いちばん太い）
  sh(-0.24, DX, [[0, 0.118], [0.07, 0.115], [0.127, 0.07], [0.135, -0.08], [0.09, -0.19], [0, -0.2]]),            // 中身の上の端（横の装甲と同じ幅）
];
/** 横の装甲：すねの壁がひざの横まで上がる。上の縁（前の上・後ろの上）は今までのすねと同じ形、下はすねの殻の上の端に重ねる。
 *  外の面の出は、殻の横の幅に合わせる（今までの道具は ±0.11 の寸法なので KX で割る） */
const TOPF = [[-0.11, 0.165], [0.03, 0.11], [0.07, 0.06]], TOPB = [[0.06, -0.02], [0.03, -0.07], [-0.03, -0.15], [-0.12, -0.2], [-0.23, -0.225]];
const EX = curve([[0.07, 0.118 / KX], [-0.1, 0.13 / KX], [-0.24, 0.136 / KX], [-0.36, 0.14 / KX]]);
const ears = () => shells('すねの横の装甲', [...TOPF, ...TOPB, [-0.34, -0.215], [-0.34, 0.11], [-0.22, 0.15]], EX);
const ankle = () => ({ ...piece('足首', ellipsoid([0.05, 0.07, 0.07], [0, -0.87, 0], 10, [-50, -15, 15, 50]), { color: DARK }), ankleRange: ANKLE_RANGE });
const riser = () => shinPlates().filter(pc => pc.name.includes('立ち上がり'));
/** すねの殻のほかの物（横の装甲・後ろの立ち上がり・足首・ひざの節）：同じ作りの別のすね（parts/leg/hover.js）でも使う */
export const shinFixtures = () => [...ears(), ...riser(), ankle(), ...link()].map(pc => ({ ...SHIN, ...wide(pc) }));

// ---- 足首の受け（issue #218「関節がおもちゃっぽい」）：すねの殻の下に暗い卵が 1 つあるだけで、すねと足が細い柄でつながって見えた。
// 油圧シリンダーの端の二股（クレビス）・ショベルのアームの先と同じ作りにする：すねの横の壁がそのまま下りた、厚さの決まった平らな板 2 枚（骨 shin）が、
// 足首の軸を中心とした半円の端で終わり、足の側の太い軸受けの筒（骨 foot）を左右から挟む。板の外の面は、すねの殻の下の端の横の面と同じ面
// （ANKLE_TOP の前の角〜後ろの角）で、下へ YOKE_LEAN だけ内へ傾く。膨らませない。軸の端の蓋・ピンは付けない。
// 板の半円（半径 YOKE_R）の中に入る足の部品は、軸受けの筒と足首の台だけで、どちらも板の内の面より内。足の殻・甲とかかとの装甲は軸から
// 0.07 より外なので、足が回っても板に入らない。寸法は [独自] ----
const YOKE_R = 0.056, YOKE_T = 0.024;
/** 板の外の面（DX からの外向き）：y −0.8 で ANKLE_TOP の前の角・後ろの角を通り、下へ傾く */
const yokeOut = (y, z) => 0.1241 - 0.106 * z + YOKE_LEAN * (y + 0.8);
/** 横から見た板の形：すねの中（y −0.78）から下りて、足首の軸を中心とした半円で終わる */
const YOKE_SIDE = [[-0.78, YOKE_R], [-0.78, -YOKE_R], ...Array.from({ length: 13 }, (_, k) => (k * 15 - 90) * Math.PI / 180).map(a => [ANKLE_Y - YOKE_R * Math.cos(a), YOKE_R * Math.sin(a)]).reverse()];
/** 二股の板の片側（s 1 で外、−1 で内）：厚さ YOKE_T の平らな板 */
const yokeCheek = s => {
  const at = (dx, y, z) => [DX + s * dx, y, z];
  return piece(`足首の受け（${s > 0 ? '外' : '内'}）`, planesFromPoints(YOKE_SIDE.flatMap(([y, z]) => [at(yokeOut(y, z), y, z), at(yokeOut(y, z) - YOKE_T, y, z)])), { ...SHIN, ankleRange: ANKLE_RANGE });
};
const ankleYoke = () => [yokeCheek(1), yokeCheek(-1)];

// ---- 足（骨 foot）：足首の横の軸（y −0.87）のまわりに回る。足の裏は y −1.14 で平ら。y −0.93 より上にあるのは、足首の台と、足首の軸から 0.1 以内の
// 甲の装甲・かかとの上の装甲だけ（足が回っても、すねの裾に当たらない）。すねを太くした分、足も広い（半分の幅 0.131 → 0.165）----
const ft = (y, pts) => ({ y, x: DX, pts });
const FOOTB = [
  ft(-1.14, [[0, 0.44], [0.1, 0.42], [0.15, 0.3], [0.158, -0.1], [0.13, -0.23], [0, -0.26]]),          // 足の裏
  ft(-1.08, [[0, 0.46], [0.105, 0.44], [0.158, 0.31], [0.165, -0.1], [0.137, -0.24], [0, -0.27]]),     // いちばん外
  ft(-1.0, [[0, 0.4], [0.09, 0.38], [0.14, 0.27], [0.15, -0.1], [0.12, -0.22], [0, -0.24]]),
  ft(-0.94, [[0, 0.2], [0.07, 0.19], [0.11, 0.14], [0.12, -0.08], [0.095, -0.17], [0, -0.185]]),       // 甲の上の面
];
const SOLEB = [
  ft(-1.14, [[0, 0.45], [0.104, 0.43], [0.156, 0.305], [0.164, -0.1], [0.135, -0.237], [0, -0.267]]),
  ft(-1.105, [[0, 0.462], [0.107, 0.442], [0.161, 0.312], [0.168, -0.1], [0.14, -0.243], [0, -0.273]]),
];
const lr = pts => pts.flatMap(([x, y, z]) => [[DX - x, y, z], [DX + x, y, z]]);
const hullAt = (name, pts, o = {}) => piece(name, planesFromPoints(lr(pts)), o);
/** 足首の軸受け（骨 foot）：足首の軸のまわりの太い筒（ボス）。二股の板の間（DX から ±0.08、板の内の面との間にすき間）。足が回っても形は同じ */
const footHub = () => cylX('足首の軸受け', ANKLE_Y, 0, 0.05, DX - 0.08, DX + 0.08, 24, { color: DARK });
/** 足首の台：軸受けの筒から足の中へ下りる台（上は軸の高さで DX から ±0.07） */
const footCore = () => ({ ...hullAt('足首の台', [[0.07, ANKLE_Y, -0.045], [0.07, ANKLE_Y, 0.045], [0.105, -1.08, -0.15], [0.105, -1.08, 0.14]], { color: DARK }), pivot: 'foot', center: [0, ANKLE_Y, 0] });

export default [
  { id: 'footmass', name: '足（厚い塊）', cat: '足', size: [0.34, 0.27, 0.73],
    pieces: [footCore(), footHub(), shell('足の殻', FOOTB), shell('足の裏の縁', SOLEB, { color: DARK }),
      hullAt('足の甲の装甲', [[0.11, -0.945, 0.33], [0.115, -0.945, 0.02], [0.075, -0.875, 0.088], [0.075, -0.89, 0.03]]),   // つま先の上から足首の前へ上がる塊（足首を隠す）
      hullAt('かかとの上の装甲', [[0.11, -0.945, -0.02], [0.105, -0.945, -0.2], [0.07, -0.885, -0.035], [0.07, -0.89, -0.09]]),
    ].map(pc => ({ ...FOOT, ...pc })) },
  // ひざ当て：ひざの前いっぱいの厚い盾（すねに付く。作りは今までのひざ当てと同じ道具）
  { id: 'kneemass', name: 'ひざ当て（厚い盾）・すねに付く', cat: 'ひざ当て', size: [0.18, 0.3, 0.2],
    pieces: kneecap('ひざ当て', [[0.085, 0.115], [0.05, 0.165], [-0.05, 0.185], [-0.15, 0.165], [-0.2, 0.115]], 0.022, {}, 0.072, 'shin').map(pc => wide({ ...pc, ...SHIN })) },
  { id: 'thighmass', name: '太もも（厚い塊）', cat: '太もも', size: [0.275, 0.37, 0.24],
    pieces: [{ ...LEG, ...shell('太ももの殻', THIGH) }, ...thighTabs().map(pc => ({ ...LEG, ...wide(pc) }))] },
  { id: 'shinmass', name: 'すね（厚い塊）', cat: 'すね', size: [0.28, 0.87, 0.36], ankle: ANKLE_RANGE,
    pieces: [{ ...SHIN, ...shell('すねの殻', SHINB) }, ...[...ears(), ...riser(), ...link()].map(pc => ({ ...SHIN, ...wide(pc) })), ...ankleYoke()] },
];
