// ---- すね（骨 shin） ----
// ひざから上の作り（横の装甲・後ろの立ち上がり・節）と、ふくらはぎより上の殻は厚い塊のすね（mass.js）と同じ。ふくらはぎ（y −0.4）から
// 裾（y −0.88）までは中の空いた装甲板の輪で、その中に足首の暗い筒が下りる。足の甲の装甲は裾の中に入るので、足首が回っても板に届かない
// （裾の内の面は、足首の軸から前 0.22・後ろ 0.3・横 0.19 以上離れている）。数字は置いた後の寸法（ひざの中心から。内が負）
const ID = p => p;
// 釣鐘の 4 つの輪：高さ L と、内 xi・外 xo・後ろ zb・前 zf。下ほど速く開く
const L0 = -0.4, L1 = -0.6, L2 = -0.76, L3 = -0.88;
const B0 = [-0.07, 0.235, -0.215, 0.125], B1 = [-0.1, 0.29, -0.28, 0.18], B2 = [-0.128, 0.37, -0.37, 0.26], B3 = [-0.14, 0.43, -0.44, 0.32];
const lerpB = (a, b, k) => a.map((v, i) => v + (b[i] - v) * k);
const grow = (b, d) => [b[0] - d, b[1] + d, b[2] - d, b[3] + d];
/** 釣鐘の輪：高さ y、内 xi・外 xo、後ろ zb・前 zf（丸みのある四角、14 角）。t だけ内へ */
const bell = (y, [xi, xo, zb, zf], t = 0) => sq(y, xi + t, xo - t, zb + t, zf - t, 2.8, 14);
/** 輪 2 つ（上・下）の間を、角ごとに 1 枚の厚い板にする。t は板の厚み */
const plates = (name, [y0, e0], [y1, e1], t, o = {}) => {
  const a = bell(y0, e0), b = bell(y1, e1), ai = bell(y0, e0, t), bi = bell(y1, e1, t), n = a.length;
  return Array.from({ length: n }, (_, i) => { const j = (i + 1) % n;
    return piece(`${name} ${i + 1}`, planesFromPoints([a[i], a[j], b[i], b[j], ai[i], ai[j], bi[i], bi[j]]), { ...SHIN, ...o }); });
};
const oc2 = (y, x, z, c = 0.03) => oct(y, x, z, c);
const blockAt = (name, rings, o = {}) => piece(name, planesFromPoints(rings.flat()), o);
