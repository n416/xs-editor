// ひざ（中間の節、骨 knee）：2 重関節（xs-editor/doublejoint.js）。原点はひざの中心 K。上の軸 P1（y +0.04）と下の軸 P2（y −0.16）の横の円柱
// （半径 0.055、x ±0.055）を節がつなぐ。軸の間が長い（0.2）のは、正座で折りたたむため（太ももの裏とふくらはぎが重ならない）。
// 太ももが短く見えないよう、節はほとんどすねの上の端の高さにある。
// 節は太ももとすねの、軸を挟む板（x 0.058 より外）の間を通るので、節の物はすべて |x| < 0.056。
// ひざは後ろへ曲がり、節の前（ひざ当て）は外側：曲げると、上の軸のまわりでは前が下へ、下の軸のまわりでは前が上へ回る（太もも・すねから離れる）。
// 真ん中の部品（回転の中心 shin）は、ひざの中心 K を center に持つ。
import { hull, cylX } from '../limb/kit.js';
import { DARK, BLACK, MAIN, ACCENT } from '../../xsasm-lib.js';

const L = { bone: 'knee', pivot: 'none' };
const Y1 = 0.04, Y2 = -0.16, YM = (Y1 + Y2) / 2;
const knuckles = (h = 0.055) => [cylX('ひざの上の軸', Y1, 0, 0.055, -h, h, 16, { color: DARK }), cylX('ひざの下の軸', Y2, 0, 0.055, -h, h, 16, { color: DARK })];
const core = (w = 0.045, d = 0.035, color = BLACK) => ({ ...hull('ひざの節', [-w, w].flatMap(x => [Y1, Y2].flatMap(y => [-d, d].map(z => [x, y, z]))), { color, pivot: 'shin' }), center: [0, 0, 0] });
const K = (id, name, size, pieces) => ({ id, name, cat: 'ひざ', size, pieces: pieces.map(pc => ({ ...L, ...pc, pivot: pc.pivot ?? 'none' })) });
/** ひざ当て：節の前の板。節の真ん中（YM）から y0〜y1、前へ z1 まで、幅 w。真ん中が前へとがる */
const cap = (name, { y0 = -0.11, y1 = 0.12, z1 = 0.09, w = 0.05, tip = 0.012 } = {}, o = {}) => hull(name, [
  [-w, YM + y1, 0.03], [w, YM + y1, 0.03], [-w * 0.8, YM + y1 - 0.015, z1 - 0.02], [w * 0.8, YM + y1 - 0.015, z1 - 0.02], [0, YM + y1 - 0.02, z1],
  [-w, YM, z1 - 0.012], [w, YM, z1 - 0.012], [0, YM + 0.005, z1 + tip],
  [-w * 0.75, YM + y0, z1 - 0.03], [w * 0.75, YM + y0, z1 - 0.03], [-w * 0.75, YM + y0 + 0.01, 0.03], [w * 0.75, YM + y0 + 0.01, 0.03], [0, YM + y0 + 0.004, z1 - 0.016]], o);

export default [
  K('knee', 'ひざ（2 重関節）', [0.11, 0.32, 0.15], [core(), ...knuckles(), cap('ひざ当て', { y0: -0.07, y1: 0.08, z1: 0.07, w: 0.04 })]),
  K('kneeguard', 'ひざ（2 重関節・大きなひざ当て）', [0.11, 0.32, 0.2], [core(), ...knuckles(), cap('ひざ当て', { y0: -0.13, y1: 0.14, z1: 0.11, w: 0.052, tip: 0.02 })]),
  // 外の板：軸を短くし、節の左右の板が 2 本の軸を包む（両端は軸と同じ丸み）
  K('kneeplates', 'ひざ（2 重関節・外の板）', [0.11, 0.32, 0.13], [core(0.04), ...knuckles(0.044),
    ...[1, -1].map(s => hull(`ひざの外の板（${s > 0 ? '外' : '内'}）`, [Y1, Y2].flatMap(y => Array.from({ length: 12 }, (_, k) => k * Math.PI / 6).flatMap(a => [0.044, 0.055].map(x => [s * x, y + 0.055 * Math.sin(a), 0.055 * Math.cos(a)]))))),
    cap('ひざ当て', { y0: -0.06, y1: 0.06, z1: 0.075, w: 0.036 }, { color: DARK })]),
  // とがったひざ当て：前へ長くとがる角
  K('kneespike', 'ひざ（2 重関節・とがったひざ当て）', [0.11, 0.32, 0.24], [core(), ...knuckles(), cap('ひざ当て', { y0: -0.11, y1: 0.12, z1: 0.095, w: 0.05 }),
    hull('ひざ当ての角', [[-0.022, YM + 0.06, 0.09], [0.022, YM + 0.06, 0.09], [-0.022, YM - 0.04, 0.09], [0.022, YM - 0.04, 0.09], [0, YM + 0.04, 0.16], [-0.008, YM, 0.14], [0.008, YM, 0.14]], { color: DARK })]),
  // 太い節：前が丸くふくらむ太い節と、暗い帯
  K('kneethick', 'ひざ（2 重関節・太い節）', [0.11, 0.32, 0.16], [core(0.05, 0.035, DARK), ...knuckles(),
    hull('ひざの節の前', [-0.05, 0.05].flatMap(x => [[x, YM + 0.085, 0.03], [x, YM - 0.085, 0.03], [x * 0.9, YM + 0.06, 0.075], [x * 0.9, YM - 0.06, 0.075], [x * 0.85, YM, 0.088]])),
    hull('ひざの節の帯', [-0.052, 0.052].flatMap(x => [[x, YM + 0.012, 0.03], [x, YM - 0.012, 0.03], [x * 0.9, YM + 0.012, 0.09], [x * 0.9, YM - 0.012, 0.09]]), { color: DARK })]),
  // 差し色のひざ当て
  K('kneeaccent', 'ひざ（2 重関節・差し色のひざ当て）', [0.11, 0.32, 0.2], [core(), ...knuckles(), cap('ひざ当て', { y0: -0.12, y1: 0.13, z1: 0.1, w: 0.05 }, { color: ACCENT })]),
];
