// 太ももの飾り（脚の骨 leg）：太ももの外（x 0.08 前後）の下のほう（y 0.1〜0.26）に付く。原点はひざの中心 K。
// それより上は股関節の脚の台（腰の外）が来るので出さない。
import { hull, octo2, loft } from '../limb/kit.js';
import { DARK, BLACK, MAIN, ACCENT } from '../../xsasm-lib.js';

const L = { bone: 'leg', pivot: 'none' };
const TD = (id, name, size, pieces) => ({ id, name, cat: '太ももの飾り', size, pieces: pieces.map(pc => ({ ...L, ...pc })) });
const unit = v => { const l = Math.hypot(...v); return v.map(x => x / l); };
/** 噴射口：外の輪 10 枚の板と奥の黒い板。c 中心、d 噴き出す向き、r 半径、len 長さ */
function nozzle(name, c, d, r, len) {
  d = unit(d);
  const s = unit([d[2], 0, -d[0]].some(v => Math.abs(v) > 1e-6) ? [d[2], 0, -d[0]] : [1, 0, 0]), n = unit([d[1] * s[2] - d[2] * s[1], d[2] * s[0] - d[0] * s[2], d[0] * s[1] - d[1] * s[0]]);
  const at = (t, rr, a) => [0, 1, 2].map(i => c[i] + t * d[i] + rr * (Math.cos(a) * s[i] + Math.sin(a) * n[i]));
  const out = [];
  for (let j = 0; j < 10; j++) {
    const pts = [];
    for (const a of [(j - 0.1) * Math.PI / 5, (j + 1.1) * Math.PI / 5]) pts.push(at(0, r * 0.8, a), at(0, r * 0.6, a), at(len, r, a), at(len, r * 0.8, a));
    out.push(hull(`${name}（${j + 1}）`, pts, { color: DARK }));
  }
  out.push(hull(`${name}の奥`, Array.from({ length: 10 }, (_, j) => [at(len * 0.3, r * 0.7, j * Math.PI / 5), at(len * 0.3 + 0.006, r * 0.7, j * Math.PI / 5)]).flat(), { color: BLACK }));
  return out;
}

