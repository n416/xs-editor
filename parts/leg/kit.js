// 脚の部品の共通の作り。原点はひざの中心 K（+x 側の脚で x 0.175・y 1.14・z 0）。股関節の軸は y +0.46、足の裏は y −1.14。
// ひざの中は 2 重関節（xs-editor/doublejoint.js）：上の軸 P1（y +0.04）と下の軸 P2（y −0.16）を節（骨 knee）がつなぐ。
// 外からは関節を見せない。関節の長さの分、太ももの中身は短い（y 0.1 より上）が、装甲は関節の上までかぶさる：
//   ・横：太ももの横の装甲板（外の層。外側は x 0.074〜0.106 の厚い板、内側は −0.074〜−0.092、骨 leg）が、下の軸の下（y −0.18）まで下りて関節全体を覆う。
//         すねの横の板（内の層 |x| 0.058〜0.072、骨 shin）はその内側で、下の軸のまわりの丸。曲げると 2 枚の板はすれ違う（層が違うので当たらない）
//   ・前：ひざ当て（節に付く、|x| < 0.056）。太ももの下の端（y 0.1）のすぐ下から、すねの上の端（y −0.225）の前まで
//   ・後ろ：節の後ろの板（2 本の軸をまとめて隠す。軸から 0.063 以内なので、曲げても太もも・すねに届かない）と、すねから上がる後ろの板
//   ・節は |x| < 0.056、太ももの中身は y 0.1 より上、すねの中身は y −0.225 より下（|x| < 0.058 の範囲）
import { hull, cylX, widen } from '../limb/kit.js';
import { DARK, BLACK, MAIN } from '../../xsasm-lib.js';

export const Y1 = 0.04, Y2 = -0.16, YM = (Y1 + Y2) / 2;
/** 脚の部品は、下の寸法（x）を KX 倍に太らせて置く（ひざは横の軸で曲がるので、横に太らせても当たりは変わらない）。
 *  置いたあとの幅：節 ±0.08、ひざ当て ±0.078、すねの横の板 0.084〜0.104、太ももの横の板 0.107〜0.154 */
export const KX = 1.45;
export const wide = pc => widen(pc, KX, 1);
export const HIP_Y = 0.46, SOLE = -1.14;
export const LEG = { bone: 'leg', pivot: 'none' }, KNEE = { bone: 'knee', pivot: 'none' }, SHIN = { bone: 'shin', pivot: 'none' };

/** 節：芯（回転の中心 = ひざの中心 K）、2 本の軸、後ろの板 */
export const link = (o = {}) => [
  { ...hull('ひざの節', [-0.045, 0.045].flatMap(x => [Y1, Y2].flatMap(y => [-0.035, 0.035].map(z => [x, y, z]))), { color: BLACK, ...KNEE, pivot: 'shin' }), center: [0, 0, 0] },
  cylX('ひざの上の軸', Y1, 0, 0.055, -0.055, 0.055, 16, { color: DARK, ...KNEE }), cylX('ひざの下の軸', Y2, 0, 0.055, -0.055, 0.055, 16, { color: DARK, ...KNEE }),
  hull('ひざの裏の板', [[-0.055, Y1 + 0.012, -0.04], [0.055, Y1 + 0.012, -0.04], [-0.055, Y2 - 0.012, -0.04], [0.055, Y2 - 0.012, -0.04],
    [-0.052, Y1 + 0.008, -0.059], [0.052, Y1 + 0.008, -0.059], [-0.052, Y2 - 0.008, -0.059], [0.052, Y2 - 0.008, -0.059]], { color: MAIN, ...KNEE, ...o })];

/** 横から見た形（[y, z] の並び）を x0〜x1 に押し出した板。外の面（x1 の側）は縁を落とし、真ん中を盛り上げる */
export function plate(name, yz, x0, x1, o = {}, c = 0.006) {
  const cy = yz.reduce((a, p) => a + p[0], 0) / yz.length, cz = yz.reduce((a, p) => a + p[1], 0) / yz.length, s = Math.sign(x1 - x0);
  // 外の面は平らにしない：縁から真ん中へ向かって少しずつ盛り上がる（真ん中がいちばん外）
  return hull(name, [...yz.flatMap(([y, z]) => [[x0, y, z], [x1 - s * c, y, z]]), ...yz.map(([y, z]) => [x1, y + (cy - y) * 0.25, z + (cz - z) * 0.25]), [x1 + s * c * 0.8, cy, cz]], o);
}
/** 太ももの横の装甲板（外の層、左右）。yz は横から見た形（上は太ももの中身に重ね、下は y −0.18 まで） */
export const thighPlates = (yz, o = {}, [xa, xb, xc] = [0.074, 0.106, 0.092]) => [plate('太もものひざの板（外）', yz, xa, xb, { ...LEG, ...o }, 0.012), plate('太もものひざの板（内）', yz, -xa, -xc, { ...LEG, ...o })];
/** 太ももの横の板の決まった形：上は y top、前 zf・後ろ zb、下は丸く y −0.18 まで */
export const thighPlateShape = (top = 0.16, zf = 0.1, zb = -0.085) => [[top, zb], [top, zf], [-0.06, zf * 0.95], [-0.13, zf * 0.62], [-0.175, 0.02], [-0.175, -0.02], [-0.13, zb * 0.7], [-0.06, zb]];
/** 太ももの横の板（内の層、左右）：上の軸のまわりの半径 0.098 の丸と、太ももの中身へ上がる所。すねの装甲がひざの横まで上がる脚で使う */
export const thighDiscs = (o = {}) => [1, -1].map(s => plate(`太もものひざの板（${s > 0 ? '外' : '内'}）`, [...Array.from({ length: 11 }, (_, k) => (k - 5) * 22 * Math.PI / 180).map(a => [Y1 - 0.098 * Math.cos(a), 0.098 * Math.sin(a)]), [0.17, 0.06], [0.17, -0.055]], s * 0.058, s * 0.072, { ...LEG, ...o }, 0.003));
/** すねの横の装甲（外の層、左右）：ひざの横まで上がって関節を覆う。yz は横から見た形。曲げるとすねと一緒に回り、太ももの中身（y 0.1 より上）には届かない */
export const shinFins = (yz, o = {}, [xa, xb, xc] = [0.074, 0.1, 0.09]) => [plate('すねの横の装甲（外）', yz, xa, xb, { ...SHIN, ...o }, 0.012), plate('すねの横の装甲（内）', yz, -xa, -xc, { ...SHIN, ...o }, 0.008)];
/** すねの横の板（内の層、左右）と、後ろの立ち上がり。上は上の軸の高さの少し下（y 0）まで */
export const shinPlates = (o = {}) => [
  // 下の軸のまわりの半径 0.098 の丸と、すねの中身へ下りる所。ひざ当ての盾（下の軸から 0.105 より外を、前から上・後ろへ回る）に当たらない
  ...[1, -1].map(s => plate(`すねのひざの板（${s > 0 ? '外' : '内'}）`, [...Array.from({ length: 11 }, (_, k) => (k - 5) * 18 * Math.PI / 180).map(a => [Y2 + 0.098 * Math.cos(a), 0.098 * Math.sin(a)]), [-0.25, 0.05], [-0.25, -0.05]], s * 0.058, s * 0.072, { ...SHIN, ...o }, 0.003)),
  hull('すねの後ろの立ち上がり', [[-0.072, -0.28, -0.062], [0.072, -0.28, -0.062], [-0.072, Y2 + 0.035, -0.062], [0.072, Y2 + 0.035, -0.062],
    [-0.066, -0.28, -0.084], [0.066, -0.28, -0.084], [-0.06, Y2 + 0.025, -0.08], [0.06, Y2 + 0.025, -0.08]], { ...SHIN, ...o })];
/** ひざ当て（節に付く）：横から見た形 yz（[y, z]、前へ出る）。真ん中（x 0）は前へ tip だけとがる。首と盾の 2 個を返す */
export const kneecap = (name, yz, w = 0.054, tip = 0.012, o = {}, W = 0.072) => {
  // 首：すねの横の板の間（|x| < w）を、節から前の盾の裏（z 0.105）まで。盾：すねの横の板より前（z 0.105 より前）で、太ももの横の板のすぐ内（|x| 0.072）まで
  const ZS = 0.105, y0 = Math.min(...yz.map(p => p[0])), y1 = Math.max(...yz.map(p => p[0]));
  const front = yz.filter(p => p[1] > ZS);
  const neck = hull(`${name}の首`, [-w, w].flatMap(x => [y0, y1].flatMap(y => [0.035, ZS + 0.004].map(z => [x, y, z]))), { ...KNEE, ...o });
  if (front.length < 2) return [hull(name, [...yz.flatMap(([y, z]) => [[-w, y, z], [w, y, z]]), ...yz.map(([y, z]) => [0, y, z > 0.04 ? z + tip : z])], { ...KNEE, ...o })];
  const fy0 = Math.min(...front.map(p => p[0])), fy1 = Math.max(...front.map(p => p[0]));
  const shield = hull(name, [[-W, fy1 + 0.012, ZS], [W, fy1 + 0.012, ZS], [-W, fy0 - 0.012, ZS], [W, fy0 - 0.012, ZS],
    ...front.flatMap(([y, z]) => [[-W * 0.93, y, ZS + (z - ZS) * 0.75], [W * 0.93, y, ZS + (z - ZS) * 0.75], [0, y, z + tip]])], { ...KNEE, ...o });
  return [neck, shield];
};
