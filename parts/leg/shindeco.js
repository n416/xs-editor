// 正座でふくらはぎが太ももの下に来るので、後ろの飾りは下のほう（y −0.5 より下）にだけ付ける。
import { hull, octo2, loft, widen } from '../limb/kit.js';
import { WS, SX } from './shin.js';
import { grille } from '../upper/kit.js';
import { DARK, BLACK, MAIN, ACCENT } from '../../xsasm-lib.js';

const SH = { bone: 'shin', pivot: 'none' };
// すねと同じく WS 倍に太らせて置く（太ったすねの面に付く）
const SD = (id, name, size, pieces) => ({ id, name, cat: 'すねの飾り', size, pieces: pieces.map(pc => ({ ...SH, ...widen(pc, WS, WS, SX) })) });
/** 後ろ下へ向いた噴射口：外の輪 10 枚の板と奥の黒い板。c 中心、半径 r、長さ len（後ろ −z へ、少し下へ） */
function nozzle(name, c, r, len) {
  const d = [0, -0.35, -1], l = Math.hypot(...d), u = d.map(v => v / l), s = [1, 0, 0], n = [0, u[2], -u[1]];
  const at = (t, rr, a) => [0, 1, 2].map(i => c[i] + t * u[i] + rr * (Math.cos(a) * s[i] + Math.sin(a) * n[i]));
  const out = [];
  for (let j = 0; j < 10; j++) {
    const pts = [];
    for (const a of [(j - 0.1) * Math.PI / 5, (j + 1.1) * Math.PI / 5]) pts.push(at(0, r * 0.8, a), at(0, r * 0.6, a), at(len, r, a), at(len, r * 0.8, a));
    out.push(hull(`${name}（${j + 1}）`, pts, { color: DARK }));
  }
  out.push(hull(`${name}の奥`, Array.from({ length: 10 }, (_, j) => [at(len * 0.3, r * 0.7, j * Math.PI / 5), at(len * 0.3 + 0.006, r * 0.7, j * Math.PI / 5)]).flat(), { color: BLACK }));
  return out;
}

