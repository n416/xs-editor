import { DARK, BLACK, MAIN, ACCENT } from '../../xsasm-lib.js';

const Y = h => SOLE + h;
const lr = (pts) => pts.flatMap(([x, y, z]) => (x === 0 ? [[0, y, z]] : [[-x, y, z], [x, y, z]]));
/** 足首の台：足首の球の下から靴底へ広がる暗い塊（どの足も同じ）。足の回転の中心（足首）を持つ */
const core = () => ({ ...hull('足首の台', lr([[0.045, ANKLE_Y + 0.03, -0.05], [0.045, ANKLE_Y + 0.03, 0.05], [0.084, Y(0.06), -0.15], [0.084, Y(0.06), 0.14]]), { color: DARK }), pivot: 'foot', center: [0, ANKLE_Y, 0] });
/** 足の甲の装甲：つま先の付け根から足首の前へ上がる楔（足に付く。足首の軸から 0.09 以内まで） */
const instep = (o = {}, w = 0.08) => hull('足の甲の装甲', lr([[w, Y(0.2), 0.07], [w, Y(0.2), 0.25], [w * 0.75, -0.855, 0.06], [w * 0.75, -0.86, 0.1], [0, -0.846, 0.085], [0, Y(0.215), 0.268]]), o);
/** かかとの上の装甲：かかとの付け根から足首の後ろへ上がる楔 */
const heelTop = (o = {}, w = 0.075) => hull('かかとの上の装甲', lr([[w, Y(0.2), -0.06], [w, Y(0.2), -0.2], [w * 0.75, -0.865, -0.05], [w * 0.75, -0.87, -0.085], [0, -0.86, -0.075], [0, Y(0.21), -0.215]]), o);
const FT = (id, name, size, pieces) => ({ id, name, cat: '足', size: [size[0] * KX / 1.4, size[1], size[2]], pieces: [core(), ...pieces].map(pc => ({ ...FOOT, ...wide(pc) })) });
/** 靴底：上から見た輪郭（かかと zb、つま先 zf、幅 w、つま先の幅 wt）を高さ h まで。縁は下を少し落とす */
const sole = (name, { zb = -0.2, zf = 0.42, w = 0.105, wt = 0.08, h = 0.06 } = {}, o = {}) => {
  const out = [[-w, zb + 0.03], [-w * 0.8, zb], [w * 0.8, zb], [w, zb + 0.03], [w, zf - 0.14], [wt, zf - 0.02], [wt * 0.6, zf], [-wt * 0.6, zf], [-wt, zf - 0.02], [-w, zf - 0.14]];
  return hull(name, [...out.map(([x, z]) => [x * 0.94, Y(0), z * 0.97]), ...out.map(([x, z]) => [x, Y(0.02), z]), ...out.map(([x, z]) => [x * 0.97, Y(h), z * 0.98])], o);
};

