// 足は長さ 0.5 前後（かかと z −0.15、つま先 z 0.36）。幅は 0.3 前後（x ±0.15。足は置くときに太らせない）。足の裏は地面に立つので平ら（ほかの広い面は傾ける）。
import { hull } from '../limb/kit.js';
import { SHIN, SOLE } from './kit.js';
import { DARK, BLACK, MAIN, ACCENT } from '../../xsasm-lib.js';

const FT = (id, name, size, pieces) => ({ id, name, cat: '足', size, pieces: pieces.map(pc => ({ ...SHIN, ...pc })) });
const Y = h => SOLE + h;
/** 靴底：上から見た輪郭（かかと zb、つま先 zf、幅 w、つま先の幅 wt）を高さ h まで。縁は下を少し落とす */
const sole = (name, { zb = -0.15, zf = 0.36, w = 0.15, wt = 0.11, h = 0.06, cx = 0.005 } = {}, o = {}) => {
  const out = [[-w, zb + 0.03], [-w * 0.8, zb], [w * 0.8, zb], [w, zb + 0.03], [w, zf - 0.14], [wt, zf - 0.02], [wt * 0.6, zf], [-wt * 0.6, zf], [-wt, zf - 0.02], [-w, zf - 0.14]];
  return hull(name, [...out.map(([x, z]) => [cx + x * 0.94, Y(0), z * 0.97]), ...out.map(([x, z]) => [cx + x, Y(0.02), z]), ...out.map(([x, z]) => [cx + x * 0.97, Y(h), z * 0.98])], o);
};

