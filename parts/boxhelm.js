// 角ばった頭：丸みのない 3 つめの頭の殻。上は低い六角柱の天板（前後に長い六角形、上の縁を大きく落とす）、
// その下にまゆの棚が前へ張り出し、棚の下に垂直な顔の板。顔の板は目の上・目の下・目の間の 3 枚に分け、
// 目の溝の奥に暗い壁、その手前に光る目。顔の板の両脇に頬の板が斜めに付き、下はあごへすぼまる。
// 後ろは垂直に近い板と首すじの斜面。頭の中心が原点付近、前が +z。幅 0.19 × 高さ 0.22 × 奥行き 0.28
// 正面（顔の板・目・あご・まゆの棚）は上から見て 八 の字。耳のように張り出す頬の板は付けない：右半分を、中央の前面を通る縦の軸で後ろへ回し、左はその鏡像。中央に鼻筋の稜
import { P, XH, XL, YH, YL, ZH, ZL, both, box, piece, pair, mir, rotYAt, MAIN, DARK, BLACK, GLOW } from '../xsasm-lib.js';

const FACE_Z = 0.126, FACE_X = 0.07;     // 顔の板の前面と半幅
const EYE_Y0 = 0.01, EYE_Y1 = 0.036;     // 目の溝の下端・上端
const EYE_X0 = 0.012, EYE_X1 = 0.072;    // 目の溝の内端・外端（外端は頬の板の中に入る）
const FOLD = 30;                         // 正面の折れ（度）。右半分を縦軸まわりにこれだけ後ろへ回す
const NAPE = P([0, -1, -1], [0, -0.025, -0.105]);   // 芯の首すじの斜面（後ろ下）：y -0.025 の後ろから y -0.1 の z -0.03 へ

export default {
  id: 'boxhelm', name: '角ばった頭', cat: '頭蓋', size: [0.19, 0.22, 0.28],
  face: { eye: [0.023, 0.134], mouth: [-0.03, 0.128, 0], under: [-0.1, 0], brow: [0.072, 0.146], lift: 0.05 },   // 顔の部品を付ける所：目は作り付けの目の前面、口もとは垂直な顔の板
  pieces: [
    // 芯：顔・頬・天板・後ろの板を載せる中身の箱。下へすぼまって首になり、前下は斜め、後ろ下は首すじの斜面、後ろの角は落とす
    piece('芯', [XL(-0.088), XH(0.088), YL(-0.1), YH(0.09), ZL(-0.105), ZH(0.1), NAPE,
      ...both(P([1, -0.6, 0], [0.088, -0.01, 0])),                            // 下へすぼまる
      P([0, -1, 1], [0, -0.1, 0.06]),                                        // 前下の斜め（あごの奥）
      ...both(P([1, 0, -1], [0.088, 0, -0.085]))]),                            // 後ろの角を落とす
    // 天板：前後に長い六角柱（前と後ろが短い平ら、真ん中がいちばん広い）。上の縁は 6 辺とも大きく落とす
    piece('天板', [YL(0.085), YH(0.12), ZH(0.118), ZL(-0.128), ...both(XH(0.095)),
      ...both(P([0.14, 0, 0.035], [0.06, 0, 0.118])),                       // 前の斜めの辺
      ...both(P([0.115, 0, -0.035], [0.095, 0, -0.02])),                     // 後ろの斜めの辺
      P([0, 1, 1], [0, 0.1, 0.118]), P([0, 1, -1], [0, 0.1, -0.128]),        // 上の縁：前・後ろ
      ...both(P([1, 1, 0], [0.095, 0.1, 0])),                                // 上の縁：横
      ...both(P([0.14, 0.1443, 0.035], [0.06, 0.1, 0.118])),                 // 上の縁：前の斜めの辺
      ...both(P([0.115, 0.1202, -0.035], [0.095, 0.1, -0.02]))]),            // 上の縁：後ろの斜めの辺
    // まゆの棚：天板の下から顔の前へ張り出す低い板。頬より広く、前の角を落とし、下の前縁を少し斜めに
    piece('まゆの棚', [...box(-0.095, 0.095, 0.055, 0.09, 0.0, 0.146),
      ...both(P([1, 0, 1], [0.095, 0, 0.114])),                              // 前の角
      P([0, -1, 1], [0, 0.055, 0.134])]),                                    // 下の前縁
    // 正面の右半分（回す前。x 0 〜）：顔の板（目の上・目の下）、目の溝の奥、光る目、あご、まゆの棚、頬の板
    ...(() => {
      const R = [
        ['目の上', [XL(0), XH(FACE_X), YL(EYE_Y1), YH(0.06), ZL(0.095), ZH(FACE_Z)], {}],
        ['目の下', [XL(0), XH(FACE_X), YL(-0.03), YH(EYE_Y0), ZL(0.095), ZH(FACE_Z)], {}],
        ['目の奥', box(EYE_X0, EYE_X1, EYE_Y0, EYE_Y1, 0.095, 0.11), { color: BLACK }],                       // 溝の奥の暗い壁
        ['目', box(EYE_X0 + 0.004, FACE_X - 0.003, EYE_Y0 + 0.003, EYE_Y1 - 0.003, 0.108, FACE_Z + 0.008), { color: GLOW, glow: true, metal: 0, rough: 0.3 }],   // 顔の板より前へ出す
        ['あご', [XL(0), XH(FACE_X), YL(-0.1), YH(-0.025), ZL(0.04), ZH(FACE_Z), P([1, -0.4, 0], [FACE_X, -0.025, 0]), P([0, -1, 1], [0, -0.1, 0.09])], {}],
        ['まゆの棚', [XL(0), XH(0.088), YL(0.055), YH(0.09), ZL(0.0), ZH(0.146), P([1, 0, 1], [0.088, 0, 0.114]), P([0, -1, 1], [0, 0.055, 0.134])], {}],
      ];
      const out = [];
      for (const [name, planes, o] of R) { const r = rotYAt(planes, FOLD, 0, FACE_Z); out.push(piece(name + '（右）', r, o), piece(name + '（左）', r.map(mir), o)); }
      return out;
    })(),
    // 中央：目の間の鼻筋（折れ目を覆う。前は小さな稜）と、まゆの棚の中央（棚は軸より前へ出るので、折れ目の切れ込みを埋める）
    piece('鼻筋', [XL(-EYE_X0), XH(EYE_X0), YL(-0.03), YH(0.06), ZL(0.095), P([0.5, 0, 1], [EYE_X0 * 0.5, 0, FACE_Z + 0.016]), P([-0.5, 0, 1], [-EYE_X0 * 0.5, 0, FACE_Z + 0.016])]),   // 稜を前へ出す
    piece('棚の中央', [XL(-0.014), XH(0.014), YL(0.055), YH(0.09), ZL(0.0), P([0.5, 0, 1], [0.007, 0, 0.152]), P([-0.5, 0, 1], [-0.007, 0, 0.152]), P([0, -1, 1], [0, 0.055, 0.14])]),
    // 後ろの板：垂直に近い（上が少し前）。芯より狭い
    piece('後ろの板', [XL(-0.08), XH(0.08), YH(0.1), YL(-0.03), ZH(-0.1),
      P([0, 0.08, -1], [0, 0.1, -0.126])]),
    // 首すじ：後ろの板の下から首へ下りる斜面の板。芯の斜面に重ね、下へ少しすぼまる
    piece('首すじ', [XL(-0.075), XH(0.075), YH(-0.028), YL(-0.1),
      P([0, -1, -1], [0, -0.03, -0.134]),                                    // 外の斜面
      P([0, 1, 1], [0, -0.02, -0.105]),                                      // 内側（芯の斜面より少し中へ入って重なる）
      ...both(P([1, -0.6, 0], [0.075, -0.03, 0]))]),                        // 芯のすぼまりと同じ傾き（芯からはみ出さない）
  ],
};
