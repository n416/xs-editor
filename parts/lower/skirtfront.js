// 前スカート：腰の帯の前面の下の角に蝶番で付き、太ももの前に下がる大きな台形の装甲（腰の骨の子のスカートの骨）。原点は股関節の中心（+x 側）。
// 脚を前へ上げると太ももに押されて、蝶番のまわりに前へ開く（hinge：蝶番の軸は横、y 0.17・z 0.2、dir +1 で裾が前へ上がる）。
// 蝶番は帯の前面の下の角にあり、板は帯の外から下がるので、ひざ立ちで水平まで押し上げられても帯に入らない
// （板の上の端は蝶番より前へほとんど出さない）。付け根以外の厚さは自由（押されて開くので太ももに縛られない）。
// 太ももの半ばまで覆い、下ほど広く、下ほど厚い。横に反り（中央が盛り上がる）、中央に一段高いパネル。下の縁は中央が低い V
import { P, XH, XL, YH, prismX, piece, DARK } from '../../xsasm-lib.js';
import { crown, steps } from './shape.js';

const HINGE = { y: 0.17, z: 0.2, dir: 1 };
const H = { hinge: HINGE, bone: 'skirt' };   // 骨はスカート（ゲームでは skirt_front_* / skirt_back_*）
const C = 0.03;                                                     // 板の中心（x）。太ももの柱の中心より少し外
const TOP = 0.155;                                                  // 板の上の端
const face = lift => (x, y) => 0.21 + (TOP - y) * 0.2 - 2 * (x - C) ** 2 + lift;   // 前の面：上 0.21、下ほど前へ（厚さ 付け根 0.025、裾 0.1）
const back = P([0, 0.02, -1], [0, TOP, 0.185]);                    // 裏の面：ほぼ縦（下ほど少し前）
export default {
  id: 'skirtfront', name: '前スカート', cat: '前スカート', size: [0.21, 0.42, 0.11],
  pieces: [
    piece('前スカート', [...crown('z', 1, face(0), steps(-0.075, 0.135, 4), steps(-0.3, TOP, 6)),
      back, YH(TOP), P([0, 1, 1.5], [0, TOP, 0.205]),                             // 上の縁の前の角を落とす
      P([1, 0.0357, 0], [0.12, TOP, 0]), P([-1, 0.0357, 0], [-0.06, TOP, 0]),       // 下ほど広い台形
      P([0.3, -1, 0], [C, -0.26, 0]), P([-0.3, -1, 0], [C, -0.26, 0])], H),        // 下の縁は中央が低い V
    piece('前スカートのパネル', [...crown('z', 1, face(0.01), steps(C - 0.07, C + 0.07, 2), steps(-0.2, 0.1, 4)),
      P([0, 0.02, -1], [0, TOP, 0.21]), YH(0.1), P([1, 0.0357, 0], [C + 0.06, 0.1, 0]), P([-1, 0.0357, 0], [C - 0.06, 0.1, 0]),
      P([0.3, -1, 0], [C, -0.2, 0]), P([-0.3, -1, 0], [C, -0.2, 0])], H),
    piece('前スカートの蝶番', [...prismX(0.02, 8, 22.5, HINGE.y, HINGE.z), XL(-0.05), XH(0.11)], { ...H, pivot: 'skirt', color: DARK }),
  ],
};
