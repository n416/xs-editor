// 腰（芯）：2 段の帯と、股の芯。原点は腰の帯の下端（骨格図の waist.yBand、y 1.77）の中心。x 右・y 上・z 前。
// 帯（y 0〜0.18）は脚を上げても届かない高さなので幅いっぱい（領域 C）。前後の面は横に反った装甲、前後の角は斜めに落とす。
// 下の段は下ほど細く、上の段は上ほど細い（正面から見て、段の間がいちばん広い）。段の間に暗い溝。
// それより下は太ももの柱の内側 |x| ≤ 0.085 だけ（領域 A）：卵形の股の芯（暗い色）。前掛け（V 字の盾）は別の部品（maekake.js）
import { P, YH, YL, both, ellipsoid, piece, DARK } from '../../xsasm-lib.js';
import { crown, steps } from './shape.js';

const XS = steps(-0.3, 0.3, 6);
/** 帯の段：y0〜y1、前後の面の高さ zf・zb（中央）、横 x の位置と傾き、角の落とし */
const tier = (y0, y1, zf, zb, xw, tilt, bend) => [YL(y0), YH(y1),
  ...crown('z', 1, (x, y) => zf - 0.5 * x * x - bend * (y - (y0 + y1) / 2) ** 2, XS, steps(y0, y1, 2)),
  ...crown('z', -1, (x, y) => zb - 0.5 * x * x - bend * (y - (y0 + y1) / 2) ** 2, XS, steps(y0, y1, 2)),
  ...both(P([1, tilt, 0], [xw, (y0 + y1) / 2, 0])),
  ...both(P([1, 0, 0.9], [xw - 0.005, 0, zf - 0.09])), ...both(P([1, 0, -0.9], [xw - 0.005, 0, -(zb - 0.09)]))];

export default {
  id: 'waist', name: '腰', cat: '腰', size: [0.72, 0.51, 0.45],
  pieces: [
    piece('帯（下）', tier(0, 0.09, 0.215, 0.2, 0.355, -0.3, 1.5)),
    piece('帯の溝', tier(0.08, 0.105, 0.2, 0.19, 0.345, 0, 0)),
    piece('帯（上）', [...tier(0.095, 0.18, 0.205, 0.19, 0.345, 0.35, 3), P([0, 1, 1.1], [0, 0.18, 0.15]), P([0, 1, -1.1], [0, 0.18, -0.14]), ...both(P([1, 1, 0], [0.29, 0.18, 0]))]),
    piece('股の芯', [...ellipsoid([0.085, 0.3, 0.15], [0, -0.02, 0], 12, [-70, -45, -20, 0, 20, 45]), YH(0.04)], { color: DARK }),
  ],
};
