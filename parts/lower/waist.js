// 腰（芯）：帯と、股の芯。原点は腰の帯の下端（骨格図の waist.yBand、y 1.77）の中心。x 右・y 上・z 前。
// 帯（y 0〜0.18）は脚を上げても届かない高さなので幅いっぱい（領域 C）。前後の面は横に反った装甲、前後の角は斜めに落とす。
// それより下は太ももの柱の内側 |x| ≤ 0.085 だけ（領域 A）：卵形の股の芯（暗い色）。前掛け（V 字の盾など）は別の部品（maekake.js）。
// 種類：2 段の帯（段の間に暗い溝）・細い帯・横に張り出し・角ばった・中央に留め金・幅広の帯（左右が合わさるスカートと組む：
// 下の段がスカートの輪と同じ幅・奥行きで、前後のスカートの蝶番がその縁の下に収まり、上の段は胸の幅へつながる。上がすぼまらない）
import { P, YH, YL, ZL, both, ellipsoid, piece, DARK, ACCENT } from '../../xsasm-lib.js';
import { crown, steps } from './shape.js';

const XS = steps(-0.3, 0.3, 6);
/** 帯の段：y0〜y1、前後の面の高さ zf・zb（中央）、横 x の位置と傾き、上下の反り bend、横の反り cx、前後の角の落とし（角の面の向き cn、奥へ cd） */
const tier = (y0, y1, zf, zb, xw, tilt, bend, cx = 0.5, cn = 0.9, cd = 0.09) => [YL(y0), YH(y1),
  ...crown('z', 1, (x, y) => zf - cx * x * x - bend * (y - (y0 + y1) / 2) ** 2, XS, steps(y0, y1, 2)),
  ...crown('z', -1, (x, y) => zb - cx * x * x - bend * (y - (y0 + y1) / 2) ** 2, XS, steps(y0, y1, 2)),
  ...both(P([1, tilt, 0], [xw, (y0 + y1) / 2, 0])),
  ...both(P([1, 0, cn], [xw - 0.005, 0, zf - cd])), ...both(P([1, 0, -cn], [xw - 0.005, 0, -(zb - cd)]))];
const topEdge = (xw = 0.29) => [P([0, 1, 1.1], [0, 0.18, 0.15]), P([0, 1, -1.1], [0, 0.18, -0.14]), ...both(P([1, 1, 0], [xw, 0.18, 0]))];
const core = () => piece('股の芯', [...ellipsoid([0.085, 0.3, 0.15], [0, -0.02, 0], 12, [-70, -45, -20, 0, 20, 45]), YH(0.04)], { color: DARK });
const twoTier = () => [
  piece('帯（下）', tier(0, 0.09, 0.215, 0.2, 0.355, -0.3, 1.5)),
  piece('帯の溝', tier(0.08, 0.105, 0.2, 0.19, 0.345, 0, 0)),
  piece('帯（上）', [...tier(0.095, 0.18, 0.205, 0.19, 0.345, 0.35, 3), ...topEdge()]),
];
const W = (id, name, pieces) => ({ id, name, cat: '腰', size: [0.72, 0.51, 0.45], pieces });

export default [
  W('waist', '腰（2 段の帯）', [...twoTier(), core()]),
  W('waistthin', '腰（細い帯）', [
    piece('帯', [...tier(0, 0.12, 0.205, 0.19, 0.335, 0.1, 2), P([0, 1, 1.1], [0, 0.12, 0.17]), P([0, 1, -1.1], [0, 0.12, -0.16]), ...both(P([1, 1, 0], [0.3, 0.12, 0]))]),
    piece('帯の上の縁', [...tier(0.115, 0.18, 0.17, 0.16, 0.28, 0.5, 2)], { color: DARK }),
    core()]),
  W('waistbulge', '腰（横に張り出し）', [...twoTier(), core(),
    ...[1, -1].map(s => piece(`腰の張り出し（${s > 0 ? '+x' : '−x'}）`, [...ellipsoid([0.075, 0.1, 0.14], [s * 0.34, 0.09, 0], 12, [-60, -30, 0, 30, 60]), s > 0 ? P([-1, 0, 0], [0.3, 0, 0]) : P([1, 0, 0], [-0.3, 0, 0]), YL(0.005)])),
    ...[1, -1].map(s => piece(`張り出しの帯（${s > 0 ? '+x' : '−x'}）`, [...ellipsoid([0.08, 0.1, 0.145], [s * 0.34, 0.09, 0], 12, [-15, 0, 15]), s > 0 ? P([-1, 0, 0], [0.33, 0, 0]) : P([1, 0, 0], [-0.33, 0, 0]), YL(0.075), YH(0.105)], { color: DARK }))]),
  W('waistangular', '腰（角ばった）', [
    piece('帯（下）', tier(0, 0.09, 0.22, 0.2, 0.355, -0.3, 0.6, 0.25, 0.55, 0.14)),
    piece('帯の溝', tier(0.08, 0.105, 0.205, 0.185, 0.345, 0, 0, 0.25, 0.55, 0.14), { color: DARK }),
    piece('帯（上）', [...tier(0.095, 0.18, 0.21, 0.19, 0.345, 0.35, 1, 0.25, 0.55, 0.14), ...topEdge(0.3)]),
    core()]),
  W('waistwide', '腰（幅広の帯）', [
    piece('帯（下）', [...tier(0, 0.1, 0.24, 0.295, 0.425, -0.1, 1.2, 0.35, 0.45, 0.07), P([0, -1, 1.2], [0, 0, 0.225]), P([0, -1, -1.2], [0, 0, -0.28])]),
    piece('帯の溝', tier(0.09, 0.115, 0.228, 0.28, 0.41, 0, 0, 0.35, 0.45, 0.07), { color: DARK }),
    piece('帯（上）', [...tier(0.105, 0.19, 0.232, 0.27, 0.4, 0.9, 2, 0.4, 0.5, 0.08), P([0, 1, 1.4], [0, 0.19, 0.19]), P([0, 1, -1.4], [0, 0.19, -0.22]), ...both(P([1, 1.3, 0], [0.34, 0.19, 0]))]),
    core()]),
  W('waistbuckle', '腰（中央に留め金）', [...twoTier(), core(),
    piece('留め金', [...crown('z', 1, (x, y) => 0.24 - 3 * x * x - 1.5 * (y - 0.05) ** 2, steps(-0.07, 0.07, 2), steps(0.0, 0.11, 2)),
      ZL(0.15), YL(0.005), YH(0.105), ...both(P([1, 0, 0.35], [0.07, 0, 0.2]))], { color: ACCENT }),
    piece('留め金の芯', [...crown('z', 1, (x, y) => 0.252 - 3 * x * x - 1.5 * (y - 0.05) ** 2, steps(-0.03, 0.03, 2), steps(0.025, 0.08, 2)),
      ZL(0.18), YL(0.025), YH(0.08), ...both(P([1, 0, 0.35], [0.03, 0, 0.22]))], { color: DARK })]),
];
