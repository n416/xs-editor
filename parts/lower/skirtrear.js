// 後ろ腰：腰の帯の後ろの装甲と、中央のお尻の板（どちらも動かない）。原点は腰の帯の下端の中心（y 1.77）。
// 後ろ腰の装甲は帯の高さ（領域 C）で幅いっぱい、後ろへ盛り上がる。中央に一段高いパネル、下の縁に沿って暗い溝。
// （左右対称の暗い穴を 2 つ並べると、後ろから見て顔に見えるので置かない）
// お尻の板は左右の後ろスカート（skirtback）の間、太ももの柱の内側 |x| ≤ 0.08（領域 A）だけを下へ伸ばす台形。下の縁は平ら
import { P, XH, YH, YL, ZH, both, piece, DARK } from '../../xsasm-lib.js';
import { crown, steps } from './shape.js';

const back = (x, y) => 0.265 - 0.8 * x * x - 1.2 * (y - 0.08) ** 2 - 0.2 * (y - 0.08);
export default {
  id: 'skirtrear', name: '後ろ腰', cat: '後ろ腰', size: [0.56, 0.38, 0.12],
  pieces: [
    piece('後ろ腰の装甲', [...crown('z', -1, back, steps(-0.26, 0.26, 6), steps(0.002, 0.16, 3)),
      ZH(-0.16), YL(0.002), YH(0.16), ...both(P([1, 0, -0.4], [0.27, 0, -0.2]))]),
    piece('後ろ腰のパネル', [...crown('z', -1, (x, y) => back(x, y) + 0.012, steps(-0.12, 0.12, 4), steps(0.03, 0.14, 2)),
      ZH(-0.2), YL(0.03), YH(0.14), ...both(P([1, 0, -0.6], [0.12, 0, -0.24]))]),
    piece('後ろ腰の溝', [...crown('z', -1, (x, y) => back(x, y) + 0.004, steps(-0.24, 0.24, 6), [0.012]), ZH(-0.2), YL(0.006), YH(0.018), ...both(XH(0.24))], { color: DARK }),
    piece('お尻の板', [...crown('z', -1, (x, y) => 0.215 - 3 * x * x + 0.1 * y - 0.3 * (y + 0.1) ** 2, steps(-0.075, 0.075, 4), steps(-0.2, 0.03, 4)),
      ZH(-0.1), YH(0.03), YL(-0.2), ...both(P([1, -0.12, 0], [0.08, 0.03, 0])), P([0, -1, -0.6], [0, -0.2, -0.17])]),
  ],
};
