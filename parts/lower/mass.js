// 厚い塊の腰（腰の骨 hips）：薄い帯にベルト・筒を巻く作りではなく、股関節を包む骨盤の塊。上半身の厚い殻（parts/upper/mass.js）と組む。
// 原点は腰の帯の下端の中心（y 1.77）。帯の高さ（y 0〜0.09）は脚を上げても届かないので幅いっぱい、それより下は太ももの内側 |x| ≤ 0.085 だけ（股の芯）。
// 殻は「角のある断面をつなぐ形」（partgeo.js の loft の pts）。角の並びは上半身の殻と同じ：前の中央・正面の端・角・横の前・横のいちばん外・横の後ろ・後ろの角・後ろの中央。
// 役目：真ん中の高さがいちばん外へ出る（上下の面が斜めになり、下の面はスカートの付け根にかぶさる）。上の面の上に旋回輪が載り、腹の下の端（腰の関節）を囲う。
// 横幅を 0.9 倍にしない（目次で slim を通さない）：はじめから置く幅で書いてある。寸法は置いた機体で測った相手の縁から：
// 前の帯 = 横 0.317・前 0.236・後ろ 0.221、前スカートの付け根の前の面 = 前 0.21、腹の下の端 = 横 0.19・前 0.15（原点から 0.06 上）。[独自]
import { MAIN, DARK, BLACK, YH, ellipsoid, piece, planesFromPoints } from '../../xsasm-lib.js';

const shell = (name, secs, o = {}) => ({ name, kind: 'loft', secs, color: MAIN, pos: [0, 0, 0], ...o });
// 帯（下の車体）：スカートの付け根の上（y 0）から y 0.05 までの低い塊。横は腹（上の車体）より大きく張り出さない（前の形は横 0.332 まで張り出した
// 平たい皿で、胸と腰の間に積み木のように見えた、issue #218）。少し傾いた壁（上へ内へ）と、上の端の面取り
const W0 = [[0, 0.235], [0.12, 0.235], [0.245, 0.185], [0.312, 0.07], [0.325, -0.03], [0.3, -0.13], [0.18, -0.215], [0, -0.22]].map(([x, z]) => [x * 0.75, z]);
const PELVIS = [
  { y: 0, pts: W0 },                                                       // 下の縁（スカートの付け根の上）
  { y: 0.035, pts: W0.map(([x, z]) => [x * 0.96, z * 0.98]) },            // 壁の上の端
  { y: 0.05, pts: W0.map(([x, z]) => [x * 0.88, z * 0.9]) },              // 上の面（旋回輪の外）
];
// ---- 旋回輪（issue #218「関節がおもちゃっぽい」）：ショベルの上の車体と下の車体をつなぐ旋回輪（大きな軸受けの輪）の作り。帯（下の車体）の
// 上の面と、腹（上の車体、下の端は帯の上 0.12）の間にある、どちらよりも細い暗い輪（半径 0.17、y 0.045〜0.105）。横から輪の厚みが見える。
// 輪の中を腰の関節の柱（parts/lower/belly.js）が通る。上下の角は落とす。寸法は [独自] ----
const SLEW = { r: 0.17, y0: 0.045, y1: 0.105, c: 0.01, n: 24 };
const slewRing = () => [piece('旋回輪', planesFromPoints(Array.from({ length: SLEW.n }, (_, k) => (k / SLEW.n) * Math.PI * 2).flatMap(a => {
  const { r, y0, y1, c } = SLEW, at = (rr, y) => [rr * Math.sin(a), y, rr * Math.cos(a)];
  return [at(r - c, y0), at(r, y0 + c), at(r, y1 - c), at(r - c, y1)];
})), { color: '#8e959c', metal: 0.7, rough: 0.35 })];   // (鋼の色：機体の塗り替えの色から外れた色で、陣営の色に塗られない)
const core = () => piece('股の芯', [...ellipsoid([0.085, 0.3, 0.15], [0, -0.02, 0], 12, [-70, -45, -20, 0, 20, 45]), YH(0.04)], { color: DARK });

export default [
  { id: 'waistpelvis', name: '腰（骨盤の塊）', cat: '腰', size: [0.67, 0.42, 0.48], pieces: [shell('骨盤の殻', PELVIS, { color: BLACK }), core(), ...slewRing()] },
];
