// 厚い塊の腰（腰の骨 hips）：薄い帯にベルト・筒を巻く作りではなく、股関節を包む骨盤の塊。上半身の厚い殻（parts/upper/mass.js）と組む。
// 原点は腰の帯の下端の中心（y 1.77）。帯の高さ（y 0〜0.09）は脚を上げても届かないので幅いっぱい、それより下は太ももの内側 |x| ≤ 0.085 だけ（股の芯）。
// 殻は「角のある断面をつなぐ形」（partgeo.js の loft の pts）。角の並びは上半身の殻と同じ：前の中央・正面の端・角・横の前・横のいちばん外・横の後ろ・後ろの角・後ろの中央。
// 役目：真ん中の高さがいちばん外へ出る（上下の面が斜めになり、下の面はスカートの付け根にかぶさる）。上の面の上に旋回輪が載り、腹の下の端（腰の関節）を囲う。
// 横幅を 0.9 倍にしない（目次で slim を通さない）：はじめから置く幅で書いてある。寸法は置いた機体で測った相手の縁から：
// 前の帯 = 横 0.317・前 0.236・後ろ 0.221、前スカートの付け根の前の面 = 前 0.21、腹の下の端 = 横 0.19・前 0.15（原点から 0.06 上）。[独自]
import { MAIN, DARK, BLACK, YH, ellipsoid, piece, planesFromPoints } from '../../xsasm-lib.js';

const shell = (name, secs, o = {}) => ({ name, kind: 'loft', secs, color: MAIN, pos: [0, 0, 0], ...o });
// 帯：下の縁（y 0）から y 0.105 までは、少し傾いた厚い壁（横は上へ内へ、前後は上へわずかに外へ）。上の端は面取りして、y 0.125 の上の面が
// 旋回輪（外の半径 0.262）を囲う。高さの真ん中が刃のように張り出したレンズ形（前の形、高さ 0.09）にしない（issue #218：胸と腰の間に平たい皿が
// はさまって見えた）。前後は旋回輪の外まで張る
const W1 = [[0, 0.262], [0.12, 0.262], [0.25, 0.2], [0.318, 0.075], [0.332, -0.03], [0.305, -0.14], [0.18, -0.25], [0, -0.258]];
const PELVIS = [
  { y: 0, pts: [[0, 0.235], [0.12, 0.235], [0.245, 0.185], [0.312, 0.07], [0.325, -0.03], [0.3, -0.13], [0.18, -0.215], [0, -0.22]] },        // 下の縁（スカートの付け根の上）
  { y: 0.04, pts: W1 },                                                                                                                          // いちばん外
  { y: 0.105, pts: W1.map(([x, z]) => [x * 0.93, z * 1.03]) },                                                                                  // 壁の上の端
  { y: 0.125, pts: W1.map(([x, z]) => [x * 0.86, z * 1.04]) },                                                                                  // 上の面（旋回輪の外）
];
// ---- 旋回輪（issue #218「関節がおもちゃっぽい」）：骨盤の上の面が、立ち上がった縁の付いた平たい皿になっていて、胸と腰の間に皿がはさまって見えた。
// ショベルの上の車体と下の車体をつなぐ旋回輪（大きな軸受けの輪）の作りにする：骨盤の上の面の上に、腹の下の端（軸から 0.197 まで）を囲う
// 厚い暗い輪（内の半径 0.235・外 0.262、y 0.11〜0.145）。腹は輪の中で縦の軸のまわりに回り、前へ傾く（内の半径は、腹が前へ 11° 傾いても届かない大きさ）。輪は 16 個の凸の塊を並べる（中が空いた輪は
// 1 つの凸の形にならない）。外の上の角は落とす。寸法は [独自] ----
const SLEW = { ri: 0.235, ro: 0.262, y0: 0.11, y1: 0.145, n: 16 };
const slewRing = () => Array.from({ length: SLEW.n }, (_, k) => {
  const a0 = (k / SLEW.n) * Math.PI * 2, a1 = ((k + 1) / SLEW.n) * Math.PI * 2, { ri, ro, y0, y1 } = SLEW;
  const at = (r, y, a) => [r * Math.sin(a), y, r * Math.cos(a)];
  return piece(`旋回輪 ${k + 1}`, planesFromPoints([a0, a1].flatMap(a => [at(ri, y0, a), at(ri, y1, a), at(ro, y0, a), at(ro, y1 - 0.012, a), at(ro - 0.012, y1, a)])), { color: BLACK });
});
const core = () => piece('股の芯', [...ellipsoid([0.085, 0.3, 0.15], [0, -0.02, 0], 12, [-70, -45, -20, 0, 20, 45]), YH(0.04)], { color: DARK });

export default [
  { id: 'waistpelvis', name: '腰（骨盤の塊）', cat: '腰', size: [0.67, 0.42, 0.48], pieces: [shell('骨盤の殻', PELVIS), core(), ...slewRing()] },
];
