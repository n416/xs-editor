// 後ろスカート（片側）：後ろ腰の装甲の下の角に蝶番で付き、お尻と太ももの裏に下がる台形の装甲（腰の骨の子のスカートの骨）。原点は股関節の中心（+x 側）。
// 脚を後ろへ振ると太ももに押されて、蝶番のまわりに後ろへ開く（hinge：蝶番の軸は横、y 0.17・z −0.25、dir −1 で裾が後ろへ上がる）。
// 蝶番は後ろ腰の装甲の下の角にあり、板はその外から下がる（板の上の端は蝶番より後ろへほとんど出さない）。付け根以外の厚さは自由。
// お尻と太ももの裏の上半分を覆い、下ほど広く、下ほど厚い。横に反り、中央に一段高いパネル。下の縁は外が長い斜め
import { P, XH, XL, YH, prismX, piece, DARK } from '../../xsasm-lib.js';
import { crown, steps } from './shape.js';

const HINGE = { y: 0.17, z: -0.25, dir: -1 };
const H = { hinge: HINGE, bone: 'skirt' };   // 骨はスカート（ゲームでは skirt_front_* / skirt_back_*）
const C = 0.025;                                                    // 板の中心（x）
const TOP = 0.155;
const face = lift => (x, y) => 0.26 + (TOP - y) * 0.18 - 2 * (x - C) ** 2 + lift;   // 後ろの面の深さ（−z 向き）：上 0.26、下ほど後ろへ
const front = P([0, 0.02, 1], [0, TOP, -0.235]);                   // 表の面（体の側）：ほぼ縦
export default {
  id: 'skirtback', name: '後ろスカート', cat: '後ろスカート', size: [0.2, 0.41, 0.1],
  pieces: [
    piece('後ろスカート', [...crown('z', -1, face(0), steps(-0.08, 0.13, 4), steps(-0.28, TOP, 6)),
      front, YH(TOP), P([0, 1, -1.5], [0, TOP, -0.255]),
      P([1, 0.03, 0], [0.12, TOP, 0]), P([-1, 0.03, 0], [-0.07, TOP, 0]),                  // 下ほど広い台形
      P([0.35, -1, 0], [C, -0.25, 0])], H),                                                 // 下の縁：外が長い斜め
    piece('後ろスカートのパネル', [...crown('z', -1, face(0.01), steps(C - 0.065, C + 0.065, 2), steps(-0.18, 0.1, 4)),
      P([0, 0.02, 1], [0, TOP, -0.26]), YH(0.1), P([1, 0.03, 0], [C + 0.055, 0.1, 0]), P([-1, 0.03, 0], [C - 0.055, 0.1, 0]),
      P([0.35, -1, 0], [C, -0.19, 0])], H),
    piece('後ろスカートの蝶番', [...prismX(0.02, 8, 22.5, HINGE.y, HINGE.z), XL(-0.06), XH(0.11)], { ...H, pivot: 'skirt', color: DARK }),
  ],
};
