// レドーム（回転式レーダーの円盤）：バックパックの装備（胴の骨 torso）、バックパックの後ろの面の真ん中（slot 'back'）に付ける。
// レーダー機の背中の大きな円盤 [依頼主 2026-11-14「レーダー機っぽく背中に大きなレドームをつけておくといいです」]。
// 円盤は頭の上にかぶせない：付ける所から太い支柱で後ろ上へ持ち上げ、円盤の中心は背中より後ろ、高さは肩と頭のてっぺんの間
// （ハブ 2026-11-14「頭の真上にあって、日傘をさしているように見えます」→ 背中の後ろ上、正面から見て頭の後ろに少しのぞく程度）。
// 大きさは草案の絵（ナイティの草案 E）に合わせた [独自]。
// 作り：受けの箱（パックの後ろの面に沿う）→ 角柱 2 本を組んだ支柱（1 本の棒にしない）→ 回る軸受け → 円盤（上下が膨らんだレンズ形の
// 回転体）と縁の帯。円盤の上下の面の真ん中に低い盛り上がり。どれも凸の塊。
import { piece, DARK, BLACK } from '../../xsasm-lib.js';
import { hull, xf, lathePlanes, cbox } from './kit.js';

const G = (id, name, slot, size, pieces) => ({ id, name, cat: 'バックパックの装備', slot, size, pieces });

/** 円盤（中心が原点、軸は y）：半径 r、厚み t（真ん中）、縁の厚み e */
function dish(r, t, e, n = 24) {
  const lens = [[-t / 2, r * 0.18], [-t * 0.42, r * 0.55], [-t * 0.28, r * 0.82], [-e / 2, r * 0.97], [0, r], [e / 2, r * 0.97], [t * 0.28, r * 0.82], [t * 0.42, r * 0.55], [t / 2, r * 0.18]];
  return [
    piece('レドームの円盤', lathePlanes(lens, n)),
    piece('レドームの縁の帯', lathePlanes([[-e * 0.32, r * 0.985], [-e * 0.2, r + 0.008], [e * 0.2, r + 0.008], [e * 0.32, r * 0.985]], n), { color: DARK }),
    piece('レドームの上の盛り上がり', lathePlanes([[t / 2 - 0.01, r * 0.2], [t / 2 + 0.012, r * 0.15], [t / 2 + 0.02, r * 0.07]], 12), { color: DARK }),
    piece('レドームの下の盛り上がり', lathePlanes([[-t / 2 - 0.02, r * 0.07], [-t / 2 - 0.012, r * 0.15], [-t / 2 + 0.01, r * 0.2]], 12), { color: DARK }),
  ];
}

/** 支柱の角柱（a から b、断面 w × d、前の面を少し落とした 8 角の柱） */
function beam(name, a, b, w, d, o = {}) {
  const pts = [];
  for (const p of [a, b]) for (const [sx, sz] of [[-1, -1], [1, -1], [-1, 1], [1, 1]]) {
    pts.push([p[0] + sx * w, p[1], p[2] + sz * d * 0.75], [p[0] + sx * w * 0.75, p[1], p[2] + sz * d]);
  }
  return hull(name, pts, o);
}

// 付ける所（パックの後ろの面の真ん中）から見て：円盤の中心は 後ろ 0.46・上 0.32（世界で y 約 2.48・z 約 −0.9。肩アーマーの上の端とほぼ同じ高さで、正面からは頭の脇に縁が少しのぞく。ジェム・トレーナーの
// バックパックで）。支柱は付ける所の後ろ上の 2 本の角柱（前の柱が太い）と、その先の軸受け。
const C = [0, 0.32, -0.46], R0 = 0.5, T0 = 0.14;
const radome = G('gearradome', 'レドーム（背中の大きな円盤のレーダー）', 'back', [1.1, 0.8, 1.1], [
  cbox('レドームの受け', [0, -0.02], [0.13, 0.05], [0.11, 0.045], -0.14, 0.14, { bev: 0.02, color: DARK }),
  beam('レドームの支柱（前）', [0, 0.04, -0.05], [0, C[1] - 0.14, C[2] + 0.05], 0.075, 0.06),
  beam('レドームの支柱（後ろ）', [0, -0.1, -0.07], [0, C[1] - 0.18, C[2] - 0.04], 0.055, 0.045, { color: DARK }),
  hull('レドームの支柱の継ぎ目', [-1, 1].flatMap(sx => [[sx * 0.07, C[1] - 0.24, C[2] - 0.08], [sx * 0.07, C[1] - 0.24, C[2] + 0.1], [sx * 0.06, C[1] - 0.06, C[2] - 0.07], [sx * 0.06, C[1] - 0.06, C[2] + 0.07]]), { color: DARK }),   // （上の端は軸受けの中まで：離れていると浮いた部品になる）
  ...xf([
    piece('レドームの軸受け', lathePlanes([[-0.11, 0.095], [-0.09, 0.105], [-0.03, 0.105], [-0.012, 0.085]], 12), { color: DARK }),
    piece('レドームの軸受けの溝', lathePlanes([[-0.075, 0.108], [-0.065, 0.112], [-0.055, 0.108]], 12), { color: BLACK }),
    ...dish(R0, T0, 0.045),
  ], { mov: [C[0], C[1] + 0.02, C[2]] }),
]);

export default [radome];
