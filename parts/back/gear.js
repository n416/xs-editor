/** タンク（軸は y、中心が原点）：両端が丸い筒、締め帯、色の帯、下の弁、上のふた */
export function tank(name, len, r, { n = 14, bands = [-0.22, 0.22], stripe = 0.31 } = {}) {
  const h = len / 2, d = r * 0.95, k = r / 0.1;
  const lo = [[-h, r * 0.2], [-h + d * 0.1, r * 0.5], [-h + d * 0.33, r * 0.78], [-h + d * 0.65, r * 0.94], [-h + d, r]];
  const hi = lo.map(([y, q]) => [-y, q]).reverse();
  return [
    piece(name, lathePlanes([...lo, ...hi], n)),
    ...bands.map((b, i) => piece(`${name}の締め帯 ${i + 1}`, lathePlanes([[b * len - 0.024, r + 0.001], [b * len - 0.017, r + 0.009], [b * len + 0.017, r + 0.009], [b * len + 0.024, r + 0.001]], n), { color: DARK })),
    piece(`${name}の色の帯`, lathePlanes([[stripe * len - 0.02, r + 0.002], [stripe * len - 0.016, r + 0.004], [stripe * len + 0.016, r + 0.004], [stripe * len + 0.02, r + 0.002]], n), { color: ACCENT }),
    piece(`${name}の弁`, lathePlanes([[-h - 0.045 * k, 0.02 * k], [-h - 0.02 * k, 0.04 * k], [-h + 0.015, 0.046 * k]], n), { color: DARK }),
    piece(`${name}のふた`, lathePlanes([[h - 0.015, 0.046 * k], [h + 0.012 * k, 0.04 * k], [h + 0.03 * k, 0.02 * k]], n), { color: DARK }),
  ];
}
