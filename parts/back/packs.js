function drum() {
  const at = { rot: [0, 0, -90], mov: [0, 0.36, -0.3] };   // 軸を x へ
  const fin = (x, k) => {
    const pts = [];
    for (let a = -20; a <= 115; a += 15) { const r = 0.16 - 0.000004 * (a - 50) ** 2, c = Math.cos(a * Math.PI / 180), s = Math.sin(a * Math.PI / 180); for (const dx of [-0.006, 0.006]) pts.push([x + dx, 0.36 + r * s, -0.3 - r * c]); }
    for (const dx of [-0.009, 0.009]) pts.push([x + dx, 0.36, -0.3]);
    return hull(`放熱ひれ ${k + 1}`, pts, { color: DARK });
  };
  return B('backpackdrum', '横置きの炉（放熱ひれ）', [0.46, 0.4, 0.3], { side: [0.215, 0.36, -0.3], top: [0.12, 0.47, -0.25], back: [0, 0.3, -0.42] }, [
    cbox('炉の台', [0, -0.215], [0.13, 0.05], [0.105, 0.05], 0.22, 0.5, { bev: 0.02, color: DARK }),
    ...xf(lathe('炉の胴', [[-0.205, 0.06], [-0.19, 0.098], [-0.155, 0.122], [-0.1, 0.13], [0.1, 0.13], [0.155, 0.122], [0.19, 0.098], [0.205, 0.06]], { n: 16, th0: 11.25 }), at),
    ...xf([piece('炉の帯（+x）', lathePlanes([[0.105, 0.128], [0.11, 0.137], [0.135, 0.134], [0.14, 0.124]], 16, 11.25), { color: DARK }),
      piece('炉の帯（−x）', lathePlanes([[-0.14, 0.124], [-0.135, 0.134], [-0.11, 0.137], [-0.105, 0.128]], 16, 11.25), { color: DARK }),
      piece('炉のふた（+x）', lathePlanes([[0.2, 0.066], [0.215, 0.058], [0.225, 0.03]], 16, 11.25), { color: ACCENT }),
      piece('炉のふた（−x）', lathePlanes([[-0.225, 0.03], [-0.215, 0.058], [-0.2, 0.066]], 16, 11.25), { color: ACCENT })], at),
    ...[-0.06, -0.03, 0, 0.03, 0.06].map(fin),
    ...bothX(named('+x ', xf(bell('噴射口', { len: 0.1, r0: 0.045, r1: 0.072, glow: FLAME }), { rot: [22, 0, 0], mov: [0.1, 0.25, -0.345] })))]);
}

