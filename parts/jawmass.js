// あごの塊：顔の下半分。目の帯のすぐ下から、ヘルメットとほぼ同じ幅のまま前へ少し出て、下へすぼまる。小さな箱を顔に貼るのではなく、
// ヘルメットの下に続く塊（依頼主：「あご当て」は「小さすぎておかしい」「口の箱も正直変」）。動力パイプ（頭を回る）の前の端は、この塊の横に入る。
// 役目：吸気口と、パイプの受け。吸気口は正面を削った横の溝 3 本（奥は黒）。
// 形は「角のある断面をつなぐ形」（partgeo.js の loft の pts）。寸法は、GIO の水陸に置いたバイザーの頭（目なし）で測った値から（機体の座標）：
// ヘルメットの横 0.134・前 0.14、目の帯の下の端 y 2.617、パイプ y 2.52〜2.60・横 0.226、首の上の端 y 2.548・半径 0.08。[独自]
// 頭の部品の座標は、機体の座標 = 頭の原点 (0, 2.606, −0.015) + 0.45 × 部品の座標（置き方 mov 0・scal 1 のとき）。下の数字は機体の座標で書いて、K で割る。
import { MAIN, BLACK, planesFromPoints, piece } from '../xsasm-lib.js';

const K = 0.45, Y0 = 2.606, Z0 = -0.015;
const ly = y => (y - Y0) / K, lz = z => (z - Z0) / K, lx = x => x / K;
const sec = (y, pts) => ({ y: ly(y), pts: pts.map(([x, z]) => [lx(x), lz(z)]) });
// 断面の角：前の中央・正面の端・角・横（パイプの入る面）・横の後ろ・後ろの中央
const JAW = [
  sec(2.495, [[0, 0.115], [0.05, 0.11], [0.085, 0.07], [0.095, 0.02], [0.09, -0.02], [0, -0.03]]),      // あごの下の端
  sec(2.535, [[0, 0.175], [0.07, 0.165], [0.118, 0.1], [0.13, 0.03], [0.12, -0.02], [0, -0.03]]),       // いちばん前・いちばん外
  sec(2.585, [[0, 0.168], [0.065, 0.158], [0.112, 0.1], [0.128, 0.03], [0.12, -0.02], [0, -0.03]]),
  sec(2.607, [[0, 0.14], [0.055, 0.135], [0.1, 0.09], [0.12, 0.03], [0.115, -0.02], [0, -0.03]]),       // 目の帯の下へ入る上の端
];
const box = (x0, x1, y0, y1, z0, z1) => [x0, x1].flatMap(x => [y0, y1].flatMap(y => [z0, z1].map(z => [lx(x), ly(y), lz(z)])));

export default {
  id: 'jawmass', name: 'あご（顔の下の塊）', cat: 'あご', size: [0.26 / K, 0.112 / K, 0.205 / K],
  pieces: [
    { name: 'あごの殻', kind: 'loft', secs: JAW, color: MAIN, pos: [0, 0, 0] },
    // 吸気口：横の溝 3 本（引く）。その奥に黒い板（溝より後に並べるので削られない）
    { name: '吸気口の溝', kind: 'extrude', op: 'sub', pts: [[lx(-0.05), -0.006 / K], [lx(0.05), -0.006 / K], [lx(0.05), 0.006 / K], [lx(-0.05), 0.006 / K]], depth: 0.05 / K,
      arrayCount: 3, arrayStep: [0, 0.017 / K, 0], tf: { p: [0, ly(2.544), lz(0.172)], r: [0, 0, 0], s: [1, 1, 1] }, color: MAIN, pos: [0, 0, 0] },
    piece('吸気口の奥', planesFromPoints(box(-0.054, 0.054, 2.534, 2.59, 0.135, 0.15)), { color: BLACK }),
  ],
};
