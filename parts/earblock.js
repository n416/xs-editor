// 耳ブロック：頭の右横に付ける耳の箱。内側の面（x 0）で頭に付き、外へ +x。面取りした箱で、外側の面に横長の通気口の溝が 3 本。
// 溝は本当のくぼみ：外側の面を 4 本の横棒に分け、前後の枠で囲い、棒と棒の間の奥に暗い壁を置く。前の縁は斜めに落とす。左は組み立て側で鏡像
import { P, box, piece, MAIN, BLACK } from '../xsasm-lib.js';

const W = 0.08, H = 0.06, D = 0.07;                       // 幅（内側 x 0 から外へ）、高さの半分、奥行きの半分
const CH = 0.012;                                         // 外側の面のまわりの角の落とし幅
const BAR_IN = W - CH;                                    // 横棒・枠の内側 = 角の落としの始まり（芯との境目が角の稜線に重なり、同じ面がだぶらない）
const FLOOR = BAR_IN + 0.001;                             // 溝の底（暗い壁の外側の面）。外側の面 x 0.08 から 0.011 くぼむ。棒は壁に食い込む
// 箱の外形：角の落とし（全 piece に共通の面）
const SLANT = P([1, 0, 1], [W, 0, 0.04]);                 // 前の縁：外側の面の z 0.04 から前の面の x 0.05 へ 45 度に落とす
const CH_BACK = P([1, 0, -1], [W, 0, -D + CH]);           // 外・後ろの角
const CH_TOP = P([1, 1, 0], [W, H - CH, 0]);              // 外・上の角
const CH_BOT = P([1, -1, 0], [W, -(H - CH), 0]);          // 外・下の角
const CH_TB = P([0, 1, -1], [0, H, -D + 0.01]);           // 上・後ろの角
const CH_BB = P([0, -1, -1], [0, -H, -D + 0.01]);         // 下・後ろの角
const CH_TF = P([0, 1, 1], [0, H, D - 0.01]);             // 上・前の角
const CH_BF = P([0, -1, 1], [0, -H, D - 0.01]);           // 下・前の角
const EDGES = [SLANT, CH_BACK, CH_TB, CH_BB, CH_TF, CH_BF];
const ZF = 0.03, ZB = -0.052;                             // 溝の前端・後端（前枠・後枠の内側）
// 横棒 1 本：外側の面の帯 y0..y1。x は壁の中から外側の面まで、z は前枠と後枠の間（枠と面で接する）
const bar = (name, y0, y1, extra = []) => piece(name, [...box(BAR_IN, W, y0, y1, ZB, ZF), ...extra]);

export default {
  id: 'earblock', name: '耳ブロック', cat: '飾り', size: [0.08, 0.12, 0.14],
  pieces: [
    piece('芯', [...box(0, BAR_IN, -H, H, -D, D), ...EDGES]),                                    // 頭に付く側の中身（x 0 が取り付け面）。外側の棒・枠と面で接する
    piece('奥の壁', box(BAR_IN - 0.008, FLOOR, -0.033, 0.033, ZB - 0.006, ZF + 0.006), { color: BLACK }),   // 溝の底：3 本の溝の奥に見える暗い壁（芯・棒・枠に食い込む）
    bar('上棒', 0.029, H, [CH_TOP]),                                                             // 外側の面：いちばん上の帯（上の角を落とす）
    bar('中棒・上', 0.007, 0.015),                                                               // 溝と溝の間の細い棒（溝は高さ 0.014）
    bar('中棒・下', -0.015, -0.007),
    bar('下棒', -H, -0.029, [CH_BOT]),                                                           // いちばん下の帯（下の角を落とす）
    piece('前枠', [...box(BAR_IN, W, -H, H, ZF, D), SLANT, CH_TOP, CH_BOT, CH_TF, CH_BF]),       // 溝の前を閉じる縦枠：上下いっぱいで、斜めの面を 1 枚で持つ
    piece('後枠', [...box(BAR_IN, W, -H, H, -D, ZB), CH_BACK, CH_TOP, CH_BOT, CH_TB, CH_BB]),    // 溝の後ろを閉じる縦枠：上下いっぱいで、後ろの角の落としを 1 枚で持つ
  ],
};
