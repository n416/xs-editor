// 側頭の塊（左右）：ヘルメットの横に箱を貼る（耳ブロック）のをやめ、こめかみからあごの横まで下りる 1 つの多面体にする。下の端は、あごの塊
//（parts/jawmass.js）の横と同じ高さ・同じ前後の位置で終わり、頭を回る動力パイプはこの塊の下をくぐる。
// 役目：頭の横の装甲と、排熱口（外の面を削った前後に走る溝 3 本）。左右とも 1 つの部品に入っている。
// 寸法は、GIO の水陸に置いたバイザーの頭（目なし）で測った値から（機体の座標）：ヘルメットの横 0.134（y 2.57〜2.64）、耳ブロックは横 0.177・y 2.56〜2.69・
// 前後 −0.055〜0.097 だった。[独自]
// 頭の部品の座標は、機体の座標 = 頭の原点 (0, 2.606, −0.015) + 0.45 × 部品の座標（置き方 mov 0・scal 1 のとき）。下の数字は機体の座標で書いて、K で割る。
import { MAIN, planesFromPoints, piece } from '../xsasm-lib.js';

const K = 0.45, Y0 = 2.606, Z0 = -0.015;
const L = ([x, y, z]) => [x / K, (y - Y0) / K, (z - Z0) / K];
const SIDE = [
  [0.12, 2.7, 0.05], [0.12, 2.7, -0.05], [0.12, 2.52, 0.06], [0.12, 2.52, -0.03],            // ヘルメットの中に入る内の面
  [0.15, 2.7, 0.06], [0.15, 2.7, -0.05],                                                      // 上の端（こめかみ）
  [0.178, 2.65, 0.085], [0.178, 2.65, -0.06], [0.182, 2.58, 0.09], [0.182, 2.58, -0.055],    // いちばん外
  [0.15, 2.52, 0.07], [0.15, 2.52, -0.03],                                                    // 下の端（あごの横）
];
const half = s => piece(`側頭の塊（${s > 0 ? '+x' : '−x'}）`, planesFromPoints(SIDE.map(p => L([s * p[0], p[1], p[2]]))), { color: MAIN });

export default {
  id: 'cheekmass', name: '側頭の塊（左右）', cat: '飾り', size: [0.364 / K, 0.18 / K, 0.15 / K],
  pieces: [
    half(1), half(-1),
    // 排熱口：外の面を前後に走る溝 3 本（引く。左右とも）
    { name: '排熱口の溝', kind: 'extrude', op: 'sub', mirror: true, pts: [[-0.012 / K, -0.005 / K], [0.012 / K, -0.005 / K], [0.012 / K, 0.005 / K], [-0.012 / K, 0.005 / K]], depth: 0.09 / K,
      arrayCount: 3, arrayStep: [0, 0.022 / K, 0], tf: { p: L([0.182, 2.59, 0.012]), r: [0, 0, 0], s: [1, 1, 1] }, color: MAIN, pos: [0, 0, 0] },
  ],
};
