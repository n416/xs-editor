// V 字アンテナ（トサカ）：額に付く。中心の台形の塊（正面から見て台形。台形の面が前を向く）の左右の斜めの辺から、薄く長く鋭い 2 枚の刃が開く。
// 刃は板で、上の縁は刃のように研いであり、先へ向かって細り、後ろへ少し倒れる。塊の前面は上が後ろへ 19 度倒れ、横長の光る溝（本当のくぼみ）。
// y 0 が塊の底、前が +z。塊の後ろは額の中へ入る。
// 前は塊が高さ 0.016 の平たい板で、頭頂に寝かせて置いていたので、台形の広い面が上を向いていた（「なんで上を向いてるんですか」）。
// 溝も、塊の本体が溝の前まで詰まっていて見えなかった
import { P, XH, XL, YH, YL, ZH, ZL, both, box, piece, mir, rotXAt, MAIN, DARK, BLACK, GLOW } from '../xsasm-lib.js';

// 刃 1 枚（右）：x-y 面に立つ板。根元 x 0.018〜0.05、先 (0.28, 0.2)。厚み z ±0.004、上の縁と下の縁を研ぐ
const T = 0.004;
const BLADE_R = [
  ZH(T), ZL(-T), YL(0),                                           // （塊の底より下へは出さない：前は根元の内の角が、塊の下へとげのように出ていた）
  P([-1, 0.55, 0], [0.018, 0.0, 0]),                              // 根元の内側（上へ行くほど外へ）
  P([0.62, -1, 0], [0.05, 0.0, 0]),                               // 下の縁：外へ向かって上がる
  P([-0.55, 1, 0], [0.018, 0.028, 0]),                            // 上の縁：下の縁より緩く上がる（先で細る）
  P([1, 0.35, 0], [0.3, 0.21, 0]),                                 // 先
  P([-0.55, 1, 0.9], [0.018, 0.028, T]), P([-0.55, 1, -0.9], [0.018, 0.028, -T]),   // 上の縁を研ぐ（前後から）
  P([0.62, -1, 0.9], [0.05, 0.0, T]), P([0.62, -1, -0.9], [0.05, 0.0, -T]),         // 下の縁も研ぐ
];
const blade = rotXAt(BLADE_R, 18, 0, 0);                          // 後ろへ 18 度倒す（根元の軸で）
const H = 0.04;                                                    // 塊の高さ
const FRONT = d => P([0, 0.35, 1], [0, 0, 0.02 - d]);              // 塊の前面（上が後ろへ 19 度）。d は前面からの引っ込み
const SIDES = both(P([1, 0.6, 0], [0.055, 0, 0]));                 // 左右の斜めの辺：底で半幅 0.055、上で 0.031（正面から見て台形）
const TOP = P([0, 1, -0.3], [0, H, 0]);                            // 上面は後ろへ下がる
const G0 = 0.013, G1 = 0.027, GX = 0.03, GD = 0.007;               // 溝：下端・上端・半分の幅・深さ
export default {
  id: 'vfin', name: 'V 字アンテナ', cat: 'トサカ', size: [0.56, 0.2, 0.08],
  brow: [0.014, -0.012, -19],   // 額に当てる所（部品の座標 y・z）と、前面の倒れ。置くときに殻の額の点（face.brow）へ合わせる（xsasm-random.js）
  pieces: [
    piece('塊', [YL(0), TOP, ZL(-0.03), FRONT(GD + 0.001), ...SIDES]),                                   // 溝の奥より後ろの本体
    piece('上唇', [YL(G1), TOP, ZL(0), FRONT(0), ...SIDES]),
    piece('下唇', [YL(0), YH(G0), ZL(0), FRONT(0), ...SIDES]),
    piece('溝の脇（右）', [YL(G0), YH(G1), ZL(0), FRONT(0), ...SIDES, XL(GX)]), piece('溝の脇（左）', [YL(G0), YH(G1), ZL(0), FRONT(0), ...SIDES, XH(-GX)]),
    piece('溝の奥', [YL(G0 - 0.001), YH(G1 + 0.001), ZL(0), FRONT(GD - 0.0005), ...both(XH(GX + 0.001))], { color: BLACK }),
    piece('光る帯', [YL(0.017), YH(0.023), ZL(0), FRONT(0.004), ...both(XH(0.022))], { color: GLOW, glow: true, metal: 0, rough: 0.3 }),
    piece('刃（右）', blade), piece('刃（左）', blade.map(mir)),                                            // 刃の根元は塊の斜めの辺から出る
  ],
};
