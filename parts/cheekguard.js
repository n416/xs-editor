// 頬当て：頭の右の頬に付ける厚い装甲板。内側の面が x 0（取り付け面）、外へ +x。
// 横から見ると六角形（上は広く、真ん中で最も広く、下は細い）。前の縁は少し内へ折れ（外側の面に縦の折れ線）、
// 下の縁は大きく面取り。外側の平らな面には、縁と折れ線から一回り内側に、一段高い小さな板を重ねて浅い段にする。左は鏡像なので右だけ
import { P, XH, XL, YH, YL, ZH, piece, MAIN } from '../xsasm-lib.js';

/** 面を法線の向きへ t だけずらす（t < 0 で内へ） */
const shift = (pl, t) => [pl[0], pl[1], pl[2], pl[3] + t];

const T = 0.068;      // 板の厚み（外側の平らな面の x）
const FOLD = 0.02;    // 前の折れ線の z（これより前は内へ傾く）
const CHAM = -0.033;  // 下の面取りが始まる y
// 横から見た六角形の輪郭（y・z の面）：上の辺 y 0.07（z ±0.03）、最も広い所 y 0.03（z ±0.05）、下の辺 y -0.07（z ±0.015）
const OUTLINE = [
  YH(0.07), YL(-0.07),
  P([0, 1, 2], [0, 0.07, 0.03]), P([0, 1, -2], [0, 0.07, -0.03]),                       // 上の斜めの辺：前後へ広がりながら下りる
  P([0, -0.035, 0.1], [0, 0.03, 0.05]), P([0, -0.035, -0.1], [0, 0.03, -0.05]),         // 下の斜めの辺：下へすぼまる
];

export default {
  id: 'cheekguard', name: '頬当て', cat: '飾り', size: [0.08, 0.14, 0.1],
  pieces: [
    // 六角形の厚い板。外側は平らな面、前の縁の折れ（z FOLD より前は内へ傾き、前の縁で 0.018 内へ）、下の縁の大きな面取り（45 度、幅 0.035）
    piece('板', [XL(0), XH(T), P([1, 0, 0.6], [T, 0, FOLD]), P([1, -1, 0], [T, CHAM, 0]), ...OUTLINE]),
    // 段：外側の平らな面に重ねる一段高い板。輪郭は板の縁・折れ線・面取りの線から一様に 0.012 内側。板に 0.012 埋める
    piece('段', [XL(T - 0.012), XH(T + 0.01), ZH(FOLD - 0.012), YL(CHAM + 0.012), ...OUTLINE.map(p => shift(p, -0.012))]),
  ],
};
