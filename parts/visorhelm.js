// バイザーの頭：面取りした卵型の頭蓋（前が細く後ろが太い）。目の高さに幅いっぱいの横長のバイザーの溝（本当のくぼみ：
// 頭蓋を上と下に分け、溝の奥に暗い壁、その中に光る細い帯）。溝の下は口もとの板があごへすぼまり、あごの下に小さなあご当ての段。
// 横は平らな側板（殻より少し外へ出る）。後ろは首すじまで下りる。頭の中心が原点付近、前が +z。headshell と同じ大きさ
import { P, XH, XL, YH, YL, ZH, ZL, both, box, ellipsoid, MAIN, DARK, BLACK, GLOW, piece, pair } from '../xsasm-lib.js';

const C = [0, 0.038, 0];                                                    // 卵の中心
const RF = [0.082, 0.1, 0.145], RB = [0.088, 0.1, 0.135];                   // 前半分（細い）・後ろ半分（少し太い）の半径
const FRONT = [-60, -30, 0, 30, 60], SIDE = [90, 270], BACK = [120, 150, 180, 210, 240];   // 経線（度、0 が前。正面に平らな面）
/** 卵の殻の接平面：前半分は RF、横と後ろは RB */
const shell = (lats, front = true, back = true) => [
  ...(front ? ellipsoid(RF, C, 12, lats, 0, FRONT) : []),
  ...ellipsoid(RB, C, 12, lats, 0, back ? [...SIDE, ...BACK] : SIDE),
];
const UNDER = P([0, -1, -0.147], [0, -0.045, -0.09]);                       // 下面：首すじ（後ろ、y -0.045）から あご（前、y -0.07）へ緩く下がる
const VT = 0.047, VB = 0.008;                                               // 溝の上端・下端
const inset = d => [RF[0] - d, RF[1], RF[2] - d];                           // 溝の奥の壁：殻より d だけ内側の楕円
const GROOVE = [-90, ...FRONT, 90];                                         // 溝は前面から横（側板の前）まで回り込む

const visorhelm = {
  id: 'visorhelm', name: 'バイザーの頭', cat: '頭蓋', size: [0.19, 0.22, 0.29],
  face: { eye: [0.0275, 0.132], mouth: [-0.03, 0.1185, 40], under: [-0.0582, -0.147], lift: 0.016 },   // 顔の部品を付ける所：目は溝の中の光る帯の前面、口もとは「口もと」の板の正面（強く倒れた面。板は横にまっすぐ広いので、面より 0.008 前に置く：マスクの左右の端が沈まないように）
  pieces: [
    piece('頭蓋', [...shell([5, 30, 55, 80]), YL(VT)]),                                        // 溝より上：面取りした卵
    piece('後頭', [...shell([-30, 5], false), YH(VT + 0.002), UNDER, ZH(-0.02)]),               // 溝の後ろ：卵の続き、首すじへすぼまりながら下りる
    piece('口もと', [...shell([-30], true, false), YH(VB), UNDER, ZL(-0.03),
      P([0, -0.8, 0.6], [0, -0.06, 0.083])]),                                                   // 溝の下：あごへ強くすぼまる板。あごの下は斜めに切る
    piece('溝の奥', [...ellipsoid(inset(0.022), C, 12, [0], 0, GROOVE), YH(VT + 0.002), YL(VB - 0.002), ZL(-0.02)], { color: BLACK }),   // 溝の奥の暗い壁
    piece('目の帯', [...ellipsoid(inset(0.013), C, 12, [0], 0, GROOVE), YH(0.032), YL(0.023), ZL(-0.01)],
      { color: GLOW, glow: true, metal: 0, rough: 0.3 }),                                       // 溝の奥に光る細い帯（暗い壁より少し手前、殻よりは奥）
    ...pair('側板', [XH(0.095), XL(0.05), YH(0.05), YL(-0.045), ZL(-0.035), ZH(0.032),         // 平らな板。横から見ると長い八角形
      P([0, 1, 1], [0, 0.05, 0.01]), P([0, -1, 1], [0, -0.045, 0.01]),                          // 前の上下の角
      P([0, 1, -1], [0, 0.05, -0.02]), P([0, -1, -1], [0, -0.045, -0.02]),                      // 後ろの上下の角
      P([0.7, 1, 0], [0.095, 0.042, 0]), P([1, -1, 0], [0.095, -0.03, 0])]),                    // 外側の上下の角
    piece('あご当て', [...box(-0.03, 0.03, -0.082, -0.055, 0.03, 0.08),
      ...both(P([1, 0, 0.8], [0.03, 0, 0.065])),                                                // 前の角を落とす
      P([0, -1, 0.5], [0, -0.082, 0.07])]),                                                     // 下の前を斜めに
  ],
};

// バイザーの頭（目なし）：溝の奥の光る帯を外したもの（溝の奥の暗い壁は残る）。目は別の部品を入れる
const visorhelmplain = { ...visorhelm, id: 'visorhelmplain', name: 'バイザーの頭（目なし）', face: { ...visorhelm.face, eye: [0.0275, 0.123] },   // 目は溝の奥の暗い壁へ
  pieces: visorhelm.pieces.filter(pc => pc.name !== '目の帯') };

export default [visorhelm, visorhelmplain];
