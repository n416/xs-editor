// ひじ（中間の節、骨 elbow）：2 重関節（xs-editor/doublejoint.js）。原点はひじの中心 E。上の軸 P1（y +0.05）と下の軸 P2（y −0.05）の
// 横の円柱（半径 0.042、x ±0.062）を節がつなぐ。節は P1 のまわりに曲げの半分だけ回り、縦の軸のまわりにも向きを変えるので、
//   ・P1 のまわりで半径 0.042 より外へ出る物は、節の後ろ（−z、ひじ当て）か下だけ（曲げると後ろは下へ回る）
//   ・P2 のまわりは、前腕のお椀（半径 0.086 の球の欠片、緯度 −22° より下）に一部が入ったまま。P2 から 0.086 より外で、P2 より 0.02 以上下へは出さない
// 真ん中の部品（回転の中心 fore）は前後・左右に対称にする（その箱の中心がひじの中心になる）。
import { hull, cylX } from '../limb/kit.js';
import { DARK, BLACK, ACCENT } from '../../xsasm-lib.js';

const L = { bone: 'elbow', pivot: 'none' };
const knuckles = (r = 0.042, h = 0.062) => [cylX('ひじの上の軸', 0.05, 0, r, -h, h, 14, { color: DARK }), cylX('ひじの下の軸', -0.05, 0, r, -h, h, 14, { color: DARK })];
/** 節の真ん中（回転の中心）：前後・左右に対称な箱 */
const core = (w = 0.04, d = 0.026, color = BLACK) => hull('ひじの節', [[-w, 0.05, -d], [w, 0.05, -d], [-w, 0.05, d], [w, 0.05, d], [-w, -0.05, -d], [w, -0.05, -d], [-w, -0.05, d], [w, -0.05, d]], { color, pivot: 'fore' });
/** 軸の端の丸い蓋（左右） */
const caps = (r = 0.022) => [0.05, -0.05].flatMap(y => [cylX(`ひじの軸の蓋（${y > 0 ? '上' : '下'}・外）`, y, 0, r, 0.06, 0.07, 10), cylX(`ひじの軸の蓋（${y > 0 ? '上' : '下'}・内）`, y, 0, r, -0.07, -0.06, 10)]);
const E = (id, name, size, pieces) => ({ id, name, cat: 'ひじ', size, pieces: pieces.map(pc => ({ ...L, ...pc, pivot: pc.pivot ?? 'none' })) });

/** ひじ当て：節の後ろ（−z）の板。上は P1 の高さから、下は P2 の下まで、外へ反る */
const guard = (name, z0 = -0.03, z1 = -0.068, y0 = -0.068, y1 = 0.055, w = 0.05, o = {}) => hull(name, [
  [-w, y1, z0], [w, y1, z0], [-w * 0.8, y1 - 0.01, z1 + 0.012], [w * 0.8, y1 - 0.01, z1 + 0.012],
  [-w, 0, z1], [w, 0, z1], [-w * 0.7, y0, z1 + 0.02], [w * 0.7, y0, z1 + 0.02], [-w * 0.7, y0 + 0.02, z0], [w * 0.7, y0 + 0.02, z0]], o);

export default [
  E('elbowdouble', 'ひじ（2 重関節）', [0.14, 0.18, 0.09], [core(), ...knuckles(), ...caps()]),
  E('elbowguard', 'ひじ（2 重関節・ひじ当て）', [0.14, 0.18, 0.14], [core(), ...knuckles(), ...caps(), guard('ひじ当て')]),
  // 外の板：軸を短くし、その外を節の板が挟む（板の両端は軸と同じ丸み）
  E('elbowplates', 'ひじ（2 重関節・外の板）', [0.14, 0.18, 0.09], [core(0.036), cylX('ひじの上の軸', 0.05, 0, 0.042, -0.05, 0.05, 14, { color: DARK }), cylX('ひじの下の軸', -0.05, 0, 0.042, -0.05, 0.05, 14, { color: DARK }),
    ...[1, -1].map(s => hull(`ひじの外の板（${s > 0 ? '外' : '内'}）`, [0.05, -0.05].flatMap(y => Array.from({ length: 12 }, (_, k) => k * Math.PI / 6).flatMap(a => [0.05, 0.062].map(x => [s * x, y + 0.04 * Math.sin(a), 0.04 * Math.cos(a)])))))]),
  // 太い節：真ん中の節が太く、暗い帯（前は曲げの内側なので出さない）
  E('elbowthick', 'ひじ（2 重関節・太い節）', [0.14, 0.18, 0.11], [core(0.046, 0.026, DARK), ...knuckles(), ...caps(),
    hull('ひじの節の背', [[-0.046, 0.04, -0.026], [0.046, 0.04, -0.026], [-0.04, 0.03, -0.05], [0.04, 0.03, -0.05], [-0.04, -0.04, -0.05], [0.04, -0.04, -0.05], [-0.046, -0.05, -0.026], [0.046, -0.05, -0.026]])]),
  // とがったひじ当て：後ろへ段付きでとがる
  E('elbowspike', 'ひじ（2 重関節・とがったひじ当て）', [0.14, 0.18, 0.17], [core(), ...knuckles(), ...caps(), guard('ひじ当て', -0.03, -0.062, -0.066, 0.05, 0.046),
    hull('ひじ当ての角', [[-0.026, 0.02, -0.06], [0.026, 0.02, -0.06], [-0.026, -0.05, -0.06], [0.026, -0.05, -0.06], [0, -0.02, -0.105], [-0.01, -0.058, -0.088], [0.01, -0.058, -0.088]], { color: DARK })]),
  // 差し色のひじ当て
  E('elbowaccent', 'ひじ（2 重関節・差し色のひじ当て）', [0.14, 0.18, 0.14], [core(), ...knuckles(), ...caps(), guard('ひじ当て', -0.03, -0.068, -0.068, 0.055, 0.05, { color: ACCENT })]),
];
