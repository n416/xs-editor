// ひじ（中間の節、骨 elbow）：中は 2 重関節（xs-editor/doublejoint.js）だが、外からは 2 重に見せない。2 本の軸と節は装甲の覆いの中に隠し、
// 横の覆いの真ん中に丸い蓋を 1 つだけ付ける（1 つの関節に見える）。前腕の上の端は装甲の色の丸いお椀（前腕の上の丸い装甲に見える）。
// 原点はひじの中心 E。上の軸 P1（y +0.05）と下の軸 P2（y −0.05）の横の円柱（半径 0.042、x ±0.062）を節がつなぐ。
// 節は P1 のまわりに曲げの半分だけ回り、縦の軸のまわりにも向きを変えるので、覆いの寸法は次のとおり（関節チェックで確かめた範囲）：
//   ・上の端は P1 + 0.04（上腕の下の端 0.092 の下。節が縦の軸で回っても上腕に当たらない）
//   ・横の覆いは x 0.082〜0.1（前腕のお椀・上の輪より外）、下は P2 − 0.02（下の軸をほとんど隠す）。後ろの覆いも同じ高さまで
//   ・後ろ（曲がりの外側）は板で覆う。前（曲がりの内側）は上のほう（y 0.015〜0.06）だけ：前腕が前へ曲がって P2 + 0.057 まで上がってくる
// 真ん中の部品（回転の中心 fore）は前後・左右に対称にする（その箱の中心がひじの中心になる）。
import { hull, cylX } from '../limb/kit.js';
import { DARK, BLACK, MAIN, ACCENT } from '../../xsasm-lib.js';

const L = { bone: 'elbow', pivot: 'none' };
const knuckles = () => [cylX('ひじの上の軸', 0.05, 0, 0.042, -0.062, 0.062, 14, { color: DARK }), cylX('ひじの下の軸', -0.05, 0, 0.042, -0.062, 0.062, 14, { color: DARK })];
/** 節の真ん中（回転の中心）：前後・左右に対称な箱 */
const core = () => hull('ひじの節', [[-0.04, 0.05, -0.026], [0.04, 0.05, -0.026], [-0.04, 0.05, 0.026], [0.04, 0.05, 0.026], [-0.04, -0.05, -0.026], [0.04, -0.05, -0.026], [-0.04, -0.05, 0.026], [0.04, -0.05, 0.026]], { color: BLACK, pivot: 'fore' });
const inner = () => [core(), ...knuckles()];
/** 横の覆い（角ばった）：x 0.082〜0.1、外の面は少し丸い。w は外の面の出 */
const sidesBox = (w = 0.098, o = {}) => [1, -1].map(s => hull(`ひじの覆い（${s > 0 ? '外' : '内'}）`, [[0.082, 0.09, -0.045], [0.082, 0.09, 0.046], [0.082, -0.07, -0.045], [0.082, -0.07, 0.046],
  [w - 0.006, 0.088, -0.05], [w - 0.006, 0.088, 0.05], [w - 0.006, -0.068, -0.05], [w - 0.006, -0.068, 0.05], [w, 0.07, -0.035], [w, 0.07, 0.034], [w, -0.05, -0.035], [w, -0.05, 0.034]].map(p => [s * p[0], p[1], p[2]]), o));
/** 横の覆い（丸い円盤） */
const sidesRound = (o = {}) => [1, -1].map(s => hull(`ひじの丸い覆い（${s > 0 ? '外' : '内'}）`, Array.from({ length: 16 }, (_, k) => k * Math.PI / 8)
  .flatMap(a => [[0.082, 0.08], [0.098, 0.07]].map(([x, r]) => [s * x, 0.01 + Math.max(-0.08, Math.min(0.08, r * Math.sin(a))), -0.002 + r * 0.66 * Math.cos(a)])), o));
/** 横の丸い蓋（覆いの真ん中に 1 つ。1 つの関節に見せる） */
const caps = (x = 0.098, r = 0.024, o = {}) => [1, -1].map(s => cylX(`ひじの蓋（${s > 0 ? '外' : '内'}）`, 0.01, 0, r, s > 0 ? x - 0.004 : -x - 0.008, s > 0 ? x + 0.008 : -x + 0.004, 12, { color: MAIN, ...o }));
/** 後ろの覆い：左右の覆いをつなぐ板。d は後ろへの出 */
const back = (d = 0.074, o = {}) => hull('ひじの覆い（後ろ）', [[-0.094, 0.088, -0.03], [0.094, 0.088, -0.03], [-0.094, -0.07, -0.03], [0.094, -0.07, -0.03],
  [-0.09, 0.084, d - 0.138], [0.09, 0.084, d - 0.138], [-0.09, -0.066, d - 0.138], [0.09, -0.066, d - 0.138], [-0.06, 0.07, -d], [0.06, 0.07, -d], [-0.06, -0.05, -d], [0.06, -0.05, -d]], o);
/** 前の覆い（上のほうだけ。下は前腕が曲がって入ってくる） */
// 上の角は上の軸 P1 から 0.042（軸の太さ）以内に収める：節を曲げると前の覆いは P1 のまわりを上へ回り、それより外の角は上腕の裾に入る
const front = (o = {}) => hull('ひじの覆い（前）', [[-0.084, 0.06, 0.026], [0.084, 0.06, 0.026], [-0.084, 0.015, 0.026], [0.084, 0.015, 0.026],
  [-0.08, 0.06, 0.038], [0.08, 0.06, 0.038], [-0.08, 0.032, 0.048], [0.08, 0.032, 0.048], [-0.08, 0.018, 0.048], [0.08, 0.018, 0.048]], { color: DARK, ...o });
const E = (id, name, size, pieces) => ({ id, name, cat: 'ひじ', size, pieces: pieces.map(pc => ({ ...L, ...pc, pivot: pc.pivot ?? 'none' })) });

export default [
  E('elbowdouble', 'ひじ（角ばった覆い）', [0.21, 0.14, 0.15], [...inner(), ...sidesBox(), back(), front(), ...caps()]),
  // ひじ当て：後ろの覆いがさらに外へ反って下へ伸びる
  E('elbowguard', 'ひじ（ひじ当て）', [0.21, 0.15, 0.17], [...inner(), ...sidesBox(), back(), front(), ...caps(),
    hull('ひじ当て', [[-0.07, 0.07, -0.07], [0.07, 0.07, -0.07], [-0.075, -0.035, -0.07], [0.075, -0.035, -0.07], [-0.055, 0.05, -0.095], [0.055, 0.05, -0.095], [-0.06, -0.045, -0.092], [0.06, -0.045, -0.092], [-0.04, -0.06, -0.08], [0.04, -0.06, -0.08]])]),
  E('elbowplates', 'ひじ（丸い覆い）', [0.21, 0.14, 0.15], [...inner(), ...sidesRound(), back(), front(), ...caps(0.098, 0.03)]),
  // 厚い覆い：横の覆いが厚く、後ろに暗い帯
  E('elbowthick', 'ひじ（厚い覆い）', [0.23, 0.14, 0.16], [...inner(), ...sidesBox(0.108), back(0.08), front(), ...caps(0.108, 0.026),
    hull('ひじの覆いの帯', [[-0.08, 0.035, -0.074], [0.08, 0.035, -0.074], [-0.08, 0.015, -0.074], [0.08, 0.015, -0.074], [-0.07, 0.035, -0.085], [0.07, 0.035, -0.085], [-0.07, 0.015, -0.085], [0.07, 0.015, -0.085]], { color: DARK })]),
  // とがったひじ当て：後ろへ段付きでとがる
  E('elbowspike', 'ひじ（とがったひじ当て）', [0.21, 0.14, 0.21], [...inner(), ...sidesBox(), back(), front(), ...caps(),
    hull('ひじ当ての角', [[-0.03, 0.06, -0.07], [0.03, 0.06, -0.07], [-0.03, -0.03, -0.07], [0.03, -0.03, -0.07], [0, 0.01, -0.135], [-0.012, -0.02, -0.105], [0.012, -0.02, -0.105]], { color: DARK })]),
  // 差し色：後ろの覆いが差し色
  E('elbowaccent', 'ひじ（差し色のひじ当て）', [0.21, 0.14, 0.15], [...inner(), ...sidesBox(), back(0.074, { color: ACCENT }), front(), ...caps()]),
];
