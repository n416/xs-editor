const fistPath = k => [[0.014, -0.54], [-0.064, -0.537 - 0.004 * (k - 1)], [-0.077 - 0.006 * (k - 1), -0.497], [-0.044, -0.48]];
const fistThumb = () => finger('親指', [[-0.02, -0.468, 0.056], [-0.062, -0.488, 0.07], [-0.086, -0.516, 0.064]], 0, 0.027, 0.027, 0.85);

