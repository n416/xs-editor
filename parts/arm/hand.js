const palm = () => hull('手のひら', [[-0.036, -0.46, -0.044], [-0.036, -0.46, 0.048], [-0.036, -0.533, -0.046], [-0.036, -0.533, 0.05], [0.002, -0.458, -0.044], [0.002, -0.458, 0.048], [0.002, -0.538, -0.05], [0.002, -0.538, 0.056]], { color: DARK });
const ZS = [0.045, 0.017, -0.011, -0.038];
