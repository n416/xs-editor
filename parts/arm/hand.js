// 手（前腕の骨 fore、前腕と一緒に動く。ゲームの手の骨は無い）。原点はひじの中心 E、手首は y −0.45。
// 腕を下ろした姿勢で、手の甲は外（+x）、手のひらは内（−x）、親指は前（+z）。
// 握った手：指は付け根（手の甲の下の端）から内へ曲がり（基節は水平）、中節は上へ、末節は手のひらへ戻る。指の中の穴は前後（z）に通り、
//   中心 G = (−0.046, −0.531)、半径 0.018（下の寸法の 1.35 倍、外へ 0.02）：ライフルなどの握りはここを前後に通す（ゲームの右手の握りの中心）。指は穴のまわりを、穴の縁に沿って回る。
// 開いた手：指は下へ伸び、少し内へ曲がる。
// 指は 4 本＋親指、関節ごとに 1 個（角を落とした角柱）。
import { hull, seg } from '../limb/kit.js';
import { DARK, BLACK, MAIN, ACCENT } from '../../xsasm-lib.js';

const F = { bone: 'fore', pivot: 'none' };
// 形は手首 W = (0, −0.45, 0) を中心に K 倍して置く（指の点は下の小さい寸法で書いてある）
// さらに外（+x）へ HX ずらす（握った指が内へ出すぎて、広い横スカートに入らないよう）
const K = 1.35, W = [0, -0.45, 0], HX = 0.02;
const grow = pl => { const nw = pl[0] * W[0] + pl[1] * W[1] + pl[2] * W[2]; return [pl[0], pl[1], pl[2], nw + K * (pl[3] - nw) + pl[0] * HX]; };
const HD = (id, name, size, pieces) => ({ id, name, cat: '手', size: size.map(v => v * K), pieces: pieces.map(pc => ({ ...F, ...pc, planes: pc.planes.map(grow) })) });
const add = (a, b) => a.map((v, i) => v + b[i]);
/** 関節の点の並び pts（[x, y] は z の位置、[x, y, z] はそのまま）を、少し重ねてつなぐ指。w 幅（z）、h 厚み、最後の節は tip 倍に細る */
function finger(name, pts, z, w = 0.025, h = 0.029, tip = 0.8, o = { color: DARK }) {
  const P3 = pts.map(p => (p.length > 2 ? p : [p[0], p[1], z])), out = [];
  for (let i = 0; i + 1 < P3.length; i++) {
    const a = P3[i], b = P3[i + 1], d = b.map((v, k) => v - a[k]), L = Math.hypot(...d), e = d.map(v => v / L * 0.006);
    out.push(seg(`${name}（${i + 1}）`, add(a, e.map(v => -v)), add(b, e), w, h, [0, 0, 1], o, 1, i + 2 === P3.length ? tip : 1));
  }
  return out;
}
/** 手の甲：手首の端から指の付け根まで、外の面は外へ反る。armor で厚く、指の付け根の上まで */
