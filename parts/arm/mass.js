// 厚い塊の腕（上腕は骨 arm、前腕は骨 fore）：細い筒をやめ、装甲そのものが腕の太さ。上半身の厚い殻（parts/upper/mass.js）と組む。
// 原点はひじの中心 E。殻は「角のある断面をつなぐ形」（partgeo.js の loft の pts）：上腕と前腕で角の並びが同じなので、稜線がひじをまたいで続く。
// 角の並び：前の中央・前の端・角・横・後ろの角・後ろの中央（内と外は対称）。
// 役目：前腕は上腕より太い（手を動かす機械と武装の台が入る）。いちばん太いのはひじのすぐ下で、手首へ細る。前腕の外の面に武装の台。
// 関節まわりの決まり（軸受け・付け根・上のお椀・手首の輪）は、今までの上腕・前腕と同じ物を付ける。寸法は [独自]（今までの腕の半分の幅：上腕 0.078・前腕 0.10）
import { cylX, cylY, hull } from '../limb/kit.js';
import { piece, planesFromPoints, DARK, MAIN } from '../../xsasm-lib.js';
import { inner, back as elbowBack } from './elbow.js';

const shell = (name, secs, o = {}) => ({ name, kind: 'loft', secs, color: MAIN, pos: [0, 0, 0], ...o });
const A = { bone: 'arm', pivot: 'none' }, F = { bone: 'fore', pivot: 'none' };
// 上の 1/3 は肩の付け根の塊（issue #218「関節がおもちゃっぽい」）：肩アーマーの裾（y 0.35）の下に、半幅 0.105 の柱だけが出て、帽子の下に棒を差した
// ように見えた。重機のブームの根元のように、上へ行くほど太く・外へ寄る塊にして、肩アーマーの中へ入れる（内の面は胸の側へ広げない：x の中心を外へずらす）
const sec = (y, k, cx, pts) => ({ y, x: cx, pts: pts.map(([x, z]) => [x * k, z * k]) });
const UB = [[0, 0.105], [0.062, 0.098], [0.1, 0.055], [0.105, -0.035], [0.07, -0.092], [0, -0.102]];
const UPPER = [
  { y: 0.1, pts: [[0, 0.085], [0.05, 0.08], [0.082, 0.045], [0.088, -0.03], [0.06, -0.075], [0, -0.085]] },
  sec(0.17, 1, 0, UB),                     // 柱：ここから上が付け根の塊
  sec(0.3, 1.3, 0.03, UB),                 // 付け根の塊：上へ太く・外へ（内の面はほぼそのまま）
  sec(0.4, 1.48, 0.045, UB),               // 肩アーマーの裾（y 0.35）の上
  sec(0.47, 1.5, 0.05, UB),                // 肩アーマーの中
];
const FORE = [
  { y: -0.1, pts: [[0, 0.09], [0.06, 0.088], [0.112, 0.05], [0.118, -0.035], [0.075, -0.08], [0, -0.09]] },        // 上の端：ひじの受けの板がこの横の面から上がるので、横はその幅まで張る
  { y: -0.2, pts: [[0, 0.125], [0.075, 0.115], [0.118, 0.06], [0.122, -0.04], [0.08, -0.105], [0, -0.115]] },     // いちばん太い
  { y: -0.36, pts: [[0, 0.11], [0.065, 0.1], [0.1, 0.055], [0.105, -0.035], [0.07, -0.09], [0, -0.1]] },
  { y: -0.43, pts: [[0, 0.075], [0.045, 0.07], [0.07, 0.04], [0.074, -0.025], [0.05, -0.062], [0, -0.07]] },      // 手首
];
const CUFF = [
  { y: -0.445, pts: [[0, 0.08], [0.048, 0.075], [0.075, 0.043], [0.079, -0.027], [0.054, -0.067], [0, -0.075]] },
  { y: -0.405, pts: [[0, 0.092], [0.055, 0.086], [0.086, 0.048], [0.09, -0.03], [0.06, -0.076], [0, -0.085]] },
];
const J = { color: DARK };

// ---- ひじ（issue #218「関節がおもちゃっぽい」）：上腕と前腕の間に、どちらより細い節の箱と前の暗い溝・前腕の上の丸いお椀が見え、
// 2 重関節の節がむき出しの模型に見えた。足首（parts/leg/mass.js の足首の受け）と同じ、重機の腕のつなぎの作りにする：
//   ・前腕（太い側、骨 fore）の横の壁が、厚さの決まった平らな板としてそのまま上へ伸び、下の軸 P2 を中心とした半円で終わる（ひじの受け）
//   ・節（骨 elbow）の横は、上腕の横の面の続きの平らな板が下りて、P2 を中心とした半円で終わる（ひじの節の板）。前腕の受けの内の層
//   ・78° までは下の軸だけが曲がる（doublejoint.js）ので、外からは P2 の 1 つの軸で曲がって見える。前（曲がりの内側）は開ける
// 板の面は少し傾ける（垂直にしない）：受けは上へ外へ、節の板は下へ内へ 0.05。軸の端の蓋・ピンは付けない。寸法は [独自] ----
const P2Y = -0.05, LEAN = 0.05, PT = 0.022;
/** 半円（中心の高さ cy、半径 R、up で上へ・でなければ下へ張り出す）の [y, z] */
const arc = (cy, R, up, n = 12) => Array.from({ length: n + 1 }, (_, k) => (k * 180 / n - 90) * Math.PI / 180).map(a => [cy + (up ? 1 : -1) * R * Math.cos(a), R * Math.sin(a)]);
const slab = (name, side, outer, o) => [1, -1].map(s => piece(`${name}（${s > 0 ? '外' : '内'}）`,
  planesFromPoints(side.flatMap(([y, z]) => [[s * outer(y, z), y, z], [s * (outer(y, z) - PT), y, z]])), o));
/** 前腕の受け：外の面は前腕の上の端（y −0.1）の横の面（前の角 [0.112, 0.05]〜横 [0.118, −0.035]）と同じ面。前腕の中（y −0.13）から上がり、P2 を中心とした半径 0.062 の半円 */
const elbowYoke = () => slab('ひじの受け', [[-0.13, 0.05], [-0.13, -0.05], ...arc(P2Y, 0.062, true)],
  (y, z) => 0.1154 - 0.0706 * z + LEAN * (y + 0.1), { ...F });
/** 節の板：外の面は上腕の下の端（y 0.1）の横の面（前の角 [0.082, 0.045]〜横 [0.088, −0.03]）の続き。上腕の下の端のすぐ下（y 0.088）から下りて、P2 を中心とした半径 0.045 の半円 */
const linkPlates = () => slab('ひじの節の板', [[0.088, 0.048], [0.088, -0.048], ...arc(P2Y, 0.045, false)],
  (y, z) => 0.0856 - 0.08 * z + LEAN * (y - 0.1), { bone: 'elbow' });

export default [
  // ひじ：中の 2 重関節（節）は今までと同じ道具、2 本の軸は節の板の間に収まる長さ（±0.04：前腕がひねられて曲がっても受けの板に届かない）。横は節の板（上の決まり）、後ろ（曲がりの外側）は今までの後ろの覆い。
  // 前の暗い覆いは外した（前は曲がりの内側で開ける）。前腕の受けは前腕の部品に入っている
  { id: 'elbowmass', name: 'ひじ（厚い覆い・蓋なし）', cat: 'ひじ', size: [0.23, 0.16, 0.17],
    pieces: [inner()[0], ...[0.05, P2Y].map((y, k) => cylX(`ひじの${k ? '下' : '上'}の軸`, y, 0, 0.042, -0.04, 0.04, 14, J)), ...linkPlates(), elbowBack(0.086)].map(pc => ({ bone: 'elbow', ...pc, pivot: pc.pivot ?? 'none' })) },
  { id: 'upperarmmass', name: '上腕（厚い塊）', cat: '上腕', size: [0.21, 0.4, 0.21], pieces: [
    shell('上腕の殻', UPPER),
    cylY('上腕の軸受け', 0, 0, 0.056, 0.092, 0.13, 14, J),
    cylX('上腕の付け根', 0.5, 0, 0.045, -0.13, -0.02, 10, J),
  ].map(pc => ({ ...A, ...pc })) },
  { id: 'forearmmass', name: '前腕（厚い塊と武装の台）', cat: '前腕', size: [0.25, 0.38, 0.24], pieces: [
    shell('前腕の殻', FORE),
    shell('袖口の輪', CUFF, J),
    // 武装の台：外の面に一段出た厚い板（前腕の飾り・持たない武器はここに付く）
    hull('武装の台', [[0.1, -0.16, 0.055], [0.1, -0.16, -0.05], [0.1, -0.33, 0.045], [0.1, -0.33, -0.04], [0.142, -0.18, 0.04], [0.142, -0.18, -0.036], [0.136, -0.31, 0.034], [0.136, -0.31, -0.03]], J),
    ...elbowYoke(),
    // 前腕の軸受け：下の軸 P2 と同じ芯の太い筒（節の板の間）。どう曲げても下の軸を包んだまま（前腕が節から離れない）
    cylX('前腕の軸受け', P2Y, 0, 0.042, -0.045, 0.045, 20, J),
    cylY('手首', 0, 0, 0.042, -0.475, -0.42, 12, J),
  ].map(pc => ({ ...F, ...pc })) },
];
