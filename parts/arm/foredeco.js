const F = { bone: 'fore', pivot: 'none' };
// 前腕と同じく WX 倍に太らせて置く（太った前腕の面に付く）
const FD = (id, name, size, pieces) => ({ id, name, cat: '前腕の飾り', size, pieces: pieces.map(pc => ({ ...F, ...widen(pc, WX) })) });
const unit = v => { const l = Math.hypot(...v); return v.map(x => x / l); };
/** 段付きのとげ：根元の台・胴・先（どれも根元 o から向き d へ）。長さ len、根元の太さ w */
function spike(name, o, d, len, w) {
  d = unit(d);
  const s = unit(Math.abs(d[1]) < 0.9 ? [d[2], 0, -d[0]] : [1, 0, 0]), n = unit([d[1] * s[2] - d[2] * s[1], d[2] * s[0] - d[0] * s[2], d[0] * s[1] - d[1] * s[0]]);
  const at = (t, a, b) => [0, 1, 2].map(i => o[i] + t * d[i] + a * s[i] + b * n[i]);
  const sq = (t, h) => [[h, h], [h, -h], [-h, h], [-h, -h]].map(([a, b]) => at(t, a, b));
  return [hull(`${name}の台`, [...sq(-0.045, w * 0.75), ...sq(0.018, w * 0.68)], { color: DARK }),
    hull(`${name}`, [...sq(0.012, w * 0.5), ...sq(len * 0.6, w * 0.3)]),
    hull(`${name}の先`, [...sq(len * 0.56, w * 0.32), at(len, 0, 0)], { color: DARK })];
}
/** 根元が後ろ（−z）の噴射口：外の輪 12 枚の板と奥の黒い板。o 根元、d 噴き出す向き、r 半径、len 長さ */
function nozzle(name, o, d, r, len) {
  d = unit(d);
  const s = unit([d[2], 0, -d[0]].some(v => Math.abs(v) > 1e-6) ? [d[2], 0, -d[0]] : [1, 0, 0]), n = unit([d[1] * s[2] - d[2] * s[1], d[2] * s[0] - d[0] * s[2], d[0] * s[1] - d[1] * s[0]]);
  const at = (t, rr, a) => [0, 1, 2].map(i => o[i] + t * d[i] + rr * (Math.cos(a) * s[i] + Math.sin(a) * n[i]));
  const out = [];
  for (let j = 0; j < 10; j++) {
    const a0 = (j - 0.1) * Math.PI / 5, a1 = (j + 1.1) * Math.PI / 5, pts = [];
    for (const a of [a0, a1]) pts.push(at(0, r * 0.8, a), at(0, r * 0.62, a), at(len, r, a), at(len, r * 0.82, a));
    out.push(hull(`${name}（${j + 1}）`, pts, { color: DARK }));
  }
  out.push(hull(`${name}の奥`, Array.from({ length: 10 }, (_, j) => [at(len * 0.25, r * 0.72, j * Math.PI / 5), at(len * 0.25 + 0.006, r * 0.72, j * Math.PI / 5)]).flat(), { color: BLACK }));
  return out;
}

