// マスク（見本 A）：鼻筋のある口の面。もう一つの頭ジェネレーター（見本 A、資料の正面の絵を写したもの）のマスクを、
// 点の集まりのまま持ってきた。中央に鼻筋の 1 面、左右の面は外へ向かって奥へ、下はあごを囲む枠が内の縁から奥へ下がる。
// 資料の単位（1 画素）を K に。目の高さの線を y 0、部品の奥（後ろの面）を z 0 にし、前が +z。
import { planesFromPoints, piece, MAIN } from '../xsasm-lib.js';

const K = 0.0008;
const both = pts => pts.flatMap(([x, y, z]) => x === 0 ? [[0, y, z]] : [[x, y, z], [-x, y, z]]);
const back = (pts, z) => pts.map(([x, y]) => [x, y, z]);
const front = [[0, -8, 90], [7.4, -9, 90], [11, -40, 91], [7.4, -66, 92], [0, -66, 92],   // 鼻筋（口の面の前の 1 面。目のまわりより前）
  [41.4, -16, 76], [35, -54, 71.4], [18, -82, 72], [7.8, -67, 84],                          // 左右の面の外の縁
  [15, -103, 64], [12.2, -79, 78], [13.9, -88.3, 76], [9.4, -104, 74], [0, -104, 58]];     // あごを囲む枠（内の縁から奥へ下がる）
const raw = both([...front, ...back(front.filter(([x]) => x > 10), 20)]);
const YC = -56, ZB = 20;                                                                    // 部品の中心（上下）と奥の面
const pts = raw.map(([x, y, z]) => [x * K, (y - YC) * K, (z - ZB) * K]);
export default {
  // 部位「マスク」（前は「あご」に入っていて、マスクを選ぶとあごが外れた）。mouth：殻の口もとの点に合わせる所（鼻筋の前面から 0.010 奥、高さは鼻筋の中ほど）と、
  // 面の倒れ。資料の頭は顔がほぼ垂直（上がわずかに奥）だが、8 度と書いて、殻の面より 10 度起こして置く：殻の面にぴったり寝かせると、上の平らな面が棚になって見えた。
  // 上は殻の面にほぼ沈み、下（あごを囲む枠）ほど前へ出る。置くときに殻の面の倒れへ回す（xsasm-random.js）
  id: 'maska', name: 'マスク（見本 A）', cat: 'マスク', size: [0.066, 0.077, 0.058], mouth: [(-40 - YC) * K, (91 - ZB) * K - 0.010, 8],
  pieces: [piece('口の面', planesFromPoints(pts))],
};
