// ブレードアンテナ（一本）：額の低い台座から立つ、薄く高い 1 枚の刃。前の縁を研いであり、先へ細り、後ろへ倒れる。y 0 が台座の底、前が +z
import { P, XH, XL, YH, YL, ZH, ZL, both, piece, rotXAt, MAIN } from '../xsasm-lib.js';

const T = 0.005;                                                   // 厚みの半分（x）
const BLADE = [
  XH(T), XL(-T),
  YL(0.0), ZL(-0.035), ZH(0.02),                                   // 根元：z −0.035〜0.02
  P([0, 0.32, 1], [0, 0, 0.02]),                                   // 前の縁：上へ向かって後ろへ
  P([0, 1, -0.05], [0, 0.26, 0]),                                  // 先の高さ
  P([0, 0.12, -1], [0, 0, -0.035]),                                // 後ろの縁：上へ向かって前へ（先で細る）
  ...both(P([1, 0.35, 1.2], [T, 0, 0.02])),                        // 前の縁を研ぐ
  ...both(P([1, 0.25, -1.2], [T, 0, -0.035])),                     // 後ろの縁も研ぐ
];
export default {
  id: 'horn', name: 'ブレードアンテナ（一本）', cat: 'トサカ', size: [0.05, 0.26, 0.09],
  pieces: [
    piece('台座', [YL(0), YH(0.012), ZL(-0.045), ZH(0.03), ...both(XH(0.025)), P([0, 0.5, 1], [0, 0, 0.03]), P([0, 0.5, -1], [0, 0, -0.045]), ...both(P([1, 0.7, 0], [0.025, 0, 0]))]),
    piece('刃', rotXAt(BLADE, 12, 0, -0.01)),
  ],
};
