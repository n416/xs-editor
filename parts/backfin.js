// 後ろびれ：頭の後ろに付ける縦の背びれ。前（+z）の小さな箱の台座から、薄い板が後ろ上へ伸び、先は後ろへ流れて尖る。
// 板の面は左右を向く（x が厚み 0.02）。台座の前面が z 0（取り付け面）、後ろへ −z。高さは台座の底 y −0.025 から峰 y 0.175
import { P, XH, XL, YH, YL, ZH, ZL, both, box, piece, MAIN, DARK } from '../xsasm-lib.js';

// 板の側面の形（y-z）：根元 A(z −0.012, y 0.01) → 峰 B(z −0.08, y 0.175)。上の縁は峰から後ろへ下がりながら先 C(z −0.25, y 0.095) へ。
// 下の縁は台座の後ろ上の角 D(z −0.04, y 0.02) から後ろ上へ上がり、切れ込み N(z −0.134, y 0.086) から先へはほぼ水平に流れる。
// 板は 付け根（A・B・N・D）と 先（B・N・C の三角）の 2 個で、峰から切れ込みへ下りる継ぎ目（B→N）で接する（くの字の後ろびれ）
const SEAM = [0, 0.054, -0.089];                          // 継ぎ目の面の法線（B→N の線に垂直。付け根から見て後ろ上向き）
const ROOT = [
  XH(0.01), XL(-0.01),                                   // 厚み 0.02
  ZH(-0.008), YL(0.0),                                   // 根元：台座の中に埋める
  P([0, 0.068, 0.165], [0, 0.01, -0.012]),               // 前の縁：台座の上から後ろ上へ急に立ち上がる（A→B）
  P(SEAM, [0, 0.175, -0.08]),                             // 後ろ：継ぎ目（B→N）
  P([0, -0.10, -0.07], [0, 0.02, -0.04]),                // 下の縁：台座の後ろ上の角から切れ込みへ後ろ上へ（D→N）
];
const TIP = [
  XH(0.01), XL(-0.01),
  P(SEAM.map(v => -v), [0, 0.175, -0.08]),                // 前：継ぎ目（付け根と接する）
  P([0, 0.17, -0.08], [0, 0.175, -0.08]),                 // 上の縁：峰から先へ後ろへ流れて下がる（B→C）
  P([0, -0.116, -0.009], [0, 0.086, -0.134]),             // 下の縁：切れ込みから先へほぼ水平（N→C）
  ...both(P([1, 0, -0.071], [0.01, 0, -0.14])),           // 先：厚みも薄く（z −0.14 から先で刃になる）
];
export default {
  id: 'backfin', name: '後ろびれ', cat: '飾り', size: [0.05, 0.2, 0.25],
  pieces: [
    // 台座：前面が z 0 の小さな箱。後ろの角を落として少しすぼめる
    piece('台座', [...box(-0.025, 0.025, -0.025, 0.025, -0.04, 0), P([0, 1, -1], [0, 0.025, -0.032]), P([0, -1, -1], [0, -0.025, -0.032]), ...both(P([1, 0, -1], [0.025, 0, -0.032]))]),
    // 根元の金具：台座の上に乗る暗い低い箱。板はここから生える
    piece('根元', box(-0.016, 0.016, 0.015, 0.042, -0.04, -0.006), { color: DARK }),
    piece('付け根', ROOT),
    piece('先', TIP),
  ],
};
