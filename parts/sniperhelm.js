// 細身の頭：幅が狭く前後に長い卵形（狙撃用）。額は前へ伸びるくちばし形のひさしで、その下に狭いバイザーの溝（奥に暗い壁、正面だけ光る帯）。
// 顔は前下へとがるくさび形のあご。横は後ろ上がりの細長い頬の板。頭頂から後ろへ、低く長いひれ（後ろほど高い）。
// 広い面はどれも傾けてある。頭の中心が原点付近、前が +z。headshell より幅が狭く（±0.08）、前後に長い
import { P, YH, YL, ZH, ZL, ellipsoid, planesFromPoints, BLACK, DARK, GLOW, piece, pair } from '../xsasm-lib.js';

const C = [0, 0.04, -0.012];                                                // 卵の中心
const R = [0.078, 0.088, 0.15];                                             // 半径（幅・高さ・奥行き）
const ME = [0, 36, 72, 108, 144, 180, 216, 252, 288, 324];                  // 経線 10 本（0 が前）
const VT = 0.04, VB = 0.014;                                                // 溝の上端・下端
const GROOVE = [-80, -45, -15, 15, 45, 80];
const inset = d => [R[0] - d, R[1], R[2] - d];

// ひさし：上から見て前へとがる五角形、横から見て前下がりの薄いくさび
const peak = planesFromPoints([[-0.072, VT + 0.026, 0.01], [0.072, VT + 0.026, 0.01], [-0.046, VT + 0.016, 0.125], [0.046, VT + 0.016, 0.125], [0, VT + 0.01, 0.166],
  [-0.076, VT - 0.002, 0.01], [0.076, VT - 0.002, 0.01], [-0.047, VT - 0.002, 0.122], [0.047, VT - 0.002, 0.122], [0, VT - 0.002, 0.156]]);
// あご：前下へとがるくさび
const jaw = planesFromPoints([[-0.05, VB, 0.118], [0.05, VB, 0.118], [0, VB - 0.004, 0.136], [-0.016, -0.068, 0.104], [0.016, -0.068, 0.104], [0, -0.05, 0.126],
  [-0.058, VB, 0.02], [0.058, VB, 0.02], [-0.03, -0.062, 0.02], [0.03, -0.062, 0.02]]);
// 頬の板：後ろ上がりの細長い板（外へ少し張り出し、上の縁は内へ倒れる）
const cheek = planesFromPoints([[0.07, 0.03, 0.07], [0.082, 0.02, 0.03], [0.086, 0.04, -0.07], [0.078, 0.058, -0.075],
  [0.064, -0.03, 0.06], [0.076, -0.036, 0.0], [0.08, -0.02, -0.07], [0.06, 0.03, 0.06], [0.06, -0.03, 0.0], [0.064, 0.04, -0.07], [0.064, -0.02, -0.06]]);
// 頭頂のひれ：低く長い刃。頭の後ろの端を越えて、後ろへまっすぐ伸びる（高く立てたらモヒカンに見えた）
const TOP = C[1] + R[1];
const fin = planesFromPoints([[-0.009, TOP - 0.016, 0.06], [0.009, TOP - 0.016, 0.06], [0, TOP - 0.002, 0.05],
  [-0.011, TOP - 0.03, -0.1], [0.011, TOP - 0.03, -0.1], [0, TOP + 0.012, -0.11],
  [0, TOP + 0.008, -0.21], [0, TOP - 0.012, -0.2], [-0.004, TOP - 0.004, -0.17], [0.004, TOP - 0.004, -0.17],
  [-0.011, TOP - 0.05, -0.02], [0.011, TOP - 0.05, -0.02]]);

const sniperhelm = {
  id: 'sniperhelm', name: '細身の頭（くちばしのひさしと後ろのひれ）', cat: '頭蓋', size: [0.17, 0.22, 0.34],
  face: { eye: [0.027, 0.118], mouth: [-0.03, 0.118, 12], under: [-0.05, 0], brow: [0.06, 0.13], lift: 0.012 },
  pieces: [
    piece('頭蓋', [...ellipsoid(R, C, 10, [6, 30, 54, 76], 0, ME), YL(VT)]),
    piece('ひさし', peak, { color: DARK }),
    piece('頭頂のひれ', fin, { color: DARK }),
    piece('溝の奥', [...ellipsoid(inset(0.02), C, 10, [0], 0, GROOVE), YH(VT + 0.002), YL(VB - 0.002), ZL(-0.02)], { color: BLACK }),
    piece('目の帯', [...ellipsoid(inset(0.012), C, 10, [0], 0, [-30, 0, 30]), YH(0.033), YL(0.022), ZL(0.06)], { color: GLOW, glow: true, metal: 0, rough: 0.3 }),
    piece('あご', jaw),
    piece('後頭', [...ellipsoid(R, C, 10, [-14, -40], 0, [72, 108, 144, 180, 216, 252, 288]), YH(VT + 0.002), YL(-0.05), ZH(0.03)]),
    ...pair('頬の板', cheek),
  ],
};
const sniperhelmplain = { ...sniperhelm, id: 'sniperhelmplain', name: '細身の頭（くちばしのひさしと後ろのひれ・目なし）', pieces: sniperhelm.pieces.filter(pc => pc.name !== '目の帯') };
export default [sniperhelm, sniperhelmplain];
