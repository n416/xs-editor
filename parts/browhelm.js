// まゆと頬当ての頭：細い卵形の頭蓋の下に、暗い顔の芯。芯の前の面は左右半分ずつで、鼻の所がいちばん前、耳の側へ後ろに回る
// （上から見ると 八 の字、頭に載せた大きさで約 30 度）。上の辺が前に出て、少し下を向く。目（五角形）はその面の上に作る。
// 目の上に まゆのひさし（中心が厚く低い、耳の側は薄く高い）。横は 耳の塊（六角形の厚い板）と、その下から あごの先へ回り込む あご当て（段になる）。
// 目の下に、中心の稜が下へ行くほど前に出るマスクと、その下で前へ出る あご。頭頂から後頭へ 背の稜、後頭に V の谷のある装甲（下は外へ広がる）。
// 点は頭に載せた大きさ（殻の倍率 3 × 3.1 × 2.2 を掛けたあと。幅 0.6・高さ 0.67 ほど）で書き、W() で部品の座標に直す：角度が見たままになる。
// 頭の中心が原点付近、前が +z
import { P, YH, YL, ZH, ellipsoid, planesFromPoints, mir, BLACK, DARK, GLOW, piece, pair } from '../xsasm-lib.js';

const K = [3, 3.1, 2.2];
const W = p => [p[0] / K[0], p[1] / K[1], p[2] / K[2]];
const hull = pts => planesFromPoints(pts.map(W), 1e-7);
const lr = pts => pts.flatMap(([x, y, z]) => (x === 0 ? [[0, y, z]] : [[-x, y, z], [x, y, z]]));

// ---- 頭蓋：卵（前が細い）。経線は中心線をまたぐ（正面に稜が立つ） ----
const C = W([0, 0.12, -0.02]), RF = W([0.24, 0.3, 0.31]), RB = W([0.255, 0.3, 0.29]);
const FRONT = [-75, -45, -15, 15, 45, 75], BACK = [105, 135, 165, 195, 225, 255];
const egg = lats => [...ellipsoid(RF, C, 12, lats, 0, FRONT), ...ellipsoid(RB, C, 12, lats, 0, BACK)];
const BROW_Y = 0.18 / K[1];                                             // 頭蓋の下の端（目の上）
const UNDER = P([0, -1 / K[1] * 3.1, -0.22], W([0, -0.15, -0.1]));      // 下面：首すじからあごへ下がる

// ---- 顔の芯（右半分）：前の面 = 目が載る面 ----
const FA = [[0, 0.12, 0.215], [0, 0, 0.195]], FB = [[0.2, 0.135, 0.1], [0.2, 0.015, 0.08]];   // 鼻の側の辺・耳の側の辺（上、下）
const core = hull([[-0.006, ...FA[0].slice(1)], [-0.006, ...FA[1].slice(1)], ...FA, ...FB, [-0.006, 0.12, 0], [-0.006, 0, 0], [0.2, 0.19, 0.085], [0.2, 0.19, 0], [0.2, 0.015, 0]]);   // 耳の側は上へ伸ばす（ひさしの下まで。前の面より奥）
const sub = (p, q) => p.map((v, i) => v - q[i]), FU = sub(FB[1], FA[1]), FV = sub(FA[0], FA[1]);
const FN = (n => { const l = Math.hypot(...n) * Math.sign(n[2]); return n.map(v => v / l); })([FU[1] * FV[2] - FU[2] * FV[1], FU[2] * FV[0] - FU[0] * FV[2], FU[0] * FV[1] - FU[1] * FV[0]]);   // 前の面の外向き（+z の側）
const onFace = (u, v, d) => FA[1].map((p, i) => p + u * FU[i] + v * FV[i] + d * FN[i]);        // u：鼻の側 0 → 耳の側 1、v：下 0 → 上 1、d：面から外へ
// 目：五角形（twineyes.js と同じ、写真で測った角の位置）。鼻の側の端は短い縦の辺、上の辺は耳の側の端が高い、下の辺は幅の 6 割で折れて耳の側へ上がる
const EYE = [[0, 0], [0.07, 0.17], [0.87, 0.33], [1, 0.2], [0.58, -0.03]].map(([x, y]) => [0.14 + x * 0.76, 0.3 + y * 1.45]);
const eye = hull(EYE.flatMap(([u, v]) => [onFace(u, v, 0.008), onFace(u, v, -0.03)]));

// ---- まゆのひさし（右半分）：下の辺は鼻の側の端が低く、耳の側の端が高い。中心は厚く、耳の側は薄い。目より前に出る ----
const brow = hull([[-0.006, 0.1, 0.288], [-0.006, 0.228, 0.302], [0.218, 0.178, 0.128], [0.24, 0.225, 0.11],
  [-0.006, 0.1, 0.05], [-0.006, 0.228, 0.05], [0.218, 0.178, 0], [0.24, 0.225, 0], [0.1, 0.24, 0.24]]);

// 横から見た輪郭（[z, y] の並び）を、点ごとの x に置く。shrink：輪郭を中心 c へ k 倍に縮める（外の面の面取り）
const ring = (prof, xs) => prof.map(([z, y], i) => [xs[i], y, z]);
const shrink = (prof, k, c) => prof.map(([z, y]) => [c[0] + (z - c[0]) * k, c[1] + (y - c[1]) * k]);
/** 厚い板：奥の輪（頭の中）・縁の輪・外の面の輪（縮めた輪郭） */
const slab = (prof, xin, xmid, xout, k, c) => hull([...ring(prof, xin), ...ring(prof, xmid), ...ring(shrink(prof, k, c), xout)]);

// ---- 耳の塊（右）：横から見て六角形。前の辺は上が前、後ろの辺は上が後ろ。外の面は前へ回る（後ろが外） ----
const EAR = [[0.1, 0.105], [0.075, -0.045], [0, -0.075], [-0.11, -0.03], [-0.13, 0.09], [-0.02, 0.145]];
const ear = slab(EAR, [0.17, 0.17, 0.17, 0.17, 0.17, 0.17], [0.258, 0.262, 0.272, 0.282, 0.28, 0.268], [0.282, 0.286, 0.296, 0.306, 0.304, 0.292], 0.74, [-0.015, 0.03]);
// ---- あご当て（右）：耳の塊の下から、あごの先へ前に回り込む板。耳の塊より 5 cm 内（段になる）。前の辺は下が前、下の辺は後ろが高い ----
const JAW = [[-0.06, -0.01], [0.12, 0], [0.215, -0.14], [0.14, -0.235], [-0.05, -0.17]];
const jaw = slab(JAW, [0.15, 0.13, 0.06, 0.05, 0.13], [0.235, 0.205, 0.118, 0.095, 0.2], [0.255, 0.225, 0.135, 0.11, 0.22], 0.82, [0.07, -0.11]);

// ---- マスク：中心の稜は下へ行くほど前に出る。左右の面は耳の側へ回る。目の下で芯より前に出て棚になる ----
const mask = hull(lr([[0, 0.02, 0.24], [0, -0.1, 0.265], [0.105, 0.03, 0.165], [0.09, -0.11, 0.185], [0.11, 0.03, 0], [0.09, -0.11, 0]]));
// ---- あご：マスクの下で 3 cm 前へ出る幅のある塊。稜は上が前（下へ行くほど引っ込む）。下へすぼまる ----
const chin = hull(lr([[0, -0.095, 0.295], [0, -0.225, 0.28], [0.075, -0.09, 0.235], [0.05, -0.235, 0.225], [0.08, -0.09, 0.05], [0.05, -0.235, 0.05]]));

// ---- 背の稜：頭頂の前から後頭へ、中心線の上を走る稜。後ろほど高く太く、後頭の装甲の谷の上で尾になって突き出る ----
const arc = (deg, k) => { const t = deg * Math.PI / 180, c = Math.cos(t); return [0.12 + 0.3 * k * Math.sin(t), -0.02 + (c > 0 ? 0.31 : 0.29) * k * c]; };   // 卵の中心線の上の点 [y, z]（0 度が前、90 度が頭頂）
const KEEL = [[40, 1.035, 0.03], [70, 1.06, 0.036], [100, 1.085, 0.044], [130, 1.115, 0.052], [155, 1.15, 0.06], [172, 1.23, 0.034]];
const keel = hull(KEEL.flatMap(([deg, k, w]) => { const [y, z] = arc(deg, k), [y0, z0] = arc(deg, 0.95); return [[0, y, z], [w, y0, z0], [-w, y0, z0]]; }));
// ---- 後頭の装甲（右半分）：卵より外に立つ板。上の辺は中心が低く、耳の側が高い（後ろから見て V の谷）。下は首すじへすぼまらず、外へ広がる（首の覆い） ----
const nape = hull([[-0.006, -0.02, -0.33], [0.156, 0.07, -0.274], [0.258, 0.13, -0.127], [-0.006, -0.17, -0.352], [0.18, -0.17, -0.302], [0.277, -0.15, -0.125],
  [-0.006, -0.02, -0.2], [0.2, 0.13, -0.08], [-0.006, -0.17, -0.2], [0.2, -0.15, -0.08]]);
// ---- 首の覆い（右半分）：後頭の装甲の裾に重なる、外へ広がる厚い帯（段になる） ----
const skirt = hull([[-0.006, -0.105, -0.36], [-0.006, -0.2, -0.385], [0.19, -0.105, -0.31], [0.205, -0.2, -0.33], [0.29, -0.09, -0.125], [0.305, -0.185, -0.125],
  [-0.006, -0.105, -0.2], [-0.006, -0.2, -0.2], [0.2, -0.09, -0.08], [0.2, -0.185, -0.08]]);

const browhelm = {
  id: 'browhelm', name: 'まゆと頬当ての頭（八の字の目）', cat: '頭蓋', size: [0.2, 0.22, 0.29],
  face: { eye: [0.021, 0.093], mouth: [-0.0226, 0.1177, -16], under: [-0.0584, -0.22], brow: [0.0735, 0.137], lift: 0.016 },   // 目：芯の前の面の中心線の所、口もと：マスクの稜（下が前へ出る）、額：ひさしの上の端
  pieces: [
    piece('頭蓋', [...egg([5, 28, 52, 76]), YL(BROW_Y)]),
    piece('後頭', [...egg([-28, 5]), YH(BROW_Y + 0.002), UNDER, ZH(0.08 / K[2])]),
    ...pair('顔の芯', core, { color: BLACK }),
    ...pair('目', eye, { color: GLOW, glow: true, metal: 0, rough: 0.3 }),
    ...pair('まゆのひさし', brow),
    ...pair('耳の塊', ear),
    ...pair('あご当て', jaw),
    piece('マスク', mask, { color: DARK }),
    piece('あご', chin),
    piece('背の稜', keel),
    ...pair('後頭の装甲', nape),
    ...pair('首の覆い', skirt, { color: DARK }),
  ],
};
// 目なし：光る目を外したもの（芯の面は残る）。目は別の部品を入れる
const browhelmplain = { ...browhelm, id: 'browhelmplain', name: 'まゆと頬当ての頭（目なし）', pieces: browhelm.pieces.filter(pc => !pc.name.startsWith('目')) };
export default [browhelm, browhelmplain];
