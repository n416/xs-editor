// まゆと頬当ての頭：細い卵形の頭蓋の下に、暗い顔の芯。芯の前の面は左右半分ずつで、鼻の所がいちばん前、耳の側へ後ろに回る
// （上から見ると 八 の字、頭に載せた大きさで約 30 度）。上の辺が前に出て、少し下を向く。目（五角形）はその面の上に作る。
// 目の上に まゆのひさし（中心が厚く低い、耳の側は薄く高い）、目の横から下に厚い頬当て（下へ向かって内へすぼまる）、
// 目の下に、中心の稜が下へ行くほど前に出るマスクと、あごの先の突起。
// 点は頭に載せた大きさ（殻の倍率 3 × 3.1 × 2.2 を掛けたあと。幅 0.6・高さ 0.67 ほど）で書き、W() で部品の座標に直す：角度が見たままになる。
// 頭の中心が原点付近、前が +z
import { P, YH, YL, ZH, ellipsoid, planesFromPoints, mir, BLACK, DARK, GLOW, piece, pair } from '../xsasm-lib.js';

const K = [3, 3.1, 2.2];
const W = p => [p[0] / K[0], p[1] / K[1], p[2] / K[2]];
const hull = pts => planesFromPoints(pts.map(W), 1e-7);
const lr = pts => pts.flatMap(([x, y, z]) => (x === 0 ? [[0, y, z]] : [[-x, y, z], [x, y, z]]));

// ---- 頭蓋：卵（前が細い）。経線は中心線をまたぐ（正面に稜が立つ） ----
const C = W([0, 0.12, -0.02]), RF = W([0.24, 0.3, 0.31]), RB = W([0.255, 0.3, 0.29]);
const FRONT = [-75, -45, -15, 15, 45, 75], BACK = [105, 135, 165, 195, 225, 255];
const egg = lats => [...ellipsoid(RF, C, 12, lats, 0, FRONT), ...ellipsoid(RB, C, 12, lats, 0, BACK)];
const BROW_Y = 0.18 / K[1];                                             // 頭蓋の下の端（目の上）
const UNDER = P([0, -1 / K[1] * 3.1, -0.22], W([0, -0.15, -0.1]));      // 下面：首すじからあごへ下がる

// ---- 顔の芯（右半分）：前の面 = 目が載る面 ----
const FA = [[0, 0.12, 0.215], [0, 0, 0.195]], FB = [[0.2, 0.135, 0.1], [0.2, 0.015, 0.08]];   // 鼻の側の辺・耳の側の辺（上、下）
const core = hull([[-0.006, ...FA[0].slice(1)], [-0.006, ...FA[1].slice(1)], ...FA, ...FB, [-0.006, 0.12, 0], [-0.006, 0, 0], [0.2, 0.19, 0.085], [0.2, 0.19, 0], [0.2, 0.015, 0]]);   // 耳の側は上へ伸ばす（ひさしの下まで。前の面より奥）
const sub = (p, q) => p.map((v, i) => v - q[i]), FU = sub(FB[1], FA[1]), FV = sub(FA[0], FA[1]);
const FN = (n => { const l = Math.hypot(...n) * Math.sign(n[2]); return n.map(v => v / l); })([FU[1] * FV[2] - FU[2] * FV[1], FU[2] * FV[0] - FU[0] * FV[2], FU[0] * FV[1] - FU[1] * FV[0]]);   // 前の面の外向き（+z の側）
const onFace = (u, v, d) => FA[1].map((p, i) => p + u * FU[i] + v * FV[i] + d * FN[i]);        // u：鼻の側 0 → 耳の側 1、v：下 0 → 上 1、d：面から外へ
// 目：五角形（twineyes.js と同じ、写真で測った角の位置）。鼻の側の端は短い縦の辺、上の辺は耳の側の端が高い、下の辺は幅の 6 割で折れて耳の側へ上がる
const EYE = [[0, 0], [0.07, 0.17], [0.87, 0.33], [1, 0.2], [0.58, -0.03]].map(([x, y]) => [0.14 + x * 0.76, 0.3 + y * 1.45]);
const eye = hull(EYE.flatMap(([u, v]) => [onFace(u, v, 0.008), onFace(u, v, -0.03)]));

// ---- まゆのひさし（右半分）：下の辺は鼻の側の端が低く、耳の側の端が高い。中心は厚く、耳の側は薄い。目より前に出る ----
const brow = hull([[-0.006, 0.1, 0.288], [-0.006, 0.228, 0.302], [0.218, 0.178, 0.128], [0.24, 0.225, 0.11],
  [-0.006, 0.1, 0.05], [-0.006, 0.228, 0.05], [0.218, 0.178, 0], [0.24, 0.225, 0], [0.1, 0.24, 0.24]]);

// ---- 頬当て（右）：厚い塊。前の面は耳の側へ回り、下へ向かって内へすぼまる。外の面は中ほどがいちばん張り出す ----
const cheek = hull([[0.185, 0.085, 0.13], [0.12, -0.2, 0.2], [0.265, 0.1, 0.07], [0.245, -0.17, 0.135], [0.3, -0.04, 0.02],
  [0.255, 0.12, -0.1], [0.235, -0.15, -0.08], [0.12, 0.1, -0.08], [0.1, -0.18, -0.05]]);

// ---- マスク：中心の稜は下へ行くほど前に出る。左右の面は耳の側へ回る。目の下で芯より前に出て棚になる ----
const mask = hull(lr([[0, 0.015, 0.235], [0, -0.19, 0.275], [0.11, 0.03, 0.165], [0.085, -0.21, 0.2], [0.12, 0.03, 0], [0.1, -0.2, 0]]));
const nose = hull(lr([[0, 0.075, 0.258], [0, -0.17, 0.302], [0.02, 0.065, 0.24], [0.032, -0.165, 0.284], [0.02, 0.065, 0.1], [0.032, -0.165, 0.1]]));   // 鼻筋：目の間からあごへ、下ほど太く前へ
const chin = hull(lr([[0.032, -0.14, 0.27], [0.022, -0.218, 0.275], [0.026, -0.152, 0.325], [0.018, -0.203, 0.318], [0.032, -0.14, 0.2], [0.022, -0.218, 0.2]]));

const browhelm = {
  id: 'browhelm', name: 'まゆと頬当ての頭（八の字の目）', cat: '頭蓋', size: [0.2, 0.22, 0.29],
  face: { eye: [0.021, 0.093], mouth: [-0.029, 0.131, -14], under: [-0.0584, -0.22], brow: [0.0735, 0.137], lift: 0.016 },   // 目：芯の前の面の中心線の所、口もと：鼻筋の稜（下が前へ出る）、額：ひさしの上の端
  pieces: [
    piece('頭蓋', [...egg([5, 28, 52, 76]), YL(BROW_Y)]),
    piece('後頭', [...egg([-28, 5]), YH(BROW_Y + 0.002), UNDER, ZH(0.08 / K[2])]),
    ...pair('顔の芯', core, { color: BLACK }),
    ...pair('目', eye, { color: GLOW, glow: true, metal: 0, rough: 0.3 }),
    ...pair('まゆのひさし', brow),
    ...pair('頬当て', cheek),
    piece('マスク', mask, { color: DARK }),
    piece('鼻筋', nose),
    piece('あごの先', chin),
  ],
};
// 目なし：光る目を外したもの（芯の面は残る）。目は別の部品を入れる
const browhelmplain = { ...browhelm, id: 'browhelmplain', name: 'まゆと頬当ての頭（目なし）', pieces: browhelm.pieces.filter(pc => !pc.name.startsWith('目')) };
export default [browhelm, browhelmplain];
