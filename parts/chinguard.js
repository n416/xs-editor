// あご当て：顔の下に付ける小さなあご。前から見ると下へすぼまるくさび（六角形の輪郭）、上から見ると前の角を落とし
// 後ろも少しすぼめて、両脇の面が後ろへ流れる。前面は下へ行くほど少し引っ込む。前面には横長の口の溝が 3 本
//（溝と溝の間の桟、溝の両端の柱、奥に暗い壁。本当のくぼみ）。前面の縦の角は 45 度で落とし、桟の前の縁も小さく落とす。
// 上面（y 0）が平らな取り付け面で、下へ −y
import { P, XH, XL, YH, YL, ZL, both, piece, pair, BLACK } from '../xsasm-lib.js';

const ZF = 0.05, SLOPE = 0.15;                        // 前面：上端 z 0.05、下へ行くほど引っ込む（z = ZF + SLOPE·y）
const FRONT = d => P([0, -SLOPE, 1], [0, 0, ZF - d]); // 前面と平行な面（d = 前面からの引っ込み）
const zf = y => ZF + SLOPE * y;
// 外形（すべての piece が共有する面）：幅 0.14・高さ 0.1・奥行き 0.1
const BODY = [
  YH(0), YL(-0.1), ZL(-0.05), FRONT(0),
  ...both(XH(0.07)),                                  // 脇の平らな帯（いちばん広い所：y -0.02..-0.045、z -0.025..0.005）
  ...both(P([4, 3, 0], [0.07, -0.02, 0])),            // 上の張り出し：上面の縁 (x 0.055, y 0) から帯の上端 (0.07, -0.02) へ広がる
  ...both(P([11, -8, 0], [0.07, -0.045, 0])),         // 下へすぼまる脇：帯の下端 (0.07, -0.045) から底 (0.03, -0.1) へ
  ...both(P([5, 0, 2], [0.07, 0, 0.005])),            // 前の角の落とし（浅い）：前面は x ±0.052、帯の前端 z 0.005 で全幅
  ...both(P([1, 0, 1], [0.042, 0, ZF])),              // 前面の縦の角：45 度で 0.01 落とす（いちばん見せる面の角）
  ...both(P([5, 0, -2], [0.07, 0, -0.025])),          // 後ろへ流れる脇：帯の後端 z -0.025 から後面 x ±0.06 へすぼむ
  P([0, -0.65, 1], [0, -0.1, 0.02]),                  // 底の前の落とし：前面 y -0.07 から底 z 0.02 へ
  P([0, -1, -2], [0, -0.1, -0.035]),                  // 底の後ろの落とし：後面 y -0.07 から底 z -0.035 へ
];
// 口の溝 3 本：上から順に（上端, 下端）。溝の高さ 0.009、桟の高さ 0.007
const SLITS = [[-0.032, -0.041], [-0.048, -0.057], [-0.064, -0.073]];
const HALF = 0.036;                                   // 溝の半分の幅
const DEPTH = 0.012;                                  // 溝の深さ
const EDGE = 0.0025;                                  // 桟の前の縁の落とし
const bar = (top, bottom) => [...BODY, YH(top), YL(bottom), P([0, 1, 1], [0, top - EDGE, zf(top)]), P([0, -1, 1], [0, bottom + EDGE, zf(bottom)])];

export default {
  id: 'chinguard', name: 'あご当て', cat: 'あご', size: [0.14, 0.1, 0.1],
  pieces: [
    piece('上の板', [...BODY, YL(SLITS[0][0]), P([0, -1, 1], [0, SLITS[0][0] + EDGE, zf(SLITS[0][0])])]),       // いちばん上の溝より上
    piece('桟 1', bar(SLITS[0][1], SLITS[1][0])),
    piece('桟 2', bar(SLITS[1][1], SLITS[2][0])),
    piece('下の板', [...BODY, YH(SLITS[2][1]), P([0, 1, 1], [0, SLITS[2][1] - EDGE, zf(SLITS[2][1])])]),        // いちばん下の溝より下
    ...pair('口の脇', [...BODY, YH(SLITS[0][0]), YL(SLITS[2][1]), XL(HALF)]),                                    // 溝の両端をふさぐ柱
    ...SLITS.map(([t, b], i) => piece(`口の奥 ${i + 1}`, [YH(t), YL(b), ...both(XH(HALF)), FRONT(DEPTH), P([0, SLOPE, -1], [0, 0, ZF - DEPTH - 0.008])], { color: BLACK })),   // 溝の奥の暗い壁（前面と平行な薄い板）
    piece('口の裏', [YH(SLITS[0][0]), YL(SLITS[2][1]), ...both(XH(HALF)), FRONT(DEPTH + 0.006), ZL(-0.05)]),   // 暗い壁の後ろを後面まで本体の色で埋める
  ],
};
