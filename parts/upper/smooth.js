// 横幅を SLIM 倍にしない（目次で slim を通さない）：はじめから置く幅で書いてある。
import { MAIN, DARK } from '../../xsasm-lib.js';

const loft = (name, secs, o = {}) => ({ name, kind: 'loft', secs, segments: 32, steps: 4, color: MAIN, pos: [0, 0, 0], ...o });
/** 腹の球：上半身が回る中心（原点の 0.14 上）を中心にした球。前後・横に傾けても、ひねっても、腰の帯から見える形が変わらない */
