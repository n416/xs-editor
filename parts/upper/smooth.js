const ballR = y => Math.sqrt(Math.max(0, BALL.r ** 2 - (y - BALL.y) ** 2));
const ballSecs = ys => ys.map((y, i) => ({ y, w: +ballR(y).toFixed(4), ...(i === 0 || i === ys.length - 1 ? { hard: true } : {}) }));
/** 胸の下の縁 = 腹の球の上の縁（同じ数字） */
const WAIST = { y: BALL.y, w: BALL.r, hard: true };

