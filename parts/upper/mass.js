// 厚い殻の胴（胴の骨 torso）：暗い芯に板を貼る作りではなく、装甲そのものが大きな塊。合格の見本は F1 型の胸（parts/upper/f1.js）：
// 片側 1 個の多面体が正面から横へ回り込む、中央の稜が前へ出て腹まで下りる、胸が腹の上に張り出して下に深い影、通気口は面に埋まる。
// 原点は胸の下端の中心（y 2.1）。殻は「角のある断面をつなぐ形」（partgeo.js の loft の pts）：同じ番めの角が上から下まで 1 本の稜線になる。
// 役目：胸 = 骨組みを包む殻（正面は 1 枚、角は回り込む）、中央の稜 = 胸から腹へ続く背骨、腹 = コクピット（前にハッチ）、
// 通気口 = 胸の正面をくぼませた中に下向きの羽根板、脇腹 = 腕の荷重を受ける肩の受け。
// 横幅を SLIM 倍にしない（目次で slim を通さない）：はじめから置く幅で書いてある。寸法は [独自]（F1 型の胸：横 0.365・前 0.30・高さ 0.105〜0.52 を目安にした）
import { MAIN, DARK, BLACK } from '../../xsasm-lib.js';
import { hull, pairOf } from './kit.js';

const shell = (name, secs, o = {}) => ({ name, kind: 'loft', secs, color: MAIN, pos: [0, 0, 0], ...o });
const both = f => [1, -1].flatMap(f);

// ---- 胸の殻：断面の角は 前の中央・正面の板の端・角・横の前・横のいちばん外・横の後ろ・後ろの角・後ろの中央 ----
const CHEST = [
  { y: 0.1, pts: [[0, 0.13], [0.16, 0.125], [0.22, 0.09], [0.26, 0.03], [0.265, -0.03], [0.25, -0.1], [0.17, -0.15], [0, -0.16]] },      // 腹に載る下の縁（張り出しの奥）
  { y: 0.21, pts: [[0, 0.3], [0.22, 0.29], [0.29, 0.235], [0.335, 0.12], [0.345, -0.02], [0.31, -0.14], [0.2, -0.2], [0, -0.21]] },       // 正面の板の下の縁
  { y: 0.38, pts: [[0, 0.32], [0.22, 0.31], [0.3, 0.245], [0.352, 0.11], [0.365, -0.02], [0.33, -0.15], [0.21, -0.21], [0, -0.22]] },     // 正面の板の上の縁（いちばん前）
  { y: 0.5, pts: [[0, 0.12], [0.17, 0.115], [0.25, 0.08], [0.31, 0.02], [0.32, -0.05], [0.29, -0.14], [0.19, -0.19], [0, -0.2]] },        // 肩の線（上の面は後ろへ寝る）
  { y: 0.555, pts: [[0, 0.03], [0.1, 0.03], [0.16, 0], [0.2, -0.04], [0.2, -0.08], [0.18, -0.13], [0.12, -0.16], [0, -0.165]] },          // 襟の載る上の縁
];
/** 中央の稜：正面の板より 4 cm 前。下の端はあごのように腹の上へ下りる */
const keel = () => hull('胸の中央の稜', both(s => [[s * 0.09, 0.22, 0.355], [s * 0.09, 0.4, 0.36], [s * 0.1, 0.22, 0.28], [s * 0.1, 0.4, 0.29],
  [s * 0.075, 0.5, 0.165], [s * 0.09, 0.5, 0.1], [s * 0.07, 0.56, 0.06], [s * 0.085, 0.16, 0.285], [s * 0.095, 0.15, 0.2]]), { color: DARK });
/** 通気口：正面の板をくぼませ（引く）、奥に黒い板、下向きの羽根板 3 枚（正面から弾も水も入りにくい向き） */
const VENT = { x0: 0.115, x1: 0.205, y0: 0.255, y1: 0.345, zin: 0.262 };
const ventCut = () => ({ name: '通気口のくぼみ', kind: 'extrude', op: 'sub', mirror: true, pts: [[-0.045, -0.045], [0.045, -0.045], [0.045, 0.045], [-0.045, 0.045]], depth: 0.12,
  tf: { p: [(VENT.x0 + VENT.x1) / 2, (VENT.y0 + VENT.y1) / 2, VENT.zin + 0.06], r: [0, 0, 0], s: [1, 1, 1] }, color: MAIN, pos: [0, 0, 0] });
const ventIn = () => [
  ...pairOf('通気口の奥', [VENT.x0 - 0.004, VENT.x1 + 0.004].flatMap(x => [VENT.y0 - 0.004, VENT.y1 + 0.004].flatMap(y => [[x, y, VENT.zin - 0.01], [x, y, VENT.zin + 0.003]])), { color: BLACK }),
  ...[0, 1, 2].flatMap(k => {
    const y = VENT.y0 + 0.004 + k * 0.029;
    return pairOf('通気口の羽根 ' + (k + 1), [VENT.x0 - 0.002, VENT.x1 + 0.002].flatMap(x => [[x, y + 0.024, VENT.zin], [x, y + 0.03, VENT.zin], [x, y, VENT.zin + 0.034], [x, y + 0.007, VENT.zin + 0.036]]), { color: DARK });
  }),
];

// ---- 腹：コクピットの塊。下の端は腰の帯の内へ入る（置いた機体で測った帯の上の縁：横 0.235・前 0.236・後ろ 0.22） ----
const BELLY = [
  { y: -0.03, pts: [[0, 0.15], [0.09, 0.15], [0.15, 0.11], [0.185, 0.03], [0.19, -0.04], [0.17, -0.1], [0.1, -0.14], [0, -0.145]] },
  { y: 0.12, pts: [[0, 0.18], [0.1, 0.18], [0.17, 0.13], [0.215, 0.04], [0.22, -0.04], [0.2, -0.12], [0.12, -0.165], [0, -0.17]] },
  { y: 0.27, pts: [[0, 0.2], [0.11, 0.2], [0.19, 0.15], [0.245, 0.05], [0.25, -0.04], [0.23, -0.13], [0.14, -0.18], [0, -0.185]] },
];
/** コクピットの塊：胸の中央の稜と同じ幅で、その真下に続く。前の面は上ほど前へ出る */
const HATCH = { y0: 0.03, z0: 0.215, y1: 0.17, z1: 0.285 };
const cockpit = () => hull('コクピットの塊', both(s => [[s * 0.085, HATCH.y0, HATCH.z0], [s * 0.085, HATCH.y1, HATCH.z1], [s * 0.09, 0.225, 0.262], [s * 0.1, 0, 0.14], [s * 0.1, 0.225, 0.14],
  [s * 0.1, HATCH.y0, HATCH.z0 - 0.03], [s * 0.1, HATCH.y1, HATCH.z1 - 0.035]]), { color: DARK });
/** ハッチ：塊の前の面に載る厚い板（上の端に蝶番の軸受け） */
const hatch = () => {
  const dy = HATCH.y1 - HATCH.y0, dz = HATCH.z1 - HATCH.z0, L = Math.hypot(dy, dz), n = [-dz / L, dy / L];   // 面の外向き（y, z）
  const at = (x, t, o) => [x, HATCH.y0 + dy * t + n[0] * o, HATCH.z0 + dz * t + n[1] * o];
  return [hull('ハッチ', both(s => [at(s * 0.068, 0.1, -0.004), at(s * 0.068, 0.86, -0.004), at(s * 0.068, 0.1, 0.008), at(s * 0.068, 0.86, 0.008), at(s * 0.056, 0.16, 0.016), at(s * 0.056, 0.8, 0.016)])),
    hull('ハッチの蝶番', both(s => [at(s * 0.05, 0.86, 0), at(s * 0.05, 0.97, 0), at(s * 0.05, 0.88, 0.014), at(s * 0.05, 0.95, 0.014)]), { color: BLACK })];
};

// ---- 脇腹：肩の受け。胸の殻の横から肩関節の筒（半径 0.1、x 0.46 から外、y 0.40）へ、八角の柱がすぼまる ----
const socket = () => pairOf('肩の受け', [[0.27, 0.15], [0.4, 0.124], [0.468, 0.106]].flatMap(([x, r]) =>
  Array.from({ length: 8 }, (_, k) => { const a = (k + 0.5) * Math.PI / 4; return [x, 0.4 + r * Math.sin(a), -0.01 + r * Math.cos(a)]; })), { color: DARK });

// ---- 背中：バックパックの載る台。殻の後ろの面から 3 cm 出る ----
const deck = () => hull('背中の台', both(s => [[s * 0.17, 0.17, -0.19], [s * 0.18, 0.45, -0.19], [s * 0.15, 0.19, -0.243], [s * 0.16, 0.43, -0.25]]));

export default [
  { id: 'chestmass', name: '胸（厚い殻と中央の稜）', cat: '胸', size: [0.73, 0.455, 0.58], pieces: [shell('胸の殻', CHEST), ventCut(), keel(), ...ventIn()] },
  { id: 'abdomencockpit', name: '腹（コクピットのハッチ）', cat: '腹', size: [0.5, 0.3, 0.47], pieces: [shell('腹の殻', BELLY), cockpit(), ...hatch()] },
  { id: 'flanksocket', name: '脇腹（肩の受け）', cat: '脇腹', size: [0.94, 0.3, 0.3], pieces: socket() },
  { id: 'backdeck', name: '背中（バックパックの台）', cat: '背中', size: [0.36, 0.28, 0.06], pieces: [deck()] },
];
