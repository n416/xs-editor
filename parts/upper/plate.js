// （外の面は下へ内へ寄り、上は関節・襟へ向かって寝る）。留め具・ボルト・蓋は付けない。色は機体の 2 番目の装甲（DARK）、稜と帯だけ主の色。
//   胸：厚い殻の胸（parts/upper/mass.js の CHEST：正面の板 z 0.275〜0.295・横 0.335〜0.35）の正面だけを覆う胸当て。横は x 0.29 まで
//       （その外は肩アーマーの内の端が回る）。原点は胸の下端の中心（y 2.1）
//   肩：肩アーマー（同じファイルの SLAB・PAULDRON）の上・外・前後を覆う殻。内の端は関節の中心より 2 cm 内まで（胸の側へは広げない）。
//       裾はもとの肩アーマーより 6〜8 cm 下がる。原点は肩関節の中心、+x 側の 1 個（反対側は鏡像で置く）
// 寸法は [独自]。
import { MAIN, DARK } from '../../xsasm-lib.js';
import { hull, grille } from './kit.js';

const EX = '#93a0ae';   // 追加の色 1（xs-editor/paint.js ROLE_COLOR.ex1）：増加装甲の色。機体の文書の paint.pal.ex1 で決まり、ゲームの機体ごとの塗り替えを受けない
const shell = (name, secs, o = {}) => ({ name, kind: 'loft', secs, color: EX, pos: [0, 0, 0], ...o });
const both = f => [1, -1].flatMap(f);

// ---- 胸当て：断面の角は 前の中央・正面の板の端・角・横・（奥：胸の殻の中）----
// （2 版目：依頼主 2026-11-14「アーマーが胸にも欲しい」「全然アーマードしてる感じない」— 1 版目は正面だけの薄い胸当てで、胴の色に塗られて見分けが
// 付かなかった。胸の下半分は横まで回る帯（y 0.34 より下は肩アーマーの内の端が来ない）、上半分は肩を空けて正面の厚い塊、前へ 8 cm 出る。
// 腕を大きく振る格闘では腕が胸の増加装甲に入る：依頼主「条件ゆるくしていい」）
