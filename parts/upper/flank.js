// 脇腹（胴の左右の横と肩の台、胴の骨 torso）：胴を胸・背中・腹・脇腹に分けたうちの左右。1 つの部品に左右の両方が入る。
// 原点は胸の下端の中心（y 2.1）。左右の暗い芯（胸・背中・腹の芯をつなぐ）、肩の台（肩関節の軸受けが外から差さる）、横の装甲。
// 横の装甲は y 0.34 より下（それより上は、腕を振ると肩アーマーの内の端が通る）。
// 種類：上下 2 枚と重ねた板・大きな 1 枚・張り出し（横へふくらむ）・縦のスリット（縦長の板を 4 枚並べる）
import { piece, DARK } from '../../xsasm-lib.js';
import { STD, sideX, frontZ, pairOf, pairPl, slab } from './kit.js';

const { wt, zb } = STD;
const core = () => pairOf('脇腹の芯', [[0.16, 0.03, 0.12], [0.16, 0.03, -0.12], [sideX(0.03), 0.03, 0.12], [sideX(0.03), 0.03, -0.12],
  [0.2, 0.45, 0.16], [0.2, 0.45, -0.16], [wt - 0.005, 0.45, 0.16], [wt - 0.005, 0.45, -0.16]], { color: DARK });
/** 肩の台（左右）：上は低く（外ほど下がる） */
const shoulderBlock = () => pairOf('肩の台', [[0.19, 0.4, 0.1], [0.19, 0.4, -0.11], [0.27, 0.375, 0.09], [0.27, 0.375, -0.1], [0.32, 0.35, 0.1], [0.32, 0.35, -0.11],
  [0.34, 0.3, 0.1], [0.34, 0.3, -0.11], [0.2, 0.27, 0.13], [0.2, 0.27, -0.14], [0.3, 0.26, 0.12], [0.3, 0.26, -0.13]]);
/** 横の面から lift だけ外の面（前後は丸く回る） */
const sideF = (lift, k = 0.7) => (y, z) => sideX(y) + 0.028 + lift - k * (z + 0.01) ** 2;
const F = (id, name, pieces) => ({ id, name, cat: '脇腹', size: [2 * wt + 0.1, 0.45, 0.36], pieces: [...core(), ...shoulderBlock(), ...pieces] });
export default [
  F('flank', '脇腹（上下 2 枚と重ねた板）', [
    ...pairPl('脇腹の板（上）', slab('x', 1, sideF(0), [0.2, 0.34], [-zb + 0.035, frontZ(0.3) - 0.04], { bev: 0.014, depth: 0.06 })),
    ...pairPl('脇腹の板（下）', slab('x', 1, sideF(-0.004), [0.035, 0.185], [-0.115, frontZ(0.1) - 0.035], { bev: 0.012, depth: 0.06 })),
    ...pairPl('脇腹の重ねた板', slab('x', 1, sideF(0.011), [0.235, 0.31], [-0.09, 0.07], { bev: 0.009, depth: 0.03, na: 2, nb: 2 }))]),
  F('flankbig', '脇腹（大きな 1 枚）', [
    ...pairPl('脇腹の板', slab('x', 1, sideF(0.004), [0.04, 0.335], [-zb + 0.04, frontZ(0.2) - 0.04], { bev: 0.018, depth: 0.07, nb: 4 })),
    ...pairPl('脇腹の溝', slab('x', 1, sideF(0.012), [0.17, 0.19], [-0.1, 0.1], { bev: 0.004, depth: 0.03, na: 1, nb: 2 }), { color: DARK })]),
  // 張り出し：横へ 4.5 cm ふくらむ丸い塊（y 0.26 まで。それより上だと、腕を振った重ね板の冠板の縁が当たる）と、下の細い板
  F('flankbulge', '脇腹（張り出し）', [
    ...pairPl('脇腹の張り出し', slab('x', 1, (y, z) => sideF(0.045, 1.2)(y, z) - 1.2 * (y - 0.17) ** 2, [0.07, 0.26], [-0.13, 0.13], { bev: 0.026, depth: 0.1, na: 4, nb: 4 })),
    ...pairPl('脇腹の板（下）', slab('x', 1, sideF(-0.004), [0.03, 0.1], [-0.11, frontZ(0.08) - 0.035], { bev: 0.01, depth: 0.05, na: 2 }))]),
  // 縦のスリット：縦長の板を前後に 4 枚、2 cm ずつあけて並べる（間から暗い芯が見える）
  F('flankslats', '脇腹（縦のスリット）', [-0.135, -0.06, 0.015, 0.09].flatMap((z0, i) =>
    pairPl(`脇腹の縦の板 ${i + 1}`, slab('x', 1, sideF(0.004), [0.04, 0.33], [z0, z0 + 0.055], { bev: 0.01, depth: 0.06, na: 4, nb: 2 })))),
];
