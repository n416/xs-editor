// 胸（胴の骨 torso）。原点は胸の下端の中心（骨格図の chest.yBot、y 2.1）。x 右・y 上・z 前。
// 形：前から見て下（腹）が細く上（肩）が広い逆三角形。暗い芯（内側の骨組み）の上に、装甲の塊と板を重ねる。
//   胸の張り出し（左右の大きな塊）：上の縁がいちばん前で、下の面は下向きに奥へ入る（下に影ができる）。外の上の角は大きく落とす
//   ハッチ：左右の張り出しの間の中央の板
//   腹の板：下ほど細い 3 枚の板。上の板の下の縁が、下の板の上の縁の前にかぶさる（うろこのように重なる）
//   横の板・背中の板・肩の塊（肩関節の軸受けが差さる所）
// 上半身は腹の中心（原点の 0.1 下）のまわりに、ひねり ±70°・前 17°・後ろ 25°・横 ±0.22 rad 回る。下端は腰の帯（y −0.15）より
// 十分上で、下ほど細いので、どこへ傾いても帯に届かない。肩の塊の上は低くして、腕を上げたり振ったりした肩アーマーが当たらないようにする。
// 種類：標準・丸い（張り出しが 1 つの大きな丸い塊）・角ばった（張り出しの前が上下 2 面に折れて稜が立つ）・細い・差し色
import { P, XL, YL, YH, both, mir, planesFromPoints, piece, DARK, ACCENT } from '../../xsasm-lib.js';
import { crown, steps } from '../lower/shape.js';

const hull = (name, pts, o = {}) => piece(name, planesFromPoints(pts), o);
const mirP = pts => pts.map(p => [-p[0], p[1], p[2]]);
/** 左右の対（+x の点から、−x は鏡像） */
const pairOf = (name, pts, o = {}) => [hull(`${name}（+x）`, pts, o), hull(`${name}（−x）`, mirP(pts), o)];

/**
 * wb・wt 下と上の横の半分の幅、top 上の端、zf 芯の前（上）、zb 芯の後ろ（上）、br 胸の張り出しの形（'pair' 左右 2 つ、'round' 1 つの丸い塊、
 * 'wedge' 前が上下 2 面に折れる）、bz 張り出しの前の高さ、abs 腹の板の数、hatch 中央のハッチ、accent 差し色（'br' 張り出し、'hatch' ハッチ）
 */
function chest({ id, name, wb = 0.21, wt = 0.31, top = 0.555, zf = 0.2, zb = 0.18, br = 'split', bz = 0.27, abs = 3, hatch = false, accent = null }) {
  const sideX = y => wb + (wt - wb) * Math.min(1, y / 0.45);          // 芯の横の面（下ほど細い）
  const frontZ = y => 0.15 + (zf - 0.15) * Math.min(1, y / 0.3);      // 芯の前の面（下ほど奥）
  const out = [];
  // 芯
  out.push(hull('胸の芯', [
    ...[1, -1].flatMap(s => [[s * wb, 0, 0.15], [s * wb, 0, -0.14], [s * sideX(0.3), 0.3, zf], [s * sideX(0.3), 0.3, -zb],
      [s * wt, 0.47, zf - 0.01], [s * wt, 0.47, -zb + 0.01], [s * 0.13, top, zf - 0.07], [s * 0.13, top, -zb + 0.06]])], { color: DARK }));
  // 胸の装甲（上）：幅いっぱいの 1 枚の大きな板。前は横にも縦にも丸く、上の縁の少し下がいちばん前。下の縁は中央が下がる V 字。
  // 外の角は上から見て後ろへ落とす（「八」の字）。br 'split' は中央に縦の溝（左右 2 枚）、'wedge' は中ほどに横の稜が立つ
  const acc = k => (accent === k ? { color: ACCENT } : {});
  const bib = (x0, x1) => {
    const f = (x, y) => (br === 'wedge' ? bz - 0.35 * Math.abs(y - 0.42) : bz - 1.1 * (y - 0.44) ** 2) - (br === 'round' ? 0.6 : 0.4) * x * x - 0.1 * Math.sqrt(x * x + 0.002);
    return [...crown('z', 1, f, steps(x0, x1, 5), steps(0.28, 0.55, br === 'wedge' ? 2 : 4)), ...(br === 'wedge' ? crown('z', 1, f, steps(x0, x1, 5), [0.4, 0.44]) : []),
      P([0, 0.25, -1], [0, 0.4, 0.12]), YH(top - 0.003), P([0, 1, 0.9], [0, top - 0.035, bz - 0.06]),
      ...both(P([0.14, -1, 0], [0, 0.255, 0])), ...both(P([1, 0, 0.75], [wt - 0.045, 0, bz - 0.07])), ...both(P([1, 0.3, 0], [wt + 0.005, 0.45, 0])), ...both(P([1, 0.9, 0], [wt - 0.03, 0.5, 0]))];
  };
  if (br === 'split') {
    out.push(piece('胸の装甲（+x）', [...bib(0.012, wt), XL(0.012)], acc('br')), piece('胸の装甲（−x）', [...bib(0.012, wt), XL(0.012)].map(mir), acc('br')));
  } else out.push(piece('胸の装甲', bib(-wt, wt), acc('br')));
  // 胸の装甲の下の縁の暗い帯（V 字の下に見える段）
  out.push(piece('胸の装甲の下の段', [...crown('z', 1, (x, y) => bz - 0.035 - 0.4 * x * x, steps(-wt + 0.03, wt - 0.03, 5), [0.28]),
    P([0, 0.25, -1], [0, 0.4, 0.12]), ...both(P([0.14, -1, 0], [0, 0.232, 0])), P([0, 1, 0], [0, 0.3, 0]), ...both(P([1, 0, 0.75], [wt - 0.06, 0, bz - 0.09]))], { color: DARK }));
  // 中央のハッチ：V 字の下、腹の板の上。上が広い台形
  if (hatch) out.push(hull('胸のハッチ', [...[1, -1].flatMap(s => [[s * 0.085, 0.27, frontZ(0.27) + 0.045], [s * 0.06, 0.17, frontZ(0.17) + 0.04],
    [s * 0.1, 0.275, frontZ(0.27) + 0.02], [s * 0.075, 0.16, frontZ(0.17) + 0.015], [s * 0.1, 0.28, 0.12], [s * 0.075, 0.16, 0.1]])], acc('hatch')));
  // 腹の板：胸の装甲の下から腰の上まで、幅いっぱいの板を abs 枚、1 cm あけて重ねる（間から芯が見える）。前の面は芯の前の面に沿って
  // 下ほど奥（少し下を向く）、横に少し丸い。上・下・横の角は 45° に落とす（上の面が光って縞に見えないように）
  const y1s = 0.245, h = (y1s - 0.02) / abs, slope = (wt - wb) / 0.45;
  for (let k = 0; k < abs; k++) {
    const y0 = 0.02 + k * h, y1 = y0 + h - 0.01, w = sideX(y0) - 0.012, f = (x, y) => frontZ(y) + 0.022 - 0.3 * x * x;
    out.push(piece(`腹の板 ${k + 1}`, [...crown('z', 1, f, steps(-w, w, 6), steps(y0, y1, 1)),
      P([0, 0.18, -1], [0, 0, -0.13]), YL(y0), YH(y1), ...both(P([1, -slope, 0], [w, y0, 0])), ...both(P([1, 0, 1], [w - 0.016, 0, f(w, y0)])),
      P([0, 1, 1], [0, y1 - 0.011, f(0, y1)]), P([0, -1, 1], [0, y0 + 0.008, f(0, y0)])]));
  }
  // 横の板（左右）：下ほど細い横の面に沿う
  out.push(...pairOf('横の板', [
    [sideX(0.04) + 0.018, 0.04, 0.1], [sideX(0.04) + 0.018, 0.04, -0.1], [sideX(0.36) + 0.02, 0.36, 0.14], [sideX(0.36) + 0.02, 0.36, -0.15],
    [sideX(0.04) - 0.02, 0.03, 0.12], [sideX(0.04) - 0.02, 0.03, -0.12], [sideX(0.36) - 0.02, 0.37, 0.16], [sideX(0.36) - 0.02, 0.37, -0.17]]));
  // 上の板：胸の装甲の上の縁から背中の板の上の縁まで、上の面を覆う（真ん中に襟と首が通る）。前後・左右へ少し下がる
  out.push(piece('胸の上の板', [...crown('y', 1, (x, z) => top + 0.012 - 0.25 * x * x - 0.5 * (z + 0.02) ** 2, steps(-wt + 0.05, wt - 0.05, 5), steps(-zb + 0.03, bz - 0.08, 3)),
    YL(top - 0.03), ...both(P([1, 0.8, 0], [wt - 0.03, top - 0.02, 0])), P([0, 0.6, 1], [0, top, bz - 0.07]), P([0, 0.6, -1], [0, top, -zb + 0.03])]));
  // 背中の板
  out.push(piece('背中の板', [...crown('z', -1, (x, y) => zb + 0.025 - 0.35 * x * x - 0.5 * (y - 0.3) ** 2, steps(-wt + 0.04, wt - 0.04, 6), steps(0.05, 0.5, 3)),
    P([0, 0.1, 1], [0, 0.3, -zb + 0.04]), YL(0.05), YH(0.5), P([0, 1, -0.6], [0, 0.49, -zb]), ...both(P([1, -0.25, -0.4], [sideX(0.3) - 0.01, 0.3, -zb]))]));
  // 肩の塊（左右）：肩関節の軸受けが外から差さる。上は低く（外ほど下がる）
  out.push(...pairOf('肩の塊', [[0.19, 0.4, 0.1], [0.19, 0.4, -0.11], [0.27, 0.375, 0.09], [0.27, 0.375, -0.1], [0.32, 0.35, 0.1], [0.32, 0.35, -0.11],
    [0.34, 0.3, 0.1], [0.34, 0.3, -0.11], [0.2, 0.27, 0.13], [0.2, 0.27, -0.14], [0.3, 0.26, 0.12], [0.3, 0.26, -0.13]]));
  return { id, name, cat: '胸', size: [2 * wt + 0.08, top + 0.02, bz + zb + 0.04], pieces: out };
}

export default [
  chest({ id: 'chest', name: '胸', br: 'split', abs: 2 }),
  chest({ id: 'chestbarrel', name: '胸（丸い）', br: 'round', bz: 0.285, zf: 0.21, abs: 3, hatch: false }),
  chest({ id: 'chestangular', name: '胸（角ばった）', br: 'wedge', bz: 0.285, abs: 2, wb: 0.2, wt: 0.32 }),
  chest({ id: 'chestslim', name: '胸（細い）', br: 'split', wb: 0.17, wt: 0.28, zf: 0.18, zb: 0.16, bz: 0.245, abs: 2 }),
  chest({ id: 'chestaccent', name: '胸（差し色）', accent: 'br', br: 'single', abs: 3 }),
];
