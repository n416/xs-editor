// 胸（胴の前の上、胴の骨 torso）：胴を胸・背中・腹・脇腹に分けたうちの前の上。y 0.2〜0.555、z −0.03 より前。原点は胸の下端の中心（y 2.1）。
// 種類ごとに輪郭（前・横・上から見た形）から違う。広い面は垂直にも水平にもしない（どれも傾けるか丸める）。
//   鳩胸：上の胸が大きく前へせり出す。上の面は襟から前へ下る斜面で、左右に通気口。前の面は下ほど奥
//   丸い胴：上から見て円に近い樽形。前にハッチ、腰寄りに暗い帯
//   逆三角：肩の方へ広がる V 字の大きな装甲（先は腹の上まで下がる）と、下ほど細い芯
//   角ばった塊：上下 2 つの重い塊（間に暗い溝）。前は上ほど前へ、横は下ほどすぼまる。下の塊に横長の通気口
//   コクピットの張り出し：左右の胸の装甲の真ん中から、四角い操縦席の塊が前へ突き出る
//   骨組み：細い芯に、前を回る肋の棒 3 本と胸骨、上に小さな板 2 枚（軽い機体）
//   角の排気口：上の角の丸い塊の、左右の上の外の角を斜めに落とした面に排気口（光る黄色の羽根板）。真ん中に縦長の板
// 腕を振ると肩アーマーの内の端が肩のまわり（x 0.26 より外で y 0.34 より上）を通るので、そこは空ける。
import { P, XL, YL, YH, both, mir, ellipsoid, piece, DARK, ACCENT } from '../../xsasm-lib.js';
import { crown, steps } from '../lower/shape.js';
import { STD, sideX, frontZ, hull, mirP, pairPl, slab, grille, mirrorPieces, unit, cross } from './kit.js';

const { wt, top, zf, bz } = STD;
const ptsBoth = pts => [...pts, ...mirP(pts)];
/** 上の面の前の半分（襟と首が通る）。z0 まで前 */
const topPlate = (z0 = bz - 0.08, w = wt - 0.05) => piece('胸の上の板', [...crown('y', 1, (x, z) => top + 0.012 - 0.25 * x * x - 0.5 * (z + 0.02) ** 2, steps(-w, w, 5), steps(-0.03, z0, 2)),
  YL(top - 0.03), ...both(P([1, 0.8, 0], [w + 0.02, top - 0.02, 0])), P([0, 0.6, 1], [0, top, z0 + 0.01]), P([0, 0, -1], [0, 0, 0.03])]);
/** 標準の芯（前の上の塊） */
const coreStd = (w0 = sideX(0.2) - 0.005) => hull('胸の芯', ptsBoth([[w0, 0.2, frontZ(0.2)], [w0, 0.2, -0.03], [sideX(0.3), 0.3, zf], [sideX(0.3), 0.3, -0.03],
  [wt, 0.47, zf - 0.01], [wt, 0.47, -0.03], [0.13, top, zf - 0.07], [0.13, top, -0.03]]), { color: DARK });
/** 胸の装甲の前の面（左右 2 枚の標準の形） */
const face = (x, y) => bz - 1.1 * (y - 0.44) ** 2 - 0.4 * x * x - 0.1 * Math.sqrt(x * x + 0.002);
const bib = (x0, x1) => [...crown('z', 1, face, steps(x0, x1, 5), steps(0.28, 0.55, 4)),
  P([0, 0.25, -1], [0, 0.4, 0.12]), YH(top - 0.003), P([0, 1, 0.9], [0, top - 0.035, bz - 0.06]),
  ...both(P([0.14, -1, 0], [0, 0.255, 0])), ...both(P([1, 0, 0.75], [wt - 0.045, 0, bz - 0.07])), ...both(P([1, 0.3, 0], [wt + 0.005, 0.45, 0])), ...both(P([1, 0.9, 0], [wt - 0.03, 0.5, 0]))];
const underStep = () => piece('胸の装甲の下の段', [...crown('z', 1, (x) => bz - 0.035 - 0.4 * x * x, steps(-wt + 0.03, wt - 0.03, 5), [0.28]),
  P([0, 0.25, -1], [0, 0.4, 0.12]), ...both(P([0.14, -1, 0], [0, 0.232, 0])), P([0, 1, 0], [0, 0.3, 0]), ...both(P([1, 0, 0.75], [wt - 0.06, 0, bz - 0.09]))], { color: DARK });

const C = (id, name, size, pieces) => ({ id, name, cat: '胸', size, pieces });

// ---- 鳩胸 ----
function pigeon() {
  const D = [0.16, top, 0.09], Cn = [0, 0.515, 0.355], B = [0.265, 0.5, 0.325];   // 上の斜面（左の半分の三角形 D-C-B が 1 枚の面）
  const prow = hull('胸の張り出し', ptsBoth([D, Cn, B, [0.24, 0.31, 0.285], [0, 0.3, 0.31], [0.23, 0.255, 0.16], [0, 0.25, 0.17],
    [0.305, 0.46, 0.15], [0.285, 0.33, 0.15], [0.2, 0.52, 0.05], [0.2, 0.27, 0.05]]));
  // 通気口：上の斜面（三角形 D-C-B）の上、外寄り
  const o = [0, 1, 2].map(i => 0.42 * D[i] + 0.28 * Cn[i] + 0.3 * B[i]), u = unit([B[0] - Cn[0], B[1] - Cn[1], B[2] - Cn[2]]);
  const mid = [0, 1, 2].map(i => (Cn[i] + B[i]) / 2), v0 = unit([D[0] - mid[0], D[1] - mid[1], D[2] - mid[2]]);
  const n = unit(cross(u, v0)), v = unit(cross(n, u));   // 面の上で u に直角な上り
  const vent = grille('胸の通気口（+x）', o, u, v, 0.1, 0.075, { slats: 3 });
  return C('chestpigeon', '胸（鳩胸）', [0.64, 0.36, 0.4], [
    hull('胸の芯', ptsBoth([[0.26, 0.2, 0.16], [0.26, 0.2, -0.03], [0.3, 0.42, 0.2], [0.3, 0.42, -0.03], [0.29, 0.5, 0.12], [0.29, 0.5, -0.03], [0.15, top, 0.08], [0.15, top, -0.03]]), { color: DARK }),
    topPlate(0.07, 0.2), prow, ...vent, ...mirrorPieces(vent),
    hull('張り出しの下の段', ptsBoth([[0.22, 0.26, 0.17], [0, 0.255, 0.185], [0.22, 0.225, 0.14], [0, 0.22, 0.155], [0.22, 0.24, 0.05], [0, 0.23, 0.05]]), { color: DARK })]);
}

// ---- 丸い胴 ----
function barrel() {
  const rings = [[0.2, 0.25, 0.2], [0.3, 0.29, 0.265], [0.42, 0.3, 0.285], [0.5, 0.275, 0.255], [top, 0.19, 0.17]];
  const ring = (y, rx, rz, k = 20) => Array.from({ length: k + 1 }, (_, j) => { const a = Math.PI * j / k; return [rx * Math.cos(a), y, Math.max(-0.03, rz * Math.sin(a))]; });
  const shell = hull('胸（丸い胴）', rings.flatMap(([y, rx, rz]) => ring(y, rx, rz)));
  const rz = y => { const i = Math.max(1, rings.findIndex(r => r[0] >= y)), [y0, , z0] = rings[i - 1], [y1, , z1] = rings[i]; return z0 + (z1 - z0) * (y - y0) / (y1 - y0); };
  return C('chestbarrel', '胸（丸い胴）', [0.62, 0.36, 0.34], [shell,
    hull('胸の帯', [...ring(0.265, 0.285, 0.25), ...ring(0.295, 0.297, 0.268)].map(p => [p[0] * 1.03, p[1], p[2] * 1.035]), { color: DARK }),
    piece('胸のハッチ', slab('z', 1, (x, y) => rz(y) + 0.012 - 1.6 * x * x, [-0.1, 0.1], [0.34, 0.49], { bev: 0.012, depth: 0.05, na: 4, nb: 3 })),
    piece('ハッチの縁', slab('z', 1, (x, y) => rz(y) + 0.004 - 1.6 * x * x, [-0.115, 0.115], [0.325, 0.505], { bev: 0.004, depth: 0.05, na: 4, nb: 3 }), { color: DARK })]);
}

// ---- 逆三角 ----
function vee() {
  const half = (dz, o = {}) => hull('胸の V 字の装甲（+x）', [[0.014, 0.552, 0.262 + dz], [0.305, 0.52, 0.212 + dz], [0.014, 0.14, 0.215 + dz], [0.2, 0.33, 0.222 + dz],
    [0.014, 0.556, 0.2], [0.31, 0.522, 0.16], [0.014, 0.13, 0.16], [0.2, 0.32, 0.17]], o);
  const plate = half(0);
  const inner = hull('胸の V 字の板（+x）', [[0.05, 0.515, 0.268], [0.22, 0.49, 0.235], [0.05, 0.26, 0.24], [0.05, 0.515, 0.23], [0.22, 0.49, 0.2], [0.05, 0.26, 0.2]], { color: ACCENT });
  return C('chestvee', '胸（逆三角）', [0.64, 0.43, 0.3], [
    hull('胸の芯', ptsBoth([[0.17, 0.2, 0.17], [0.17, 0.2, -0.03], [0.26, 0.32, 0.19], [0.26, 0.32, -0.03], [wt, 0.47, 0.19], [wt, 0.47, -0.03], [0.13, top, 0.13], [0.13, top, -0.03]]), { color: DARK }),
    topPlate(0.17), plate, ...mirrorPieces([plate]), inner, ...mirrorPieces([inner])]);
}

// ---- 角ばった塊 ----
function block() {
  // 上の塊：前は上ほど前へ（z 0.25 → 0.28）、上の面は襟へ上る。下の塊：前は下ほど奥、横は下ほどすぼまる
  const upper = hull('胸の上の塊', ptsBoth([[0.28, 0.385, 0.25], [0.3, 0.5, 0.28], [0.13, 0.545, 0.2], [0.3, 0.385, 0.2], [0.305, 0.48, 0.23], [0.28, 0.385, -0.02], [0.3, 0.5, -0.02], [0.13, top, -0.02],
    [0, 0.51, 0.29], [0, 0.385, 0.26]]));
  const lower = hull('胸の下の塊', ptsBoth([[0.24, 0.215, 0.2], [0.27, 0.36, 0.235], [0.255, 0.21, 0.16], [0.285, 0.36, 0.2], [0.24, 0.21, -0.02], [0.27, 0.36, -0.02], [0, 0.36, 0.245], [0, 0.215, 0.21]]));
  // 下の塊の前の面（y 0.215 で z 0.2、y 0.36 で z 0.235）に、横長の通気口を 1 つ（2 つ並べると目に見える）
  const v = unit([0, 0.145, 0.035]), u = [1, 0, 0], o = [0, 0.285, 0.2 + 0.035 * (0.285 - 0.215) / 0.145 + 0.012];
  const vent = grille('胸の通気口', o, u, v, 0.3, 0.075, { slats: 3 });
  return C('chestblock', '胸（角ばった塊）', [0.62, 0.36, 0.33], [
    hull('胸の芯', ptsBoth([[0.24, 0.2, 0.17], [0.24, 0.2, -0.03], [0.29, 0.47, 0.2], [0.29, 0.47, -0.03], [0.13, top, 0.13], [0.13, top, -0.03]]), { color: DARK }),
    upper, lower, ...vent]);
}

// ---- コクピットの張り出し ----
function cockpit() {
  const pod = hull('操縦席の塊', ptsBoth([[0.105, 0.46, 0.335], [0.095, 0.24, 0.305], [0.1, 0.53, 0.22], [0.09, 0.21, 0.2], [0.12, 0.44, 0.31], [0.113, 0.26, 0.285],
    [0.1, 0.5, 0.12], [0.09, 0.22, 0.12], [0, 0.47, 0.345], [0, 0.235, 0.312]]));
  const zPod = y => 0.312 + (0.345 - 0.312) * (y - 0.235) / (0.47 - 0.235);
  return C('chestcockpit', '胸（コクピットの張り出し）', [0.64, 0.36, 0.38], [coreStd(), topPlate(),
    ...pairPl('胸の装甲', [...bib(0.03, wt), XL(0.03)]), underStep(), pod,
    piece('操縦席のハッチ', slab('z', 1, (x, y) => zPod(y) + 0.008 - 0.5 * x * x, [-0.07, 0.07], [0.29, 0.43], { bev: 0.01, depth: 0.04, na: 2, nb: 2 })),
    piece('ハッチの縁', slab('z', 1, (x, y) => zPod(y) + 0.002 - 0.5 * x * x, [-0.08, 0.08], [0.28, 0.44], { bev: 0.003, depth: 0.04, na: 2, nb: 2 }), { color: DARK })]);
}

// ---- 骨組み ----
function frame() {
  // 肋：前を回る棒（y を外ほど少し下げる）。短い区切りの凸の塊を並べる
  const rib = (name, y, rx, rz, drop, o = {}) => Array.from({ length: 8 }, (_, j) => {
    const pts = [];
    for (const a of [Math.PI * (0.08 + 0.84 * j / 8) - 0.02, Math.PI * (0.08 + 0.84 * (j + 1) / 8) + 0.02]) {
      const x = rx * Math.cos(a), z = rz * Math.sin(a), yy = y - drop * Math.abs(Math.cos(a));
      for (const [dr, dy] of [[0, 0.012], [0, -0.012], [-0.025, 0.012], [-0.025, -0.012]]) pts.push([(rx + dr) / rx * x, yy + dy, (rz + dr) / rz * z]);
    }
    return hull(`${name}（${j + 1}）`, pts, o);
  });
  return C('chestframe', '胸（骨組み）', [0.6, 0.36, 0.3], [
    hull('胸の芯', ptsBoth([[0.19, 0.2, 0.13], [0.19, 0.2, -0.03], [0.24, 0.45, 0.14], [0.24, 0.45, -0.03], [0.13, top, 0.1], [0.13, top, -0.03]]), { color: DARK }),
    topPlate(0.1, 0.2),
    ...rib('胸の肋 1', 0.29, 0.26, 0.19, 0.03), ...rib('胸の肋 2', 0.36, 0.28, 0.2, 0.03), ...rib('胸の肋 3', 0.43, 0.29, 0.2, 0.03),
    piece('胸骨', slab('z', 1, (x, y) => 0.2 + 0.1 * (y - 0.25) - 3 * x * x, [-0.03, 0.03], [0.24, 0.5], { bev: 0.008, depth: 0.08, na: 2, nb: 3 })),
    ...pairPl('胸の小さな板', slab('z', 1, (x, y) => 0.215 - 0.8 * (x - 0.13) ** 2 - 1.5 * (y - 0.5) ** 2, [0.04, 0.23], [0.465, 0.55], { bev: 0.012, depth: 0.08, extra: [P([1, 0.8, 0], [0.21, 0.52, 0])] }))]);
}

// ---- 角の排気口 ----
// 写真の胸から（角の立った多面体。寸法は写真の上で胸の半分の幅 = 0.31 として測った）：
//   前の面：上が広く下が狭い。折れ目（y 0.306）より上は上前を向き（上ほど奥）、折れ目より下の帯はほとんど前、わずかに下を向く
//   脇の面：前の面の左右の斜め前外を向いた面。上は細く（幅 0.02）、折れ目まで広がって（0.075）、そこから下は同じ幅で縦に下りる
//   排気口：前の面の下の帯の、脇の面のすぐ内側（光る黄色の羽根板）
//   上の面：前の面の上の縁から、首の後ろへ上って後ろへ回る
function cornerExhaust() {
  const FY = 0.306, TY = 0.49, BY = 0.2;                                   // 折れ目・前の面の上の縁・下の端
  const zf = y => (y >= FY ? 0.29 - (y - FY) * 0.07 / (TY - FY) : 0.29 - (FY - y) * 0.03 / (FY - BY));   // 前の面の z
  const xi = y => (y >= FY ? 0.235 + (y - FY) * (0.29 - 0.235) / (TY - FY) : 0.235 + (FY - y) * 0.005 / (FY - BY));   // 前の面と脇の面の境
  const W = 0.31, side = y => [W, y, zf(y) - 1.6 * (W - xi(y))];           // 脇の面の外の縁（横寄りに傾け、外の角は後ろへ。剣を振る腕が前を通るため）
  const pts = [];
  for (const y of [TY, 0.4, FY, 0.25, BY]) pts.push([0, y, zf(y) + 0.004], [xi(y), y, zf(y)], side(y));   // 前の面（真ん中は少しだけ前）と脇の面
  pts.push([0.25, 0.555, 0.1], [0, 0.575, 0.12], [0.2, 0.575, -0.03], [0.29, 0.52, 0.06],               // 上の面
    [W - 0.005, 0.45, 0.0], [W - 0.01, 0.3, 0.0], [0.3, 0.47, -0.03], [0.28, BY, -0.03], [0.29, BY, 0.05]);   // 横と後ろ（横の面は少しすぼめる）
  const shell = hull('胸の塊', ptsBoth(pts));
  // 排気口：前の面の下の帯（折れ目から下）の、脇の面のすぐ内側
  const u = [1, 0, 0], v = unit([0, FY - BY, zf(FY) - zf(BY)]);
  const ox = xi(0.25) - 0.07, oy = 0.255;
  const vent = grille('胸の排気口（+x）', [ox, oy, zf(oy) + 0.002], u, v, 0.13, 0.08, { slats: 3, dep: 0.018, slatColor: '#ffd257' });
  return C('chestexhaust', '胸（角の排気口）', [0.64, 0.38, 0.34], [
    hull('胸の芯', ptsBoth([[0.24, 0.2, 0.17], [0.24, 0.2, -0.03], [0.29, 0.47, 0.2], [0.29, 0.47, -0.03], [0.13, top, 0.13], [0.13, top, -0.03]]), { color: DARK }),
    shell, ...vent, ...mirrorPieces(vent)]);
}

