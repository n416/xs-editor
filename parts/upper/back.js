// 背中（胴の後ろの上、胴の骨 torso）：胴を胸・背中・腹・脇腹に分けたうちの後ろの上。y 0.2〜0.555、z 0.03 より後ろ。原点は胸の下端の中心（y 2.1）。
// 自分の暗い芯と、後ろの装甲、上の面の後ろの半分を持つ。バックパックはこの後ろの面に差す。
// 種類：上の板と中央の稜・盛り上がった背中（大きな丸い板）・横の段（3 段の板）・左右の張り出し（肩甲骨のような 2 つの塊）
import { P, YL, both, piece, DARK } from '../../xsasm-lib.js';
import { crown, steps } from '../lower/shape.js';
import { STD, sideX, backZ, hull, pairPl, slab } from './kit.js';

const { wt, top, zb } = STD;
const core = () => hull('背中の芯', [...[1, -1].flatMap(s => [[s * (sideX(0.2) - 0.005), 0.2, 0.03], [s * (sideX(0.2) - 0.005), 0.2, backZ(0.2)],
  [s * sideX(0.3), 0.3, 0.03], [s * sideX(0.3), 0.3, -zb], [s * wt, 0.47, 0.03], [s * wt, 0.47, -zb + 0.01], [s * 0.13, top, 0.03], [s * 0.13, top, -zb + 0.06]])], { color: DARK });
const topPlate = () => piece('背中の上の板', [...crown('y', 1, (x, z) => top + 0.012 - 0.25 * x * x - 0.5 * (z + 0.02) ** 2, steps(-wt + 0.05, wt - 0.05, 5), steps(-zb + 0.03, 0.03, 2)),
  YL(top - 0.03), ...both(P([1, 0.8, 0], [wt - 0.03, top - 0.02, 0])), P([0, 0.6, -1], [0, top, -zb + 0.03]), P([0, 0, 1], [0, 0, 0.03])]);
/** 背中の面（後ろへの出）。z = −fk */
const fk = (x, y) => zb + 0.025 - 0.35 * x * x - 0.5 * (y - 0.33) ** 2;
const side = both(P([1, -0.25, -0.4], [sideX(0.3) - 0.01, 0.3, -zb]));
const B = (id, name, pieces) => ({ id, name, cat: '背中', size: [2 * wt + 0.02, 0.36, zb + 0.1], pieces: [core(), topPlate(), ...pieces] });
export default [
  B('back', '背中（上の板と稜）', [
    piece('背中の板', slab('z', -1, fk, [-(wt - 0.035), wt - 0.035], [0.225, 0.5], { bev: 0.016, depth: 0.06, na: 6, extra: [...side, P([0, 1, -0.6], [0, 0.49, -zb])] })),
    piece('背中の中央の稜', slab('z', -1, (x, y) => fk(0, y) + 0.016 - 3 * x * x, [-0.045, 0.045], [0.21, 0.49], { bev: 0.011, depth: 0.05, na: 2, nb: 4 })),
    ...pairPl('背中の重ねた板', slab('z', -1, (x, y) => fk(x, y) + 0.011, [0.09, wt - 0.085], [0.29, 0.455], { bev: 0.011, depth: 0.03, extra: [P([1, 0.3, 0], [wt - 0.085, 0.455, 0])] }))]),
  // 盛り上がった背中：後ろへ 5 cm 多く出る大きな丸い板。上下に暗い帯
  B('backhump', '背中（盛り上がった）', [
    piece('背中の盛り上がり', slab('z', -1, (x, y) => fk(x, y) + 0.05 - 0.4 * x * x - 0.8 * (y - 0.37) ** 2, [-(wt - 0.05), wt - 0.05], [0.22, 0.52],
      { bev: 0.03, depth: 0.12, na: 6, nb: 4, extra: [...side, P([0, 1, -0.7], [0, 0.5, -zb - 0.02])] })),
    piece('盛り上がりの帯', slab('z', -1, (x, y) => fk(x, y) + 0.04 - 0.4 * x * x, [-(wt - 0.07), wt - 0.07], [0.305, 0.33], { bev: 0.005, depth: 0.08, na: 6, nb: 1 }), { color: DARK })]),
  // 横の段：幅いっぱいの板を 3 段。上の板の裾が下の板の上の端にかぶさる（下の縁が後ろへ出る）
  B('backlames', '背中（横の段）', [0, 1, 2].map(k => {
    const y0 = 0.42 - 0.09 * k, y1 = Math.min(0.53, y0 + 0.1);
    return piece(`背中の段 ${k + 1}`, slab('z', -1, (x, y) => fk(x, y) + 0.02 - 0.012 * k + 0.22 * (y1 - y) - 0.02, [-(wt - 0.035 - 0.01 * k), wt - 0.035 - 0.01 * k], [y0, y1],
      { bev: 0.012, depth: 0.09, na: 6, nb: 2, extra: side }));
  })),
  // 左右の張り出し：肩甲骨のような 2 つの塊。間の中央は暗い溝
  B('backblades', '背中（左右の張り出し）', [
    piece('背中の板', slab('z', -1, fk, [-(wt - 0.035), wt - 0.035], [0.215, 0.5], { bev: 0.016, depth: 0.06, na: 6, extra: [...side, P([0, 1, -0.6], [0, 0.49, -zb])] })),
    ...pairPl('背中の張り出し', slab('z', -1, (x, y) => fk(x, y) + 0.04 - 1.2 * (x - 0.16) ** 2 - 1.2 * (y - 0.38) ** 2, [0.06, wt - 0.05], [0.26, 0.5],
      { bev: 0.022, depth: 0.08, na: 4, nb: 4, extra: [P([1, 0.4, -0.3], [wt - 0.05, 0.45, -zb])] })),
    piece('背中の溝', slab('z', -1, (x, y) => fk(0, y) + 0.008 - 3 * x * x, [-0.035, 0.035], [0.22, 0.5], { bev: 0.006, depth: 0.05, na: 2, nb: 3 }), { color: DARK })]),
];
