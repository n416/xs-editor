// トサカ板：頭の上を前後に走る薄い縦の板。前は低く、後ろへ向かって高くなり、後ろの先は鋭く流れる。上の縁は研いである。
// 根元は薄い台座。y 0 が台座の底、前が +z
import { P, XH, XL, YH, YL, ZH, ZL, both, piece, MAIN } from '../xsasm-lib.js';

const T = 0.006;
export default {
  id: 'finplate', name: 'トサカ板', cat: 'トサカ', size: [0.03, 0.09, 0.26],
  pieces: [
    piece('台座', [YL(0), YH(0.01), ZL(-0.12), ZH(0.1), ...both(XH(0.015)), P([0, 0.6, 1], [0, 0, 0.1]), P([0, 0.6, -1], [0, 0, -0.12])]),
    piece('板', [XH(T), XL(-T), YL(0.0),
      P([0, 1, 0.35], [0, 0.03, 0.09]),                             // 上の縁の前半：前へ下がる
      P([0, 1, -0.12], [0, 0.085, -0.05]),                          // 上の縁の後半：後ろへ少し上がる
      P([0, 0.45, 1], [0, 0.0, 0.11]),                              // 前の縁：上へ向かって後ろへ
      P([0, -0.35, -1], [0, 0.0, -0.13]),                           // 後ろの縁：上へ向かって後ろへ（先が流れる）
      ...both(P([1, 0.8, 0.28], [T, 0.03, 0.09])), ...both(P([1, 0.8, -0.1], [T, 0.085, -0.05])),   // 上の縁を研ぐ
    ]),
  ],
};
