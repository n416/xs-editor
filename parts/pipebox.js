// 動力パイプの受け（頭の後ろ）：頭を回る動力パイプ（parts/headpipe.js の headpiperim）の後ろの端を受ける箱。パイプは前の端があごの塊、
// 後ろの端がこの箱に入る（依頼主：「頭の後ろの動力パイプを受けるボックスが頭にないじゃん」。前の決まり：パイプは両端が何かの部品に入っていること）。
// 形：うなじに付く多面体。前はヘルメットの後ろの下へ入り、上の面はうなじへ斜めに上がる。左右の面に、パイプの端を囲う八角の受け口。
// 寸法は、GIO の水陸に置いた頭で測った値から（機体の座標）：パイプの後ろの端は 横 ±0.08〜0.10・高さ 2.54〜2.60・前後 −0.11〜−0.17、太さは半径 0.026。
// ヘルメットの後ろは、その高さで −0.11。[独自]
// 頭の部品の座標は、機体の座標 = 頭の原点 (0, 2.606, −0.015) + 0.45 × 部品の座標（置き方 mov 0・scal 1 のとき）。下の数字は機体の座標で書いて、K で割る。
import { MAIN, DARK, planesFromPoints, piece } from '../xsasm-lib.js';

const K = 0.45, Y0 = 2.606, Z0 = -0.015;
const L = ([x, y, z]) => [x / K, (y - Y0) / K, (z - Z0) / K];
const both = pts => pts.flatMap(([x, y, z]) => [[x, y, z], [-x, y, z]]);
const hull = (name, pts, o = {}) => piece(name, planesFromPoints(pts.map(L)), o);
/** パイプの受け口：箱の横の面から外へ出る八角の輪（パイプの端の 1.5 cm を囲う） */
const socket = s => hull(`パイプの受け口（${s > 0 ? '+x' : '−x'}）`, [0.098, 0.128].flatMap((x, i) => Array.from({ length: 8 }, (_, k) => {
  const a = (k + 0.5) * Math.PI / 4, r = i ? 0.034 : 0.038; return [s * x, 2.566 + r * Math.sin(a), -0.142 + r * Math.cos(a)];
})), { color: DARK });

export default {
  id: 'pipebox', name: '動力パイプの受け（頭の後ろ）', cat: '飾り', size: [0.256 / K, 0.12 / K, 0.1 / K],
  pieces: [
    hull('パイプの受けの箱', both([
      [0.095, 2.525, -0.1], [0.095, 2.615, -0.1],            // ヘルメットの後ろの下へ入る面
      [0.105, 2.53, -0.15], [0.105, 2.608, -0.15],           // いちばん外
      [0.08, 2.537, -0.19], [0.08, 2.598, -0.19],            // 後ろの面
      [0.07, 2.64, -0.115],                                   // うなじへ上がる面の上の端
    ])),
    socket(1), socket(-1),
    hull('点検口の蓋', both([[0.045, 2.55, -0.188], [0.045, 2.588, -0.188], [0.038, 2.555, -0.198], [0.038, 2.583, -0.198]]), { color: DARK }),
  ],
};
