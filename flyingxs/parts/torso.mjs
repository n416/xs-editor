// 両端は胸とランドセルの中。弧は外・下へふくらむ（前と後ろが高く、脇で低い）
function bellowsBetween(name, a, b, bulge, sag, o) {
  const c = sub(b, a), cl = Math.hypot(...c), ch = c.map(v => v / cl);
  const bb = unit(sub(bulge, ch.map(v => v * dot(bulge, ch))));
  const R = (cl * cl / 4 + sag * sag) / (2 * sag), th = sag > cl / 2 ? 2 * Math.PI - 2 * Math.asin(cl / 2 / R) : 2 * Math.asin(cl / 2 / R);   // 垂れが弦の半分を超えたら半円より大きい弧（torso32 まではいつも小さい弧で、垂れを増やすと浅くなった）
  const t0 = add(ch.map(v => v * Math.cos(th / 2)), bb, Math.sin(th / 2));
  const n0 = sub(ch.map(v => v * Math.sin(th / 2)), bb.map(v => v * Math.cos(th / 2)));
  const x0 = cross(t0, n0);
  const e = new THREE.Euler().setFromRotationMatrix(new THREE.Matrix4().makeBasis(new THREE.Vector3(...x0), new THREE.Vector3(...t0), new THREE.Vector3(...n0)), 'XYZ');
  return block(name, { kind: 'bellows', len: r6(R * th), bend: r6(th * 180 / Math.PI), bendDir: 0, ...o,
    tf: { p: a.map(r6), r: [e.x, e.y, e.z].map(v => r6(v * 180 / Math.PI)), s: [1, 1, 1] } });
}
