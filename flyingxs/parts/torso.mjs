// 元の点はそのまま残るので、形と大きさ（いちばん前・横・後ろ）は変わらない
function sub4(pts, closed, levels = 1) {
  for (let k = 0; k < levels; k++) {
    const n = pts.length, at = i => closed ? pts[(i + n) % n] : pts[Math.max(0, Math.min(n - 1, i))], out = [];
    for (let i = 0; i < (closed ? n : n - 1); i++) {
      out.push(pts[i]);
      out.push(pts[i].map((_, j) => (-at(i - 1)[j] + 9 * at(i)[j] + 9 * at(i + 1)[j] - at(i + 2)[j]) / 16));
    }
    if (!closed) out.push(pts[n - 1]);
    pts = out;
  }
  return pts;
}
