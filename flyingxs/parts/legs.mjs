// 輪：高さ y、中心 (cx, cz)、横の半幅 hw、前 f・後ろ b。sq が 1 に近いほど丸い。yz：前後で高さを傾ける
function ring(cx, y, cz, hw, f, b, n = 24, sq = 0.95, yz = 0) {
  const out = [];
  for (let i = 0; i < n; i++) {
    const t = (i + 0.5) / n * Math.PI * 2, c = Math.cos(t), s = Math.sin(t);
    const x = cx + hw * Math.sign(c) * Math.abs(c) ** sq, z = cz + (s > 0 ? f : b) * Math.sign(s) * Math.abs(s) ** sq;
    out.push([x, y + yz * (z - cz), z]);
  }
  return out;
}
