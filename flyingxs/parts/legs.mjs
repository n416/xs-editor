const surf = (row, t, out = 0, sq = 0.95) => {
  const [y, hw, f, b] = row, c = Math.cos(t), s = Math.sin(t);
  return [AX(y) - (hw + out) * Math.sign(s) * Math.abs(s) ** sq, y, AZ(y) + (c >= 0 ? f + out : -(b + out)) * Math.abs(c) ** sq];
};
const rowAt = rows => y => {   // 行の間を直線で
  if (y >= rows[0][0]) return [y, ...rows[0].slice(1)];
  for (let k = 0; k < rows.length - 1; k++) {
    const a = rows[k], b = rows[k + 1];
    if (y <= a[0] && y >= b[0]) { const u = (a[0] - y) / (a[0] - b[0]); return [y, ...a.slice(1).map((v, i) => v + (b[i + 1] - v) * u)]; }
  }
  return [y, ...rows.at(-1).slice(1)];
};

// 行を高さの刻み step で細かくし、間を Catmull-Rom でつなぐ（面の丸み：行の所で陰が折れない。review-adv-8）
const densify = (rows, step = 0.04) => {
  const out = [];
  for (let k = 0; k < rows.length - 1; k++) {
    const a = rows[Math.max(0, k - 1)], b = rows[k], c = rows[k + 1], d = rows[Math.min(rows.length - 1, k + 2)];
    const n = Math.max(1, Math.round((b[0] - c[0]) / step));
    for (let i = 0; i < n; i++) {
      const u = i / n, u2 = u * u, u3 = u2 * u;
      out.push(b.map((_, j) => j === 0 ? b[0] + (c[0] - b[0]) * u : 0.5 * (2 * b[j] + (-a[j] + c[j]) * u + (2 * a[j] - 5 * b[j] + 4 * c[j] - d[j]) * u2 + (-a[j] + 3 * b[j] - 3 * c[j] + d[j]) * u3)));
    }
  }
  out.push(rows.at(-1));
  return out;
};

